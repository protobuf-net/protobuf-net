using ProtoBuf.Meta;
using System;
using System.Buffers;
using System.Collections.Generic;
using System.IO;
using Xunit;

namespace ProtoBuf.AotConformance
{
    /// <summary>
    /// The generated write path, driven across a chunk boundary at every offset it can land on.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The raw write ops are span-direct when the leased chunk has room, and fall out-of-line to
    /// the backend's virtual machinery when it does not (notes/nano-writer.md, buffer-core step 2).
    /// The fast arm is what every other test in this assembly exercises, because a real lease is
    /// large; the SLOW arm is reached only when a chunk runs out mid-member, which nothing
    /// exercised at all until this fixture. Shrinking <see cref="TypeModel.BufferSize"/> walks the
    /// boundary through every op in turn - varint, fixed, string, bytes, tag - for every fixture.
    /// </para>
    /// <para>
    /// The stream backend is the reference here rather than ref-emit: <c>DifferentialTests</c>
    /// already pins the generated bytes against the runtime model, so what is being asserted is
    /// that the SAME generated model produces the same bytes however the destination is chunked.
    /// </para>
    /// </remarks>
    public class ChunkBoundaryTests
    {
        /// <summary>
        /// Leases exactly what was asked for and never a byte more, so the boundary falls where
        /// BufferSize says rather than wherever a generous pool happened to put it.
        /// </summary>
        private sealed class ExactBufferWriter : IBufferWriter<byte>
        {
            private readonly MemoryStream _committed = new();
            private byte[] _current = Array.Empty<byte>();

            public byte[] ToArray() => _committed.ToArray();

            public void Advance(int count)
            {
                if (count < 0 || count > _current.Length) throw new ArgumentOutOfRangeException(nameof(count));
                _committed.Write(_current, 0, count);
                _current = Array.Empty<byte>();
            }

            public Memory<byte> GetMemory(int sizeHint = 0) => Lease(sizeHint);
            public Span<byte> GetSpan(int sizeHint = 0) => Lease(sizeHint).Span;

            private Memory<byte> Lease(int sizeHint)
            {
                _current = new byte[sizeHint <= 0 ? 1 : sizeHint];
                return _current;
            }
        }

        // spread so that the prefix-plus-body ops (string, bytes) split at a different point
        // each time. TypeModel.MinimumBufferSize is the smallest value that means anything -
        // below it the property normalises, so smaller entries would silently be one test.
        private static readonly int[] LeaseSizes =
            [128, 129, 131, 137, 149, 160, 181, 192, 224, 256, 320, 512];

        public static IEnumerable<object[]> GetCases() => DifferentialTests.GetCases();

        [Theory, MemberData(nameof(GetCases))]
        public void GeneratedWriteIsChunkingInvariant(string modelTypeName, int index)
        {
            var (model, value) = DifferentialTests.CreateGeneratedCase(modelTypeName, index);

            using var ms = new MemoryStream();
            model.Serialize(ms, value);
            var expected = BitConverter.ToString(ms.ToArray());

            foreach (var lease in LeaseSizes)
            {
                model.BufferSize = lease;
                var bw = new ExactBufferWriter();
                model.Serialize(bw, value);
                Assert.Equal(expected, BitConverter.ToString(bw.ToArray()));
            }
        }
    }
}
