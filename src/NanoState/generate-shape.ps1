# Regenerates ReaderState.cs / WriterState.cs from the *real* ProtoReader.State / ProtoWriter.State
# surfaces, so the shape the rewrite must satisfy is derived rather than guessed. Re-run after
# building protobuf-net.Core (Debug/net8.0) if the State surface moves.
$ErrorActionPreference = 'Stop'
$root = Resolve-Path "$PSScriptRoot\..\.."
$dll = Join-Path $root "src\protobuf-net.Core\bin\Debug\net8.0\protobuf-net.Core.dll"
$asm = [System.Reflection.Assembly]::LoadFrom($dll)

function CSharpName([Type]$t) {
    if ($t.IsByRef) { return CSharpName $t.GetElementType() }
    if ($t.IsGenericParameter) { return $t.Name }
    if ($t.IsArray) { return (CSharpName $t.GetElementType()) + "[]" }
    if ($t.IsGenericType -and $t.GetGenericTypeDefinition().FullName -eq 'System.Nullable`1') {
        return (CSharpName $t.GetGenericArguments()[0]) + "?"
    }
    $map = @{
        'System.Void'='void';'System.Object'='object';'System.String'='string';'System.Boolean'='bool'
        'System.Byte'='byte';'System.SByte'='sbyte';'System.Int16'='short';'System.UInt16'='ushort'
        'System.Int32'='int';'System.UInt32'='uint';'System.Int64'='long';'System.UInt64'='ulong'
        'System.Single'='float';'System.Double'='double';'System.Decimal'='decimal';'System.Char'='char'
        'System.IntPtr'='nint';'System.UIntPtr'='nuint'
    }
    if (-not $t.IsGenericType -and $map.ContainsKey($t.FullName)) { return $map[$t.FullName] }
    $name = if ($t.IsGenericType) { $t.GetGenericTypeDefinition().FullName } else { $t.FullName }
    $name = ($name -split '`')[0] -replace '\+', '.'
    if ($t.IsGenericType) {
        $args = ($t.GetGenericArguments() | ForEach-Object { CSharpName $_ }) -join ', '
        $name = "$name<$args>"
    }
    return "global::$name" -replace 'global::(void|int|string|bool)$', '$1'
}

function ParamDecl([System.Reflection.ParameterInfo]$p) {
    $prefix = ''
    if ($p.ParameterType.IsByRef) {
        if ($p.IsOut) { $prefix = 'out ' }
        elseif ($p.GetCustomAttributes([System.Runtime.CompilerServices.IsReadOnlyAttribute], $false).Count -gt 0) { $prefix = 'in ' }
        else { $prefix = 'ref ' }
    }
    $decl = "$prefix$(CSharpName $p.ParameterType) $($p.Name)"
    if ($p.HasDefaultValue -and -not $p.ParameterType.IsByRef) {
        $decl += ' = ' + $(if ($null -eq $p.DefaultValue) { 'default' }
            elseif ($p.DefaultValue -is [bool]) { $p.DefaultValue.ToString().ToLower() }
            elseif ($p.ParameterType.IsEnum) { 'default' }
            elseif ($p.DefaultValue -is [string]) { '"' + $p.DefaultValue + '"' }
            else { "$($p.DefaultValue)" })
    }
    return $decl
}

function Constraints([System.Reflection.MethodInfo]$m) {
    $result = ''
    foreach ($gp in $m.GetGenericArguments()) {
        $parts = @()
        $attrs = $gp.GenericParameterAttributes
        if ($attrs -band [System.Reflection.GenericParameterAttributes]::ReferenceTypeConstraint) { $parts += 'class' }
        if ($attrs -band [System.Reflection.GenericParameterAttributes]::NotNullableValueTypeConstraint) { $parts += 'struct' }
        foreach ($tc in $gp.GetGenericParameterConstraints()) {
            if ($tc.FullName -ne 'System.ValueType') { $parts += (CSharpName $tc) }
        }
        if (($attrs -band [System.Reflection.GenericParameterAttributes]::DefaultConstructorConstraint) -and
            -not ($attrs -band [System.Reflection.GenericParameterAttributes]::NotNullableValueTypeConstraint)) { $parts += 'new()' }
        if ($parts) { $result += " where $($gp.Name) : $($parts -join ', ')" }
    }
    return $result
}

function IsAccessible([Type]$t) {
    if ($t.IsByRef -or $t.IsArray) { return IsAccessible $t.GetElementType() }
    if ($t.IsGenericParameter) { return $true }
    if ($t.IsGenericType -and -not $t.IsGenericTypeDefinition) {
        if (-not (IsAccessible $t.GetGenericTypeDefinition())) { return $false }
        foreach ($a in $t.GetGenericArguments()) { if (-not (IsAccessible $a)) { return $false } }
        return $true
    }
    if ($t.IsNested) { return $t.IsNestedPublic -and (IsAccessible $t.DeclaringType) }
    return $t.IsPublic
}

# members that have graduated to hand-written partials; regeneration must not resurrect them
$graduated = @{
    'ReaderState' = @('Dispose', 'FieldNumber', 'WireType', 'ReadFieldHeader', 'ReadInt32', 'StartSubItem', 'EndSubItem', 'SkipField')
    'WriterState' = @()
}

function Emit([Type]$state, [string]$structName, [string]$file) {
    $flags = [System.Reflection.BindingFlags]"Public,NonPublic,Instance,Static,DeclaredOnly"
    $sb = [System.Text.StringBuilder]::new()
    [void]$sb.AppendLine(@"
// GENERATED by generate-shape.ps1 from $($state.FullName) - the surface the rewrite must satisfy.
// Bodies all throw: this file exists to nail the *shape*, member by member. Implement by moving
// members out of this file into hand-written partials, so what remains here is the to-do list.
#nullable disable
#pragma warning disable IDE0060 // unused parameters - stubs
using System;
using ProtoBuf;

namespace ProtoBuf.Nano;

public ref partial struct $structName
{
"@)
    foreach ($p in ($state.GetProperties($flags) | Sort-Object Name)) {
        if ($graduated[$structName] -contains $p.Name) {
            [void]$sb.AppendLine("    // $($p.Name): graduated - implemented in $structName.Nano.cs")
            continue
        }
        $access = if ($p.GetMethod -and $p.GetMethod.IsPublic) { 'public' } else { 'internal' }
        $setter = if ($p.SetMethod) { ' set => throw new NotImplementedException();' } else { '' }
        [void]$sb.AppendLine("    $access $(CSharpName $p.PropertyType) $($p.Name) { get => throw new NotImplementedException();$setter }")
    }
    [void]$sb.AppendLine()
    $methods = $state.GetMethods($flags) | Where-Object {
        -not $_.IsSpecialName -and -not $_.IsPrivate -and $_.Name -notmatch '^(Equals|GetHashCode|ToString|GetType)$' `
            -and $_.Name -notmatch '[<>|]' # compiler-lifted local functions have unspeakable names
    } | Sort-Object Name, { $_.GetParameters().Count }
    foreach ($m in $methods) {
        if ($graduated[$structName] -contains $m.Name) {
            [void]$sb.AppendLine("    // $($m.Name): graduated - implemented in $structName.Nano.cs")
            continue
        }
        $access = if ($m.IsPublic) { 'public' } elseif ($m.IsAssembly -or $m.IsFamilyOrAssembly) { 'internal' } else { continue }
        $static = if ($m.IsStatic) { 'static ' } else { '' }
        $generics = ''
        if ($m.IsGenericMethodDefinition) {
            $generics = '<' + (($m.GetGenericArguments() | ForEach-Object Name) -join ', ') + '>'
        }
        $params = ($m.GetParameters() | ForEach-Object { ParamDecl $_ }) -join ', '
        $decl = "$access $static$(CSharpName $m.ReturnType) $($m.Name)$generics($params)$(Constraints $m)"
        $inaccessible = -not (IsAccessible $m.ReturnType)
        foreach ($p in $m.GetParameters()) { if (-not (IsAccessible $p.ParameterType)) { $inaccessible = $true } }
        if ($inaccessible) {
            # the signature names a Core-internal type; still part of the shape, so record it
            [void]$sb.AppendLine("    // INTERNAL-TYPE SIGNATURE (kept for the shape; cannot compile outside Core):")
            [void]$sb.AppendLine("    // $decl")
        } else {
            [void]$sb.AppendLine("    $decl")
            [void]$sb.AppendLine("        => throw new NotImplementedException();")
        }
    }
    [void]$sb.AppendLine("}")
    Set-Content (Join-Path $PSScriptRoot $file) $sb.ToString()
    "$structName : $(@($methods).Count) methods, $($state.GetProperties($flags).Count) properties -> $file"
}

Emit $asm.GetType("ProtoBuf.ProtoReader+State") "ReaderState" "ReaderState.cs"
Emit $asm.GetType("ProtoBuf.ProtoWriter+State") "WriterState" "WriterState.cs"


