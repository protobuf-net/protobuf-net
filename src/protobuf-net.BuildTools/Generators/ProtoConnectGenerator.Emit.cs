#nullable enable
using ProtoBuf.BuildTools.Internal.Connect;
using ProtoBuf.BuildTools.Internal.Grpc;
using System;
using System.Text;

namespace ProtoBuf.BuildTools.Generators
{
    partial class ProtoConnectGenerator
    {
        /// <summary>
        /// Emits the generated half of a <c>[ProtoConnect]</c> container.
        /// </summary>
        /// <remarks>
        /// The target shape is <c>src/AotConnectSmoke/Services.HandWritten.cs</c>, which was written by
        /// hand and reviewed before this existed - see notes/connect/findings.md §14. Two rules from
        /// that review are load-bearing here:
        /// <list type="bullet">
        /// <item>the generated partial restates <b>no</b> accessibility and <b>no</b> <c>static</c>:
        /// both are the consumer's to choose, and a part that restated either would fight or force
        /// them;</item>
        /// <item>every extension method's name carries either the <b>container</b> (operations over all
        /// services) or the <b>contract</b> (operations over one), never a bare generic - a generic
        /// extension is ambiguous between any two containers in scope.</item>
        /// </list>
        /// </remarks>
        private static string Emit(ConnectContainerPlan plan)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>").AppendLine("#nullable enable").AppendLine();

            var indent = 0;
            if (plan.ContainerNamespace is { Length: > 0 } ns)
            {
                sb.Append("namespace ").Append(ns).AppendLine().AppendLine("{");
                indent = 1;
            }

            Line(sb, indent, "[global::System.CodeDom.Compiler.GeneratedCode(\"protobuf-net.BuildTools\", \"1.0\")]");
            // no accessibility and no `static`: the consumer's declaration governs
            Line(sb, indent, $"partial class {plan.ContainerName}");
            Line(sb, indent, "{");

            if (!plan.IsStatic && !plan.DeclaresConstructor)
            {
                Line(sb, indent + 1, "/// <summary>There is nothing to construct: every member here is static.</summary>");
                Line(sb, indent + 1, $"private {plan.ContainerName}() {{ }}");
                sb.AppendLine();
            }

            EmitCreateClient(sb, indent + 1, plan);

            if (HasServer(plan))
            {
                sb.AppendLine();
                EmitRegistration(sb, indent + 1, plan);
                sb.AppendLine();
                EmitBinding(sb, indent + 1, plan);
            }

            foreach (var service in plan.Services)
            {
                sb.AppendLine();
                EmitMethods(sb, indent + 1, service);
                sb.AppendLine();
                EmitClientProxy(sb, indent + 1, service);
                if (service.ImplementationTypeFullName is { Length: > 0 })
                {
                    sb.AppendLine();
                    EmitServerBindings(sb, indent + 1, service);
                }
            }

            Line(sb, indent, "}");

            sb.AppendLine();
            EmitExtensions(sb, indent, plan);

            if (indent == 1) sb.AppendLine("}");
            return sb.ToString();
        }

        private static void EmitCreateClient(StringBuilder sb, int indent, ConnectContainerPlan plan)
        {
            Line(sb, indent, "/// <summary>Creates a client proxy for one of the contracts this container declares.</summary>");
            Line(sb, indent, "public static TService CreateClient<TService>(global::ProtoBuf.Connect.ConnectChannel channel) where TService : class");
            Line(sb, indent, "{");
            foreach (var service in plan.Services)
            {
                Line(sb, indent + 1, $"if (typeof(TService) == typeof({service.InterfaceFullName})) return (TService)(object)new {ProxyName(service)}(channel);");
            }
            Line(sb, indent + 1, "throw new global::System.InvalidOperationException(");
            Line(sb, indent + 2, $"\"No build-time Connect proxy for \" + typeof(TService).FullName + \" in {plan.ContainerName}.\");");
            Line(sb, indent, "}");
        }

        private static void EmitMethods(StringBuilder sb, int indent, GrpcInterfaceModel service)
        {
            Line(sb, indent, $"/// <summary>The method descriptors for <see cref=\"{XmlName(service.InterfaceFullName)}\"/>.</summary>");
            Line(sb, indent, $"private static class {MethodsName(service)}");
            Line(sb, indent, "{");
            Line(sb, indent + 1, $"public const string ServiceName = \"{service.ServiceName}\";");
            sb.AppendLine();
            foreach (var op in service.Operations)
            {
                // written out in full rather than through a helper: a helper would only be expressible
                // if every method shared one request/response pair, which a real contract does not
                Line(sb, indent + 1, $"public static readonly global::ProtoBuf.Connect.ConnectMethod<{op.RequestTypeFullName}, {op.ResponseTypeFullName}> {op.OperationName} =");
                Line(sb, indent + 2, $"new(global::ProtoBuf.Connect.ConnectMethodType.{MethodType(op.Kind)}, ServiceName, \"{op.OperationName}\");");
            }
            Line(sb, indent, "}");
        }

        private static void EmitClientProxy(StringBuilder sb, int indent, GrpcInterfaceModel service)
        {
            Line(sb, indent, "/// <summary>Reached through <c>CreateClient</c>; the caller only ever sees the contract.</summary>");
            Line(sb, indent, $"private sealed class {ProxyName(service)} : {service.InterfaceFullName}");
            Line(sb, indent, "{");
            Line(sb, indent + 1, "private readonly global::ProtoBuf.Connect.ConnectChannel _channel;");
            sb.AppendLine();
            Line(sb, indent + 1, $"public {ProxyName(service)}(global::ProtoBuf.Connect.ConnectChannel channel) => _channel = channel;");

            foreach (var op in service.Operations)
            {
                sb.AppendLine();
                var (options, token) = ContextArguments(op.Context);
                Line(sb, indent + 1, $"public {op.ReturnTypeDisplay} {op.MethodName}({Signature(op)})");
                Line(sb, indent + 2, $"=> _channel.{ChannelCall(op.Kind)}({MethodsName(service)}.{op.OperationName}, {RequestArgument(op)}, {options}, {token});");
            }

            Line(sb, indent, "}");
        }

        /// <summary>
        /// Whether this container hosts anything. A client-only container - every <c>[ProtoService]</c>
        /// naming a contract and no implementation - emits no registration and no binding at all, which
        /// is a genuinely smaller shape rather than a trimmed one.
        /// </summary>
        private static bool HasServer(ConnectContainerPlan plan)
        {
            foreach (var service in plan.Services)
            {
                if (service.ImplementationTypeFullName is { Length: > 0 }) return true;
            }
            return false;
        }

        private static void EmitRegistration(StringBuilder sb, int indent, ConnectContainerPlan plan)
        {
            Line(sb, indent, "/// <summary>Registers the codec and every service implementation this container declares.</summary>");
            Line(sb, indent, "public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddServices(");
            Line(sb, indent + 1, "global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
            Line(sb, indent, "{");
            Line(sb, indent + 1, "AddCodec(services);");
            foreach (var service in plan.Services)
            {
                if (service.ImplementationTypeFullName is not { Length: > 0 } impl) continue;
                Line(sb, indent + 1, $"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddScoped<{impl}>(services);");
            }
            Line(sb, indent + 1, "return services;");
            Line(sb, indent, "}");
            sb.AppendLine();

            Line(sb, indent, "/// <summary>Registers what one service needs: the codec, and that service's implementation.</summary>");
            Line(sb, indent, "public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddService<TService>(");
            Line(sb, indent + 1, "global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
            Line(sb, indent, "{");
            Line(sb, indent + 1, "AddCodec(services);");
            foreach (var service in plan.Services)
            {
                if (service.ImplementationTypeFullName is not { Length: > 0 } impl) continue;
                Line(sb, indent + 1, $"if (typeof(TService) == typeof({service.InterfaceFullName}))");
                Line(sb, indent + 1, "{");
                Line(sb, indent + 2, $"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddScoped<{impl}>(services);");
                Line(sb, indent + 2, "return services;");
                Line(sb, indent + 1, "}");
            }
            Line(sb, indent + 1, "throw new global::System.InvalidOperationException(");
            Line(sb, indent + 2, $"\"No build-time Connect bindings for \" + typeof(TService).FullName + \" in {plan.ContainerName}.\");");
            Line(sb, indent, "}");
            sb.AppendLine();

            Line(sb, indent, "/// <summary>The container-level half of registration: the codec over this container's model.</summary>");
            Line(sb, indent, "/// <remarks>");
            Line(sb, indent, "/// The guard is inside the configure delegate, not around AddConnect: options delegates");
            Line(sb, indent, "/// accumulate and all of them run, so checking at registration time would still add two.");
            Line(sb, indent, "/// </remarks>");
            Line(sb, indent, "private static void AddCodec(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
            Line(sb, indent + 1, "=> global::ProtoBuf.Connect.AspNetCore.ConnectServiceCollectionExtensions.AddConnect(services, static options =>");
            Line(sb, indent + 1, "{");
            Line(sb, indent + 2, "foreach (var existing in options.Codecs) { if (existing.Name == \"proto\") return; }");
            Line(sb, indent + 2, $"options.Codecs.Add(new global::ProtoBuf.Connect.ProtoConnectCodec({plan.ModelTypeFullName}.Instance));");
            Line(sb, indent + 1, "});");
        }

        private static void EmitBinding(StringBuilder sb, int indent, ConnectContainerPlan plan)
        {
            Line(sb, indent, "/// <summary>Maps every service this container declares.</summary>");
            Line(sb, indent, "public static global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder BindServices(");
            Line(sb, indent + 1, "global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder endpoints, string? routingPrefix = null)");
            Line(sb, indent, "{");
            Line(sb, indent + 1, "var builders = new global::System.Collections.Generic.List<global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder>();");
            foreach (var service in plan.Services)
            {
                if (service.ImplementationTypeFullName is not { Length: > 0 }) continue;
                Line(sb, indent + 1, $"builders.Add(BindService<{service.InterfaceFullName}>(endpoints, routingPrefix));");
            }
            Line(sb, indent + 1, "return new CompositeConventionBuilder(builders);");
            Line(sb, indent, "}");
            sb.AppendLine();

            Line(sb, indent, "/// <summary>Maps one service, so conventions can differ between them.</summary>");
            Line(sb, indent, "public static global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder BindService<TService>(");
            Line(sb, indent + 1, "global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder endpoints, string? routingPrefix = null)");
            Line(sb, indent, "{");
            foreach (var service in plan.Services)
            {
                if (service.ImplementationTypeFullName is not { Length: > 0 }) continue;
                Line(sb, indent + 1, $"if (typeof(TService) == typeof({service.InterfaceFullName}))");
                Line(sb, indent + 1, "{");
                Line(sb, indent + 2, $"return global::ProtoBuf.Connect.AspNetCore.ConnectEndpointRouteBuilderExtensions.MapConnectService(endpoints, new {BindingsName(service)}(), routingPrefix);");
                Line(sb, indent + 1, "}");
            }
            Line(sb, indent + 1, "throw new global::System.InvalidOperationException(");
            Line(sb, indent + 2, $"\"No build-time Connect bindings for \" + typeof(TService).FullName + \" in {plan.ContainerName}.\");");
            Line(sb, indent, "}");
            sb.AppendLine();

            Line(sb, indent, "/// <summary>Applies conventions across several services' endpoints at once.</summary>");
            Line(sb, indent, "private sealed class CompositeConventionBuilder : global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder");
            Line(sb, indent, "{");
            Line(sb, indent + 1, "private readonly global::System.Collections.Generic.List<global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder> _inner;");
            Line(sb, indent + 1, "public CompositeConventionBuilder(global::System.Collections.Generic.List<global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder> inner) => _inner = inner;");
            Line(sb, indent + 1, "public void Add(global::System.Action<global::Microsoft.AspNetCore.Builder.EndpointBuilder> convention)");
            Line(sb, indent + 2, "{ foreach (var builder in _inner) builder.Add(convention); }");
            Line(sb, indent + 1, "public void Finally(global::System.Action<global::Microsoft.AspNetCore.Builder.EndpointBuilder> finallyConvention)");
            Line(sb, indent + 2, "{ foreach (var builder in _inner) builder.Finally(finallyConvention); }");
            Line(sb, indent, "}");
        }

        private static void EmitServerBindings(StringBuilder sb, int indent, GrpcInterfaceModel service)
        {
            var impl = service.ImplementationTypeFullName;
            Line(sb, indent, "/// <summary>Server bindings: one typed delegate per method, no reflection.</summary>");
            Line(sb, indent, $"private sealed class {BindingsName(service)} : global::ProtoBuf.Connect.AspNetCore.IConnectServiceBinder<{impl}>");
            Line(sb, indent, "{");
            Line(sb, indent + 1, $"public void Bind(global::ProtoBuf.Connect.AspNetCore.ConnectServiceBinderContext<{impl}> context)");
            Line(sb, indent + 1, "{");
            foreach (var op in service.Operations)
            {
                var call = $"service.{op.MethodName}({BinderArguments(op)})";
                Line(sb, indent + 2, $"context.{BinderAdd(op.Kind)}({MethodsName(service)}.{op.OperationName},");
                Line(sb, indent + 3, $"static (service, {BinderRequestName(op.Kind)}, ctx) => {call});");
            }
            Line(sb, indent + 1, "}");
            Line(sb, indent, "}");
        }

        private static string BinderAdd(GrpcMethodKind kind) => kind switch
        {
            GrpcMethodKind.ServerStreaming => "AddServerStreamingMethod",
            GrpcMethodKind.ClientStreaming => "AddClientStreamingMethod",
            GrpcMethodKind.DuplexStreaming => "AddDuplexMethod",
            _ => "AddUnaryMethod",
        };

        private static string BinderRequestName(GrpcMethodKind kind)
            => kind is GrpcMethodKind.ClientStreaming or GrpcMethodKind.DuplexStreaming ? "requests" : "request";

        /// <summary>
        /// The arguments the service method is called with on the server.
        /// </summary>
        /// <remarks>
        /// <c>new CallContext(service, ctx)</c> is the same line <c>GrpcProxyGenerator</c> emits, and it
        /// is what keeps protobuf-net.Grpc out of <c>protobuf-net.Connect.AspNetCore</c>: the runtime
        /// takes a plain <c>ServerCallContext</c> and stays vocabulary-agnostic.
        /// </remarks>
        private static string BinderArguments(GrpcOperationModel op) => op.Context switch
        {
            GrpcContextKind.CallContext => $"{BinderRequestName(op.Kind)}, new global::ProtoBuf.Grpc.CallContext(service, ctx)",
            GrpcContextKind.CancellationToken => $"{BinderRequestName(op.Kind)}, ctx.CancellationToken",
            _ => BinderRequestName(op.Kind),
        };

        private static string BindingsName(GrpcInterfaceModel service) => ContractName(service) + "ServerBindings";

        private static void EmitExtensions(StringBuilder sb, int indent, ConnectContainerPlan plan)
        {
            Line(sb, indent, "/// <summary>");
            Line(sb, indent, $"/// The fluent surface for <see cref=\"{plan.ContainerName}\"/>, emitted alongside it.");
            Line(sb, indent, "/// </summary>");
            Line(sb, indent, "/// <remarks>");
            Line(sb, indent, "/// Always emitted, whether or not the container is <c>static</c>, so the fluent form does not");
            Line(sb, indent, "/// depend on how the consumer declared their half. Accessibility mirrors the container's.");
            Line(sb, indent, "/// </remarks>");
            Line(sb, indent, "[global::System.CodeDom.Compiler.GeneratedCode(\"protobuf-net.BuildTools\", \"1.0\")]");
            Line(sb, indent, $"{plan.Accessibility} static class {plan.ContainerName}Extensions");
            Line(sb, indent, "{");

            if (HasServer(plan))
            {
                // named after the CONTAINER, so these cannot collide however many containers exist
                Line(sb, indent + 1, $"/// <summary>Registers everything <see cref=\"{plan.ContainerName}\"/> declares.</summary>");
                Line(sb, indent + 1, $"public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection Add{plan.ContainerName}(");
                Line(sb, indent + 2, "this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
                Line(sb, indent + 2, $"=> {plan.ContainerName}.AddServices(services);");
                sb.AppendLine();
                Line(sb, indent + 1, $"/// <summary>Maps every service <see cref=\"{plan.ContainerName}\"/> declares.</summary>");
                Line(sb, indent + 1, $"public static global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder Bind{plan.ContainerName}(");
                Line(sb, indent + 2, "this global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder endpoints, string? routingPrefix = null)");
                Line(sb, indent + 2, $"=> {plan.ContainerName}.BindServices(endpoints, routingPrefix);");

                foreach (var service in plan.Services)
                {
                    if (service.ImplementationTypeFullName is not { Length: > 0 }) continue;
                    var name = ContractName(service);
                    sb.AppendLine();
                    Line(sb, indent + 1, $"/// <summary>Registers <see cref=\"{XmlName(service.InterfaceFullName)}\"/>'s implementation, and the codec.</summary>");
                    Line(sb, indent + 1, $"public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection Add{name}(");
                    Line(sb, indent + 2, "this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
                    Line(sb, indent + 2, $"=> {plan.ContainerName}.AddService<{service.InterfaceFullName}>(services);");
                    sb.AppendLine();
                    Line(sb, indent + 1, $"/// <summary>Maps <see cref=\"{XmlName(service.InterfaceFullName)}\"/> alone.</summary>");
                    Line(sb, indent + 1, $"public static global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder Bind{name}(");
                    Line(sb, indent + 2, "this global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder endpoints, string? routingPrefix = null)");
                    Line(sb, indent + 2, $"=> {plan.ContainerName}.BindService<{service.InterfaceFullName}>(endpoints, routingPrefix);");
                }
            }

            var first = !HasServer(plan);
            foreach (var service in plan.Services)
            {
                if (!first) sb.AppendLine();
                first = false;

                // named after the CONTRACT, never generic: a generic extension on ConnectChannel is
                // ambiguous between any two containers in scope, where this one can only collide with
                // another container declaring the same contract
                Line(sb, indent + 1, $"/// <summary>Creates a <see cref=\"{XmlName(service.InterfaceFullName)}\"/> client over the channel.</summary>");
                Line(sb, indent + 1, $"public static {service.InterfaceFullName} {ContractName(service)}Client(this global::ProtoBuf.Connect.ConnectChannel channel)");
                Line(sb, indent + 2, $"=> {plan.ContainerName}.CreateClient<{service.InterfaceFullName}>(channel);");
            }

            Line(sb, indent, "}");
        }

        private static string MethodType(GrpcMethodKind kind) => kind switch
        {
            GrpcMethodKind.ServerStreaming => "ServerStreaming",
            GrpcMethodKind.ClientStreaming => "ClientStreaming",
            GrpcMethodKind.DuplexStreaming => "DuplexStreaming",
            _ => "Unary",
        };

        private static string ChannelCall(GrpcMethodKind kind) => kind switch
        {
            GrpcMethodKind.ServerStreaming => "ServerStreaming",
            GrpcMethodKind.ClientStreaming => "ClientStreamingAsync",
            GrpcMethodKind.DuplexStreaming => "Duplex",
            _ => "UnaryAsync",
        };

        /// <summary>
        /// How the contract's context parameter becomes transport options and a token.
        /// </summary>
        /// <remarks>
        /// The conversion is library code - <c>ConnectCallOptions.From(in CallOptions)</c> - rather than
        /// something emitted per assembly, because it depends on nothing about the service.
        /// </remarks>
        private static (string Options, string Token) ContextArguments(GrpcContextKind context) => context switch
        {
            GrpcContextKind.CallContext =>
                ("global::ProtoBuf.Connect.ConnectCallOptions.From(context.CallOptions)", "context.CancellationToken"),
            GrpcContextKind.CancellationToken => ("null", "cancellationToken"),
            _ => ("null", "default"),
        };

        private static string Signature(GrpcOperationModel op)
        {
            var sb = new StringBuilder();
            var first = true;
            foreach (var parameter in op.Parameters)
            {
                if (!first) sb.Append(", ");
                first = false;
                sb.Append(parameter.TypeDisplay).Append(' ').Append(parameter.Name);
                if (parameter.TypeDisplay.Contains("CallContext")) sb.Append(" = default");
                else if (parameter.TypeDisplay.Contains("CancellationToken")) sb.Append(" = default");
            }
            return sb.ToString();
        }

        private static string RequestArgument(GrpcOperationModel op)
        {
            foreach (var parameter in op.Parameters)
            {
                if (!parameter.TypeDisplay.Contains("CallContext") && !parameter.TypeDisplay.Contains("CancellationToken"))
                {
                    return parameter.Name;
                }
            }
            return "default!";
        }

        private static string MethodsName(GrpcInterfaceModel service) => ContractName(service);

        private static string ProxyName(GrpcInterfaceModel service) => ContractName(service) + "ClientProxy";

        /// <summary>
        /// The contract's simple name, with the conventional leading <c>I</c> dropped.
        /// </summary>
        /// <remarks>
        /// Simple rather than fully qualified because the generator sees every contract in the
        /// container, so it can qualify only on collision. <c>GrpcProxyGenerator</c> qualifies
        /// unconditionally, which is safe but reads badly in the common case.
        /// </remarks>
        private static string ContractName(GrpcInterfaceModel service)
        {
            var full = service.InterfaceFullName;
            var dot = full.LastIndexOf('.');
            var simple = dot >= 0 ? full.Substring(dot + 1) : full;
            return simple.Length > 1 && simple[0] == 'I' && char.IsUpper(simple[1]) ? simple.Substring(1) : simple;
        }

        private static string XmlName(string fullName) => fullName.Replace("global::", "");

        private static void Line(StringBuilder sb, int indent, string text)
            => sb.Append(' ', indent * 4).AppendLine(text);
    }
