#nullable enable
using ProtoBuf.BuildTools.Internal.Aot;
using System.Globalization;
using System.Text;

namespace ProtoBuf.BuildTools.Generators
{
    partial class ProtoModelGenerator
    {
        private const string Serializers = "global::ProtoBuf.Serializers";
        private const string Features = Serializers + ".SerializerFeatures";
        private const string ServicesTypeName = "ProtoBufGeneratedServices";

        /// <summary>
        /// Render a plan as the partial half of the user's model class.
        /// </summary>
        /// <remarks>
        /// The shape here is copied from what ref-emit produces for the same contracts (see
        /// <c>src/AotRefGen</c>), rather than invented; the differences are deliberate - a nested
        /// services type rather than a mangled top-level one, and real explicit-interface members.
        /// </remarks>
        private static string Emit(ProtoModelPlan plan)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>")
              .AppendLine("#nullable disable")
              .AppendLine("#pragma warning disable CS1591")
              .AppendLine();

            const int indent = 0;
            if (plan.Namespace is not null)
            {
                sb.AppendLine($"namespace {plan.Namespace};").AppendLine();
            }

            Line(sb, indent, $"partial class {plan.TypeName}");
            Line(sb, indent, "{");

            // TODO: the base declares [DynamicallyAccessedMembers(DynamicAccess.ContractType)] on T,
            // but DynamicAccess is internal to protobuf-net so we cannot restate it here; confirm
            // against a real PublishAot build whether the override needs its own annotation
            Line(sb, indent + 1, $"protected sealed override {Serializers}.ISerializer<T> GetSerializer<T>()");
            Line(sb, indent + 2, $"=> {Serializers}.SerializerCache.Get<{ServicesTypeName}, T>();");
            sb.AppendLine();

            Line(sb, indent + 1, $"private sealed class {ServicesTypeName}");
            var prefix = ':';
            foreach (var contract in plan.Contracts)
            {
                Line(sb, indent + 2, $"{prefix} {Serializers}.ISerializer<{contract.TypeName}>");
                prefix = ',';
            }
            Line(sb, indent + 1, "{");

            var first = true;
            foreach (var contract in plan.Contracts)
            {
                if (!first) sb.AppendLine();
                first = false;
                EmitContract(sb, indent + 2, contract);
            }

            Line(sb, indent + 1, "}");
            Line(sb, indent, "}");
            return sb.ToString();
        }

        private static void EmitContract(StringBuilder sb, int indent, ProtoContractPlan contract)
        {
            var self = $"{Serializers}.ISerializer<{contract.TypeName}>";

            Line(sb, indent, $"{Features} {self}.Features");
            Line(sb, indent + 1, $"=> {Features}.CategoryMessage | {Features}.WireTypeString;");
            sb.AppendLine();

            Line(sb, indent, $"{contract.TypeName} {self}.Read(ref global::ProtoBuf.ProtoReader.State state, {contract.TypeName} value)");
            Line(sb, indent, "{");
            Line(sb, indent + 1, $"value ??= new {contract.TypeName}();");
            Line(sb, indent + 1, "int field;");
            Line(sb, indent + 1, "while ((field = state.ReadFieldHeader()) > 0)");
            Line(sb, indent + 1, "{");
            Line(sb, indent + 2, "switch (field)");
            Line(sb, indent + 2, "{");
            foreach (var member in contract.Members)
            {
                var number = member.FieldNumber.ToString(CultureInfo.InvariantCulture);
                Line(sb, indent + 3, $"case {number}:");
                Line(sb, indent + 3, "{");
                switch (member.Kind)
                {
                    case ProtoMemberKind.Int32:
                        Line(sb, indent + 4, $"value.{member.Name} = state.ReadInt32();");
                        break;
                    case ProtoMemberKind.String:
                        // a null string leaves the existing value alone, matching ref-emit
                        Line(sb, indent + 4, $"var tmp{number} = state.ReadString();");
                        Line(sb, indent + 4, $"if (tmp{number} != null) value.{member.Name} = tmp{number};");
                        break;
                    case ProtoMemberKind.Message:
                        // the *existing* value is passed in, so repeated occurrences merge rather
                        // than replace; and the category is Repeated, not Message
                        Line(sb, indent + 4, $"var tmp{number} = value.{member.Name};");
                        Line(sb, indent + 4, $"tmp{number} = state.ReadMessage<{member.TypeName}>({Features}.CategoryRepeated, tmp{number}, this);");
                        Line(sb, indent + 4, $"if (tmp{number} != null) value.{member.Name} = tmp{number};");
                        break;
                }
                Line(sb, indent + 4, "break;");
                Line(sb, indent + 3, "}");
            }
            Line(sb, indent + 3, "default:");
            Line(sb, indent + 4, "state.SkipField();");
            Line(sb, indent + 4, "break;");
            Line(sb, indent + 2, "}");
            Line(sb, indent + 1, "}");
            Line(sb, indent + 1, "return value;");
            Line(sb, indent, "}");
            sb.AppendLine();

            Line(sb, indent, $"void {self}.Write(ref global::ProtoBuf.ProtoWriter.State state, {contract.TypeName} value)");
            Line(sb, indent, "{");
            Line(sb, indent + 1, "global::ProtoBuf.Meta.TypeModel.ThrowUnexpectedSubtype(value);");
            foreach (var member in contract.Members)
            {
                var number = member.FieldNumber.ToString(CultureInfo.InvariantCulture);
                // hoist to a local, as ref-emit does; the member could be a computed property
                Line(sb, indent + 1, $"var tmp{number} = value.{member.Name};");
                switch (member.Kind)
                {
                    case ProtoMemberKind.Int32:
                        Line(sb, indent + 1, $"if (tmp{number} != 0) state.WriteInt32Varint({number}, tmp{number});");
                        break;
                    case ProtoMemberKind.String:
                        // no null test: WriteString(int, string) skips nulls itself
                        Line(sb, indent + 1, $"state.WriteString({number}, tmp{number});");
                        break;
                    case ProtoMemberKind.Message:
                        // likewise WriteMessage(int, ...) skips nulls itself
                        Line(sb, indent + 1, $"state.WriteMessage<{member.TypeName}>({number}, {Features}.CategoryRepeated, tmp{number}, this);");
                        break;
                }
            }
            Line(sb, indent, "}");
        }

        private static void Line(StringBuilder sb, int indent, string text)
            => sb.Append(' ', indent * 4).AppendLine(text);
    }
}
