#nullable enable
using Microsoft.CodeAnalysis.CSharp;
using ProtoBuf.BuildTools.Internal.Aot;
using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace ProtoBuf.BuildTools.Generators
{
    partial class ProtoModelGenerator
    {
        private const string Serializers = "global::ProtoBuf.Serializers";
        private const string Features = Serializers + ".SerializerFeatures";
        private const string ServicesTypeName = "ProtoBufGeneratedServices";

        private const string MemberTypes = "global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes";

        /// <summary>Mirrors <c>ProtoBuf.Internal.DynamicAccess.ContractType</c>, which is internal.</summary>
        private const string DynamicallyAccessedMembers
            = "global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMembers("
            + MemberTypes + ".PublicConstructors | " + MemberTypes + ".NonPublicConstructors | "
            + MemberTypes + ".PublicParameterlessConstructor | "
            + MemberTypes + ".PublicProperties | " + MemberTypes + ".NonPublicProperties | "
            + MemberTypes + ".PublicFields | " + MemberTypes + ".NonPublicFields | "
            + MemberTypes + ".PublicMethods | " + MemberTypes + ".NonPublicMethods | "
            + MemberTypes + ".PublicNestedTypes | " + MemberTypes + ".NonPublicNestedTypes)";

        /// <summary>
        /// Render a plan as the partial half of the user's model class.
        /// </summary>
        /// <remarks>
        /// The shape here is copied from what ref-emit produces for the same contracts (see
        /// <c>src/AotRefGen</c>), rather than invented; the differences are deliberate - a nested
        /// services type rather than a mangled top-level one, and real explicit-interface members.
        /// </remarks>
        internal static string Emit(ProtoModelPlan plan)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");

            // extern alias must precede everything except comments - before #nullable, before any
            // using. Every alias in the compilation is declared, not just the ones used: an unused
            // one is legal, while one naming a reference that does not carry it is CS0430, so the
            // compilation's own set is exactly the safe set. See ProtoModelGenerator.Aliases.cs.
            foreach (var alias in plan.Aliases)
            {
                sb.AppendLine($"extern alias {alias};");
            }

            sb.AppendLine("#nullable disable")
              .AppendLine("#pragma warning disable CS1591")
              // the raw reader surface is [Experimental("PBN9002")] while the writer arc may
              // still reshape it; generated code is the intended caller, so it carries its own
              // suppression rather than asking every consumer to
              .AppendLine("#pragma warning disable PBN9002")
              .AppendLine();

            const int indent = 0;
            if (plan.Namespace is not null)
            {
                sb.AppendLine($"namespace {plan.Namespace};").AppendLine();
            }

            Line(sb, indent, $"partial class {plan.TypeName}");
            Line(sb, indent, "{");

            // A shared instance, because a TypeModel is a cache: it is meant to be built once and
            // reused, and without somewhere obvious to put it people write `new MyModel()` per call.
            // It also gives PBN3010's fixer something to name when nothing is in scope, which is the
            // common case for a codebase part-way through migrating.
            //
            // Suppressed if the consumer's half of the partial already declares `Instance` (CS0102),
            // or has no accessible parameterless constructor to call.
            if (plan.EmitConstructor)
            {
                // removes the implicit public constructor, so `new MyModel()` no longer compiles and
                // Instance is the obvious route. protected rather than private where the type is not
                // sealed, or nothing could derive from it. Declaring any constructor opts out.
                var accessibility = plan.IsSealed ? "private" : "protected";
                Line(sb, indent + 1, $"/// <summary>Use <see cref=\"Instance\"/>; a <c>TypeModel</c>"
                    + " is a cache, and is intended to be shared rather than constructed per use.</summary>");
                Line(sb, indent + 1, $"{accessibility} {plan.TypeName}() {{ }}");
                sb.AppendLine();
            }

            if (plan.EmitInstance)
            {
                Line(sb, indent + 1, "/// <summary>A shared instance of this model; a <c>TypeModel</c> is"
                    + " thread-safe and is intended to be reused.</summary>");
                Line(sb, indent + 1, $"public static {plan.TypeName} Instance {{ get; }} = new {plan.TypeName}();");
                sb.AppendLine();
            }

            // the base declares [DynamicallyAccessedMembers(DynamicAccess.ContractType)] on T, and an
            // override must restate it exactly or trim analysis reports IL2095. DynamicAccess is
            // internal to protobuf-net, so the flags are spelled out; keep them in step with
            // protobuf-net.Core/Internal/DynamicallyAccessedMembersAttribute.cs. src/AotSmoke is what
            // catches any drift, since IL2095 reappears the moment the two disagree.
            var typeParameter = plan.AnnotateTrimming ? $"[{DynamicallyAccessedMembers}] T" : "T";
            Line(sb, indent + 1, $"protected sealed override {Serializers}.ISerializer<T> GetSerializer<{typeParameter}>()");
            Line(sb, indent + 2, $"=> {Serializers}.SerializerCache.Get<{ServicesTypeName}, T>();");
            sb.AppendLine();

            // PER-CONTRACT TYPED ENTRY POINTS (gap B39). A non-generic overload beats
            // TypeModel.Serialize<T> at any call site naming a concrete type, and skips what that
            // path re-decides per call: a TypeHelper<T>.ValueChecker indirection for the null test,
            // and TryGetSerializer<T> resolution. Measured at ~28ns a call, which is a third of
            // Google.Protobuf's ENTIRE time on a small payload and invisible on a large one.
            //
            // It stops at SerializeRoot rather than going lower, deliberately: CheckClear and
            // Abandon are internal, so generated code cannot reproduce the root sequence's
            // guarantees, and skipping them to save a branch would trade correctness for noise.
            //
            // Emitted for every contract we implement rather than only for the declared seeds -
            // any contract is a legal root, and "seed" is about model closure, not about what a
            // consumer may serialize. Proxied contracts are excluded: their serializer is
            // hand-written and may not even be message-category, so the root framing is not ours
            // to assume.
            if (plan.EmitTypedSerialize)
            {
                foreach (var contract in plan.Contracts)
                {
                    if (contract.ExternalSerializerTypeName is not null) continue;
                    // NO null short-circuit here. It looks free, and it is not: on a SURROGATED
                    // contract `IsValueType` describes the surrogate while TypeName is the
                    // underlying type, so `value is null` was emitted against structs like Ticks
                    // and DateTimeOffset (CS0037). It is also unnecessary - WriteAsRoot already
                    // tests TypeHelper<T>.CanBeNull and writes nothing, and SerializeRoot then
                    // returns after-before, which is 0. Same answer, one fewer thing to get wrong.
                    foreach (var destination in new[] { "System.IO.Stream", "System.Buffers.IBufferWriter<byte>" })
                    {
                        // no cref on the contract type: a closed generic renders as Wrapper<int>,
                        // and the angle brackets would have to be escaped for XML doc comments
                        Line(sb, indent + 1, "/// <summary>Serializes the supplied value.</summary>");
                        Line(sb, indent + 1, "/// <remarks>Prefer this to the generic <c>Serialize&lt;T&gt;</c>:"
                            + " it resolves the serializer at compile time rather than per call.</remarks>");
                        Line(sb, indent + 1, $"public long Serialize(global::{destination} destination,"
                            + $" {contract.TypeName} value, object userState = null)");
                        Line(sb, indent + 1, "{");
                        Line(sb, indent + 2, "var state = global::ProtoBuf.ProtoWriter.State.Create(destination, this, userState);");
                        Line(sb, indent + 2, "try");
                        Line(sb, indent + 2, "{");
                        Line(sb, indent + 3, $"return state.SerializeRoot<{contract.TypeName}>("
                            + $"value, GetSerializer<{contract.TypeName}>());");
                        Line(sb, indent + 2, "}");
                        Line(sb, indent + 2, "finally");
                        Line(sb, indent + 2, "{");
                        Line(sb, indent + 3, "state.Dispose();");
                        Line(sb, indent + 2, "}");
                        Line(sb, indent + 1, "}");
                        sb.AppendLine();
                    }
                }
            }

            // write-side: the contracts whose serialized SIZE is computable by pure arithmetic
            // (a generated Measure_ static), which is what lets a message member emit an exact
            // length prefix and call the target's RawWrite_ directly, instead of the stateful
            // engine's reserve-and-patch. Unlike read eligibility this NEEDS a fixed point:
            // there is no legacy-mode arm inside arithmetic, so one unmeasurable member takes
            // the whole contract out, and a dropped target takes its referrers' measures with
            // it (they keep their raw statements; only the measure-first message shape needs
            // the set). Keyed to the plan rather than a bare name set because the emit sites
            // need the TARGET's IsValueType to shape the null handling. Computed before the
            // interface list, because a measurable contract declares IMeasuringSerializer.
            var measurable = new Dictionary<string, ProtoContractPlan>();
            if (plan.RawWriter)
            {
                foreach (var contract in plan.Contracts)
                {
                    if (RawMeasurableShape(contract)) measurable[contract.TypeName] = contract;
                }
                bool changed;
                do
                {
                    changed = false;
                    foreach (var contract in plan.Contracts)
                    {
                        if (measurable.ContainsKey(contract.TypeName)
                            && contract.Members.Any(m => RawMemberMeasureBlocked(m, measurable, plan.ListAsSpan, plan.ImmutableArrayAsSpan)))
                        {
                            measurable.Remove(contract.TypeName);
                            changed = true;
                        }
                    }
                } while (changed);
            }

            // Which contracts' RawWrite_ actually READS a slot, transitively. A grouped sub-message
            // carries no length, so a fully-grouped tree consumes none at all - and must not be
            // given an eager measure pass it has no use for. That is not a micro-optimisation: gap
            // B35 is precisely the finding that delimited writes need NO measure, and emitting one
            // unconditionally measured 2,453ns -> 3,934ns on a 512-wide grouped graph before this
            // was put back. Transitive because the root's measure is what fills the slots for the
            // whole sub-tree the write walks, so ANY consumer below it makes the root a consumer.
            var slotConsumers = new HashSet<string>();
            if (plan.RawWriter)
            {
                bool grew;
                do
                {
                    grew = false;
                    foreach (var contract in plan.Contracts)
                    {
                        if (slotConsumers.Contains(contract.TypeName)) continue;
                        foreach (var member in contract.Members)
                        {
                            var unary = RawNativeMessageTarget(member, measurable);
                            var repeated = RawRepeatedMessageTarget(member, measurable);
                            var target = unary ?? repeated;
                            if (target is null) continue;
                            // a length-prefixed site reads a slot; a grouped one does not, but its
                            // body is still walked, so a consumer below it still counts
                            if (member.DataFormat != ProtoDataFormat.Group
                                || slotConsumers.Contains(target.TypeName))
                            {
                                slotConsumers.Add(contract.TypeName);
                                grew = true;
                                break;
                            }
                        }
                    }
                } while (grew);
            }

            Line(sb, indent + 1, $"private sealed class {ServicesTypeName}");
            var prefix = ':';
            foreach (var contract in plan.Contracts)
            {
                // a contract with a hand-written serializer is *proxied*, never implemented;
                // a measurable one declares the measuring shape (which includes ISerializer),
                // handing the classic engine's measure hook the Measure_ arithmetic
                Line(sb, indent + 2, contract.ExternalSerializerTypeName is not null
                    ? $"{prefix} {Serializers}.ISerializerProxy<{contract.TypeName}>"
                    : measurable.ContainsKey(contract.TypeName)
                        ? $"{prefix} {Serializers}.IMeasuringSerializer<{contract.TypeName}>"
                        : $"{prefix} {Serializers}.ISerializer<{contract.TypeName}>");
                prefix = ',';
                if (contract.RootTypeName is not null)
                {
                    Line(sb, indent + 2, $", {Serializers}.ISubTypeSerializer<{contract.TypeName}>");
                }
                if (contract.SkipConstructor)
                {
                    Line(sb, indent + 2, $", {Serializers}.IFactory<{contract.TypeName}>");
                }
            }
            foreach (var enumType in EnumProxies(plan))
            {
                Line(sb, indent + 2, $", {Serializers}.ISerializerProxy<{enumType.Key}>");
                Line(sb, indent + 2, $", {Serializers}.ISerializerProxy<{enumType.Key}?>");
            }
            foreach (var collection in CollectionProxies(plan))
            {
                Line(sb, indent + 2, $", {Serializers}.ISerializerProxy<{collection.Key}>");
            }
            Line(sb, indent + 1, "{");

            EmitExternalCategoryAsserts(sb, indent + 2, plan);

            // raw-read eligibility is CONTRACT-level only (shape and callbacks): any member the
            // raw pass has no native form for takes a legacy-mode arm inside the raw body
            // instead of costing the whole contract, so there is no cascade - a message member
            // whose target is not raw-eligible reads through state.ReadMessage exactly as the
            // classic body would, and only a NATIVE message member emits the direct static call
            // (which is why the member classifier consults this set)
            var rawSet = new HashSet<string>();
            var rawReasons = new Dictionary<string, string>();
            // the DIRECT-callable subset: a hierarchy layer is raw but its static is
            // RawReadSub_ over SubTypeState, so a native message member cannot call it
            // directly - members targeting one go legacy-mode (ReadMessage resolves the
            // proxy through the model, which routes to the root's RawReadSub anyway)
            var rawCallable = new HashSet<string>();
            if (plan.RawReader)
            {
                foreach (var contract in plan.Contracts)
                {
                    if (RawReadEligible(contract, out var reason))
                    {
                        rawSet.Add(contract.TypeName);
                        if (contract.RootTypeName is null && contract.SubTypes.Count == 0)
                        {
                            rawCallable.Add(contract.TypeName);
                        }
                    }
                    else rawReasons[contract.TypeName] = reason!;
                }
                // a legacy-mode member arm runs inside a STATIC RawRead_ body, where `this`
                // cannot appear - the shared instance stands in as the sub-serializer argument.
                // The serializers are stateless, so a second instance beside SerializerCache's
                // is only a second run of the Debug-only category asserts. A raw hierarchy
                // layer needs it too: the sub-type narrowing passes it as ISubTypeSerializer.
                if (plan.Contracts.Any(c => rawSet.Contains(c.TypeName)
                    && (c.SubTypes.Count != 0
                        || c.Members.Any(m => RawMemberFallbackReason(m, rawCallable) is not null))))
                {
                    Line(sb, indent + 2, $"private static readonly {ServicesTypeName} s_default = new {ServicesTypeName}();");
                    sb.AppendLine();
                }
                if (plan.Contracts.Any(c => rawSet.Contains(c.TypeName)
                    && c.Members.Any(m => m.Repeated.Factory == "CreateVector"
                        && RawMemberFallbackReason(m, rawCallable) is null)))
                {
                    // append-merge for ARRAY members: a new array per field occurrence, existing
                    // content first - ref-emit's vector semantics, which the merge gate holds us to
                    Line(sb, indent + 2, "private static T[] ArrayAppend<T>(T[] value, global::System.Collections.Generic.List<T> extra)");
                    Line(sb, indent + 2, "{");
                    Line(sb, indent + 3, "if (value is null || value.Length == 0) return extra.ToArray();");
                    Line(sb, indent + 3, "var result = new T[value.Length + extra.Count];");
                    Line(sb, indent + 3, "value.CopyTo(result, 0);");
                    Line(sb, indent + 3, "extra.CopyTo(result, value.Length);");
                    Line(sb, indent + 3, "return result;");
                    Line(sb, indent + 2, "}");
                    sb.AppendLine();
                    Line(sb, indent + 2, "private static T[] ArrayAppend<T>(T[] value, T extra)");
                    Line(sb, indent + 2, "{");
                    Line(sb, indent + 3, "var offset = value?.Length ?? 0;");
                    Line(sb, indent + 3, "var result = new T[offset + 1];");
                    Line(sb, indent + 3, "value?.CopyTo(result, 0);");
                    Line(sb, indent + 3, "result[offset] = extra;");
                    Line(sb, indent + 3, "return result;");
                    Line(sb, indent + 2, "}");
                    sb.AppendLine();
                }
            }

            var contracts = new StringBuilder();
            var first = true;
            foreach (var contract in plan.Contracts)
            {
                if (!first) contracts.AppendLine();
                first = false;
                var raw = rawSet.Contains(contract.TypeName);
                EmitContract(contracts, indent + 2, contract, raw, plan.RawWriter, plan.ListAsSpan, plan.ImmutableArrayAsSpan, measurable, slotConsumers);
                if (raw)
                {
                    EmitRawRead(contracts, indent + 2, contract, rawCallable);
                }
                else if (plan.RawReader && rawReasons.TryGetValue(contract.TypeName, out var why))
                {
                    // say WHY in the output itself: an absence and an oversight look identical
                    // otherwise, which this branch has been burned by before
                    contracts.AppendLine();
                    Line(contracts, indent + 2, $"// raw read pass: skipped - {why}");
                }
            }
            if (contracts.ToString().IndexOf(DriftAssert, StringComparison.Ordinal) >= 0)
            {
                EmitLengthDriftHelpers(sb, indent + 2);
                sb.AppendLine();
            }
            sb.Append(contracts);

            EmitEnumProxies(sb, indent + 2, plan);
            EmitCollectionProxies(sb, indent + 2, plan);
            EmitAccessors(sb, indent + 2, plan);

            Line(sb, indent + 1, "}");
            Line(sb, indent, "}");
            return sb.ToString();
        }

        /// <summary>
        /// The raw read pass: the optimized read emission against the raw reader surface (see
        /// notes/nano-core.md), symbol-gated on ProtoReader.State exposing ReadRawTag. This is the
        /// LIVE read path for an eligible contract - ISerializer&lt;T&gt;.Read proxies here - and
        /// a sibling NATIVE message member calls the target's static directly, skipping the
        /// interface dispatch. public static deliberately: static IS the direct-call design.
        /// A member with no native form takes a LEGACY-MODE arm - StashTag hands the consumed tag
        /// to the stateful surface and the classic member body runs verbatim - so one slow member
        /// costs itself, not the contract; only contract-level shape falls back to the classic
        /// body, with a comment in the output saying why.
        /// </summary>
        private static void EmitRawRead(StringBuilder sb, int indent, ProtoContractPlan contract,
            HashSet<string> rawSet)
        {
            // classify once: null = native form; a reason string = legacy-mode arm, and the
            // reason is emitted as a breadcrumb so the census can tally what is still stateful
            var fallback = new Dictionary<string, string>();
            foreach (var member in contract.Members)
            {
                if (RawMemberFallbackReason(member, rawSet) is { } why) fallback[member.Name] = why;
            }
            // the stateful repeated/map engines park run-terminating headers in the pending slot,
            // so a loop that mixes stateful members must drain it at every dispatch read; a pure
            // native loop never populates it and keeps the cheaper read
            var readTag = fallback.Count != 0 ? "state.ReadRawTagOrPending()" : "state.ReadRawTag()";

            sb.AppendLine();
            // the after-deserialize hook must fire on EVERY exit, and the raw body has two -
            // the tag==0 loop exit and the scope-end early return - so its presence swaps the
            // early return for a goto to a shared exit label
            var hasAfter = HasCallback(contract, ProtoCallbackKind.AfterDeserialize);

            // a hierarchy layer reads through SubTypeState (deferred construction: the payload
            // names the layer to build, so nothing can be constructed up front) - the static is
            // the ISubTypeSerializer.ReadSubType body, and the member arms address value.Value,
            // whose getter is the inlined materialize-on-demand (classic hoisted it per case;
            // the semantics are identical and this keeps one arm shape for both bodies)
            var subType = contract.RootTypeName is not null;
            var instance = subType ? "value.Value" : "value";

            if (subType)
            {
                Line(sb, indent, $"private static {contract.TypeName} RawReadSub_{Sanitise(contract.TypeName)}(ref global::ProtoBuf.ProtoReader.State state, "
                    + $"global::ProtoBuf.Serializers.SubTypeState<{contract.TypeName}> value)");
                Line(sb, indent, "{");
            }
            else
            {
                Line(sb, indent, $"private static {contract.TypeName} RawRead_{Sanitise(contract.TypeName)}(ref global::ProtoBuf.ProtoReader.State state, {contract.TypeName} value)");
                Line(sb, indent, "{");
                Line(sb, indent + 1, $"value ??= new {contract.TypeName}();");
                // placement is ref-emit's: after construction, before the field loop
                EmitCallback(sb, indent + 1, contract, "value", ProtoCallbackKind.BeforeDeserialize);
            }
            // the tag lives in a local and the loop reads at the BOTTOM, so a repeated-field run
            // can make the tag read its own do-while condition and hand a miss straight back to
            // dispatch via continue - the run-consumption shape, see notes/nano-core.md
            Line(sb, indent + 1, $"uint tag = {readTag};");
            Line(sb, indent + 1, "while (tag != 0)");
            Line(sb, indent + 1, "{");
            Line(sb, indent + 2, "switch (tag)");
            Line(sb, indent + 2, "{");
            // a derived layer nests inside a sub-type marker at its own field number; the
            // narrowing choreography (SubTypeState re-wrap, materialize-then-specialize, the
            // sibling refusal) is classic machinery entered via StashTag, exactly as a
            // legacy-mode member enters the stateful surface - the layer's OWN members stay raw
            foreach (var st in contract.SubTypes)
            {
                var stn = st.FieldNumber;
                Line(sb, indent + 3, $"case ({stn} << 3) | 2:  // sub-type {st.TypeName}, field {stn}");
                Line(sb, indent + 3, $"case ({stn} << 3) | 3:");
                Line(sb, indent + 4, "state.StashTag(tag);");
                Line(sb, indent + 4, $"value.ReadSubType<{st.TypeName}>(ref state, s_default);");
                Line(sb, indent + 4, "break;");
            }
            foreach (var member in contract.Members)
            {
                var name = Escape(member.Name);
                var n = member.FieldNumber;
                if (fallback.TryGetValue(member.Name, out var reason))
                {
                    // legacy-mode: labels for every data wire type, generously - the classic body
                    // validates the wire itself, so a wrong-wired arrival throws exactly as the
                    // classic loop would rather than being skipped as unknown. StashTag is the
                    // whole bridge: field number and wire type land where the stateful surface
                    // expects them, and the body below is the classic emission, verbatim.
                    Line(sb, indent + 3, $"// raw read pass: legacy-mode - member {member.Name}: {reason}");
                    Line(sb, indent + 3, $"case ({n} << 3) | 0:");
                    Line(sb, indent + 3, $"case ({n} << 3) | 1:");
                    Line(sb, indent + 3, $"case ({n} << 3) | 2:  // {member.Name}, field {n}");
                    Line(sb, indent + 3, $"case ({n} << 3) | 3:");
                    Line(sb, indent + 3, $"case ({n} << 3) | 5:");
                    Line(sb, indent + 3, "{");
                    Line(sb, indent + 4, "state.StashTag(tag);");
                    EmitClassicMemberBody(sb, indent + 1, contract, member, instance, self: "s_default");
                    Line(sb, indent + 4, "break;");
                    Line(sb, indent + 3, "}");
                    continue;
                }
                if (member.Map.Factory is not null && !fallback.ContainsKey(member.Name))
                {
                    // a NATIVE map: a run of length-prefixed {1: key, 2: value} entries, each
                    // read in its own scope with per-side wire forms; insert semantics follow
                    // MapSerializer exactly - a valid protobuf map overwrites (SetValues is the
                    // indexer), an invalid shape or DisableMap adds (AddRange throws on a
                    // duplicate). Entry seeds match TypeHelper<T>.Default: "" for a string side,
                    // default otherwise - an entry may omit either field.
                    var map = member.Map;
                    var keySeed = map.KeyKind == ProtoMemberKind.String ? "\"\"" : "default";
                    var valueSeed = map.ValueKind == ProtoMemberKind.String ? "\"\"" : "default";
                    var kForms = RawScalarForms(map.KeyKind, map.KeyEnumTypeName);
                    var insert = map.IsValidProtobufMap && !member.DisableMap
                        ? $"{instance}.{name}[k{n}] = v{n};"
                        : $"{instance}.{name}.Add(k{n}, v{n});";
                    Line(sb, indent + 3, $"case ({n} << 3) | 2:  // {member.Name}, field {n}, map entry run");
                    Line(sb, indent + 3, "{");
                    Line(sb, indent + 4, $"{instance}.{name} ??= new {member.DeclaredTypeName}();");
                    Line(sb, indent + 4, "var last = tag;");
                    Line(sb, indent + 4, "do");
                    Line(sb, indent + 4, "{");
                    Line(sb, indent + 5, "var scope = state.PushScope(last);");
                    Line(sb, indent + 5, $"{map.KeyTypeName} k{n} = {keySeed};");
                    Line(sb, indent + 5, $"{map.ValueTypeName} v{n} = {valueSeed};");
                    Line(sb, indent + 5, $"uint etag{n} = state.ReadRawTag();");
                    Line(sb, indent + 5, $"while (etag{n} != 0)");
                    Line(sb, indent + 5, "{");
                    Line(sb, indent + 6, $"switch (etag{n})");
                    Line(sb, indent + 6, "{");
                    foreach (var (wire, read) in kForms)
                    {
                        Line(sb, indent + 7, $"case (1 << 3) | {wire}:  // key, {WireName(wire)}");
                        Line(sb, indent + 8, $"k{n} = {read};");
                        Line(sb, indent + 8, "break;");
                    }
                    if (map.ValueKind == ProtoMemberKind.Message)
                    {
                        Line(sb, indent + 7, "case (2 << 3) | 2:  // value, length-prefixed");
                        Line(sb, indent + 7, "case (2 << 3) | 3:  // value, group");
                        Line(sb, indent + 7, "{");
                        Line(sb, indent + 8, $"var vscope = state.PushScope(etag{n});");
                        Line(sb, indent + 8, $"v{n} = RawRead_{Sanitise(map.ValueTypeName!)}(ref state, v{n});");
                        Line(sb, indent + 8, "state.PopScope(vscope);");
                        Line(sb, indent + 8, "break;");
                        Line(sb, indent + 7, "}");
                    }
                    else
                    {
                        foreach (var (wire, read) in RawScalarForms(map.ValueKind, map.ValueEnumTypeName))
                        {
                            Line(sb, indent + 7, $"case (2 << 3) | {wire}:  // value, {WireName(wire)}");
                            Line(sb, indent + 8, $"v{n} = {read};");
                            Line(sb, indent + 8, "break;");
                        }
                    }
                    Line(sb, indent + 7, "default:");
                    Line(sb, indent + 8, $"if (state.IsScopeEnd(etag{n})) goto entryDone{n};");
                    Line(sb, indent + 8, $"if ((etag{n} >> 3) is 1 or 2) state.ThrowUnexpectedWireType(etag{n});");
                    Line(sb, indent + 8, $"state.SkipTag(etag{n});");
                    Line(sb, indent + 8, "break;");
                    Line(sb, indent + 6, "}");
                    Line(sb, indent + 6, $"etag{n} = state.ReadRawTag();");
                    Line(sb, indent + 5, "}");
                    Line(sb, indent + 5, $"entryDone{n}:");
                    Line(sb, indent + 5, "state.PopScope(scope);");
                    Line(sb, indent + 5, insert);
                    Line(sb, indent + 4, $"}} while ((tag = state.ReadRawTag()) == last);");
                    Line(sb, indent + 4, "continue;");
                    Line(sb, indent + 3, "}");
                    continue;
                }
                if (member.Repeated.Factory == "CreateVector")
                {
                    // an ARRAY member: a run is collected into a scratch list, then append-merged
                    // into a NEW array and assigned back - ref-emit's vector semantics, held to
                    // byte-and-merge identity by the differential suite. Eligibility guaranteed a
                    // plain setter, so the assignment is direct.
                    var element = member.ElementTypeName!;
                    var buffer = $"new global::System.Collections.Generic.List<{element}>()";
                    switch (member.Kind)
                    {
                        case ProtoMemberKind.String:
                            Line(sb, indent + 3, $"case ({n} << 3) | 2:  // {member.Name}, field {n}, length-prefixed run");
                            Line(sb, indent + 3, "{");
                            Line(sb, indent + 4, $"var buf{n} = {buffer};");
                            Line(sb, indent + 4, $"do {{ buf{n}.Add(state.ReadRawString()); }}");
                            Line(sb, indent + 4, $"while ((tag = state.ReadRawTag()) == (({n} << 3) | 2));");
                            Line(sb, indent + 4, $"{instance}.{name} = ArrayAppend({instance}.{name}, buf{n});");
                            Line(sb, indent + 4, "continue;");
                            Line(sb, indent + 3, "}");
                            break;
                        case ProtoMemberKind.Message:
                            Line(sb, indent + 3, $"case ({n} << 3) | 2:  // {member.Name}, field {n}, length-prefixed");
                            Line(sb, indent + 3, $"case ({n} << 3) | 3:  // {member.Name}, field {n}, group");
                            Line(sb, indent + 3, "{");
                            Line(sb, indent + 4, $"var buf{n} = {buffer};");
                            Line(sb, indent + 4, "var last = tag;");
                            Line(sb, indent + 4, "do");
                            Line(sb, indent + 4, "{");
                            Line(sb, indent + 5, "var scope = state.PushScope(last);");
                            Line(sb, indent + 5, $"buf{n}.Add(RawRead_{Sanitise(member.TypeName!)}(ref state, null));");
                            Line(sb, indent + 5, "state.PopScope(scope);");
                            Line(sb, indent + 4, "} while ((tag = state.ReadRawTag()) == last);");
                            Line(sb, indent + 4, $"{instance}.{name} = ArrayAppend({instance}.{name}, buf{n});");
                            Line(sb, indent + 4, "continue;");
                            Line(sb, indent + 3, "}");
                            break;
                        default: // varint-kind scalar or enum element
                        {
                            var forms = RawScalarForms(member.Kind, member.EnumTypeName, member.DataFormat);
                            Line(sb, indent + 3, $"case ({n} << 3) | {forms[0].Wire}:  // {member.Name}, field {n}, unpacked run ({WireName(forms[0].Wire)})");
                            Line(sb, indent + 3, "{");
                            Line(sb, indent + 4, $"var buf{n} = {buffer};");
                            Line(sb, indent + 4, $"do {{ buf{n}.Add({forms[0].Read}); }}");
                            Line(sb, indent + 4, $"while ((tag = state.ReadRawTag()) == (({n} << 3) | {forms[0].Wire}));");
                            Line(sb, indent + 4, $"{instance}.{name} = ArrayAppend({instance}.{name}, buf{n});");
                            Line(sb, indent + 4, "continue;");
                            Line(sb, indent + 3, "}");
                            Line(sb, indent + 3, $"case ({n} << 3) | 2:  // {member.Name}, field {n}, packed");
                            Line(sb, indent + 3, "{");
                            Line(sb, indent + 4, $"var buf{n}p = {buffer};");
                            Line(sb, indent + 4, "var scope = state.PushLengthPrefix();");
                            Line(sb, indent + 4, $"while (!state.AtScopeEnd) buf{n}p.Add({forms[0].Read});");
                            Line(sb, indent + 4, "state.PopScope(scope);");
                            Line(sb, indent + 4, $"{instance}.{name} = ArrayAppend({instance}.{name}, buf{n}p);");
                            Line(sb, indent + 4, "break;");
                            Line(sb, indent + 3, "}");
                            for (int i = 1; i < forms.Length; i++)
                            {
                                Line(sb, indent + 3, $"case ({n} << 3) | {forms[i].Wire}:  // {member.Name}, field {n}, {WireName(forms[i].Wire)}");
                                Line(sb, indent + 4, $"{instance}.{name} = ArrayAppend({instance}.{name}, {forms[i].Read});");
                                Line(sb, indent + 4, "break;");
                            }
                            break;
                        }
                    }
                    continue;
                }
                if (member.Repeated.Factory is not null)
                {
                    // construct-on-first-presence, matching the classic read (ReadRepeated creates
                    // the collection and assigns it back): a null collection is created the moment
                    // its field appears, and never when it does not. A getter-only or
                    // non-public/init setter cannot take the ??= directly (CS0200), but its
                    // [UnsafeAccessor] is emitted regardless of body shape, so the construction
                    // routes through it - a nameable backing field hands back a ref, a setter
                    // accessor takes a null test. The one shape left out is IsReadOnly (a
                    // non-trivial getter with no nameable field): classic silently loses the data
                    // when the collection is null, we NRE - neither restores it, and the getter
                    // still serves the overwhelmingly common initialized-inline case.
                    var ensure = member switch
                    {
                        { IsReadOnly: true } => null,
                        { UsesAccessor: true, AccessorField: not null }
                            => $"{AccessorName(contract, member)}({instance}) ??= new {member.DeclaredTypeName}();",
                        { UsesAccessor: true }
                            => $"if ({instance}.{name} is null) {AccessorName(contract, member)}(value, new {member.DeclaredTypeName}());",
                        _ => $"{instance}.{name} ??= new {member.DeclaredTypeName}();",
                    };
                    switch (member.Kind)
                    {
                        case ProtoMemberKind.String:
                            Line(sb, indent + 3, $"case ({n} << 3) | 2:  // {member.Name}, field {n}, length-prefixed run");
                            if (ensure is not null) Line(sb, indent + 4, ensure);
                            Line(sb, indent + 4, $"do {{ {instance}.{name}.Add(state.ReadRawString()); }}");
                            Line(sb, indent + 4, $"while ((tag = state.ReadRawTag()) == (({n} << 3) | 2));");
                            Line(sb, indent + 4, "continue;");
                            break;
                        case ProtoMemberKind.Message:
                            Line(sb, indent + 3, $"case ({n} << 3) | 2:  // {member.Name}, field {n}, length-prefixed");
                            Line(sb, indent + 3, $"case ({n} << 3) | 3:  // {member.Name}, field {n}, group");
                            Line(sb, indent + 3, "{");
                            if (ensure is not null) Line(sb, indent + 4, ensure);
                            Line(sb, indent + 4, "var last = tag;");
                            Line(sb, indent + 4, "do");
                            Line(sb, indent + 4, "{");
                            Line(sb, indent + 5, "var scope = state.PushScope(last);");
                            Line(sb, indent + 5, $"{instance}.{name}.Add(RawRead_{Sanitise(member.TypeName!)}(ref state, null));");
                            Line(sb, indent + 5, "state.PopScope(scope);");
                            Line(sb, indent + 4, "} while ((tag = state.ReadRawTag()) == last);");
                            Line(sb, indent + 4, "continue;");
                            Line(sb, indent + 3, "}");
                            break;
                        default: // varint-kind scalar or enum element
                        {
                            var forms = RawScalarForms(member.Kind, member.EnumTypeName, member.DataFormat);
                            Line(sb, indent + 3, $"case ({n} << 3) | {forms[0].Wire}:  // {member.Name}, field {n}, unpacked run ({WireName(forms[0].Wire)})");
                            if (ensure is not null) Line(sb, indent + 4, ensure);
                            Line(sb, indent + 4, $"do {{ {instance}.{name}.Add({forms[0].Read}); }}");
                            Line(sb, indent + 4, $"while ((tag = state.ReadRawTag()) == (({n} << 3) | {forms[0].Wire}));");
                            Line(sb, indent + 4, "continue;");
                            Line(sb, indent + 3, $"case ({n} << 3) | 2:  // {member.Name}, field {n}, packed");
                            // a nullable element (List<int?>) takes every OTHER form unchanged -
                            // int converts to int? implicitly on Add, and the wire is identical -
                            // but the library fast path is typed List<int>, so it falls to the
                            // inline drain. AsRepeated erases element nullability from the plan
                            // deliberately (it is an ordinary element on the wire), so the test
                            // here is the element type's own spelling.
                            if (member.Kind == ProtoMemberKind.Int32 && member.EnumTypeName is null
                                && !member.Repeated.TakesCollectionType
                                && member.DataFormat == ProtoDataFormat.Default
                                && member.ElementTypeName?.EndsWith("?", StringComparison.Ordinal) != true)
                            {
                                // plain List<int>: the library fast path (bulk arms, residency-switched)
                                if (ensure is not null) Line(sb, indent + 4, ensure);
                                Line(sb, indent + 4, $"state.ReadPackedVarint32({instance}.{name});");
                                Line(sb, indent + 4, "break;");
                            }
                            else
                            {
                                Line(sb, indent + 3, "{");
                                if (ensure is not null) Line(sb, indent + 4, ensure);
                                Line(sb, indent + 4, "var scope = state.PushLengthPrefix();");
                                Line(sb, indent + 4, $"while (!state.AtScopeEnd) {instance}.{name}.Add({forms[0].Read});");
                                Line(sb, indent + 4, "state.PopScope(scope);");
                                Line(sb, indent + 4, "break;");
                                Line(sb, indent + 3, "}");
                            }
                            for (int i = 1; i < forms.Length; i++)
                            {
                                Line(sb, indent + 3, $"case ({n} << 3) | {forms[i].Wire}:  // {member.Name}, field {n}, {WireName(forms[i].Wire)}");
                                if (ensure is not null) Line(sb, indent + 4, ensure);
                                Line(sb, indent + 4, $"{instance}.{name}.Add({forms[i].Read});");
                                Line(sb, indent + 4, "break;");
                            }
                            break;
                        }
                    }
                    continue;
                }
                // the presence flag is assigned on read, outside any null test the arm itself
                // carries - matching the classic emission exactly. Repeated/map members never
                // assign it (classic's early paths skip it), which the arms above preserve by
                // never reaching here.
                var setSpecified = member.SpecifiedMember is { } sp ? $"{instance}.{sp} = true;" : null;
                if (RawBclForm(member) is { } bclRead)
                {
                    // a compatibility-level BCL member: the length-prefixed form (how these are
                    // written) reads natively; the OTHER framings the stateful path tolerated -
                    // StartGroup for all four, Fixed64 raw ticks for DateTime/TimeSpan - take a
                    // StashTag arm to the wire-aware BclHelpers read, so acceptance is unchanged
                    Line(sb, indent + 3, $"case ({n} << 3) | 2:  // {member.Name}, field {n}, length-prefixed");
                    Line(sb, indent + 4, $"{instance}.{name} = {bclRead};");
                    if (setSpecified is not null) Line(sb, indent + 4, setSpecified);
                    Line(sb, indent + 4, "break;");
                    if (member.Kind is ProtoMemberKind.DateTime or ProtoMemberKind.TimeSpan)
                    {
                        Line(sb, indent + 3, $"case ({n} << 3) | 1:  // {member.Name}, field {n}, fixed64 ticks");
                    }
                    Line(sb, indent + 3, $"case ({n} << 3) | 3:  // {member.Name}, field {n}, group");
                    Line(sb, indent + 3, "{");
                    Line(sb, indent + 4, "state.StashTag(tag);");
                    Line(sb, indent + 4, $"{instance}.{name} = {ScalarRead(member)};");
                    if (setSpecified is not null) Line(sb, indent + 4, setSpecified);
                    Line(sb, indent + 4, "break;");
                    Line(sb, indent + 3, "}");
                    continue;
                }
                switch (member.Kind)
                {
                    case ProtoMemberKind.Message:
                        Line(sb, indent + 3, $"case ({n} << 3) | 2:  // {member.Name}, field {n}, length-prefixed");
                        Line(sb, indent + 3, $"case ({n} << 3) | 3:  // {member.Name}, field {n}, group");
                        Line(sb, indent + 3, "{");
                        Line(sb, indent + 4, "var scope = state.PushScope(tag);");
                        Line(sb, indent + 4, $"{instance}.{name} = RawRead_{Sanitise(member.TypeName!)}(ref state, {instance}.{name});");
                        Line(sb, indent + 4, "state.PopScope(scope);");
                        if (setSpecified is not null) Line(sb, indent + 4, setSpecified);
                        Line(sb, indent + 4, "break;");
                        Line(sb, indent + 3, "}");
                        break;
                    case ProtoMemberKind.String:
                        // same semantics as the legacy read: a null string does not overwrite
                        Line(sb, indent + 3, $"case ({n} << 3) | 2:  // {member.Name}, field {n}, length-prefixed");
                        Line(sb, indent + 3, "{");
                        Line(sb, indent + 4, $"var tmp{n} = state.ReadRawString();");
                        Line(sb, indent + 4, $"if (tmp{n} != null) {instance}.{name} = tmp{n};");
                        if (setSpecified is not null) Line(sb, indent + 4, setSpecified);
                        Line(sb, indent + 4, "break;");
                        Line(sb, indent + 3, "}");
                        break;
                    case ProtoMemberKind.Bytes when !member.OverwriteList:
                        // legacy merge semantics for a plain bytes member: repeated occurrences
                        // CONCATENATE (AppendBytes), which ReadRawBytes' replace silently diverges
                        // from - caught by RepeatedFieldOccurrencesMergeIdentically the moment the
                        // interface read routed here. OverwriteList opts into replace, which the
                        // raw form on the forms table already is, so that shape falls through.
                        Line(sb, indent + 3, $"case ({n} << 3) | 2:  // {member.Name}, field {n}, length-prefixed");
                        Line(sb, indent + 4, $"{instance}.{name} = state.AppendRawBytes({instance}.{name});");
                        if (setSpecified is not null) Line(sb, indent + 4, setSpecified);
                        Line(sb, indent + 4, "break;");
                        break;
                    default:
                    {
                        // wire-type tolerance by case labels, not state: the legacy reader accepts
                        // any suitable wire form for an integer (and protobuf-net itself writes
                        // fixed under DataFormat.FixedSize), so each label dispatches to the
                        // correctly-named raw read and the jump table absorbs the extra labels.
                        // Conversions mirror the legacy ReadInt32/ReadInt64 wire switch; an enum
                        // is its underlying scalar plus a cast the JIT erases; a nullable member
                        // takes the same assignment.
                        foreach (var (wire, read) in RawScalarForms(member.Kind, member.EnumTypeName, member.DataFormat))
                        {
                            Line(sb, indent + 3, $"case ({n} << 3) | {wire}:  // {member.Name}, field {n}, {WireName(wire)}");
                            Line(sb, indent + 4, $"{instance}.{name} = {read};");
                            if (setSpecified is not null) Line(sb, indent + 4, setSpecified);
                            Line(sb, indent + 4, "break;");
                        }
                        break;
                    }
                }
            }
            var exit = subType ? "return value.Value;" : "return value;";
            var knownFields = contract.Members.Select(static m => m.FieldNumber)
                .Concat(contract.SubTypes.Select(static s => s.FieldNumber))
                .OrderBy(static n => n)
                .Select(static n => n.ToString(CultureInfo.InvariantCulture))
                .ToArray();
            Line(sb, indent + 3, "default:");
            Line(sb, indent + 4, hasAfter
                ? "if (state.IsScopeEnd(tag)) goto afterRead;"
                : $"if (state.IsScopeEnd(tag)) {exit}");
            if (knownFields.Length != 0)
            {
                // a KNOWN field arriving on a wire type no label matched is invalid data, and the
                // classic loop THROWS for it (the member read rejects the wire type); skipping it
                // as unknown would silently discard - a detection gap, not tolerance
                Line(sb, indent + 4, "if (IsKnownField(tag)) state.ThrowUnexpectedWireType(tag);");
            }
            // an extensible contract CAPTURES the unknown field instead of skipping it - the tag
            // rides the parameter, per the raw convention
            Line(sb, indent + 4, contract.Extensible == ProtoExtensibleKind.None
                ? "state.SkipTag(tag);"
                : $"state.AppendExtensionData(tag, {instance}{ExtensionType(contract)});");
            Line(sb, indent + 4, "break;");
            Line(sb, indent + 2, "}");
            Line(sb, indent + 2, $"tag = {readTag};");
            Line(sb, indent + 1, "}");
            if (hasAfter)
            {
                Line(sb, indent + 1, "afterRead:");
                EmitCallback(sb, indent + 1, contract, "value", ProtoCallbackKind.AfterDeserialize);
            }
            Line(sb, indent + 1, exit);
            if (knownFields.Length != 0)
            {
                sb.AppendLine();
                Line(sb, indent + 1, "static bool IsKnownField(uint tag) => (tag >> 3) is "
                    + string.Join(" or ", knownFields) + ";");
            }
            Line(sb, indent, "}");
        }

        private static string WireName(int wire) => wire switch
        {
            0 => "varint",
            1 => "fixed64",
            2 => "length-prefixed",
            3 => "group",
            5 => "fixed32",
            _ => "?",
        };

        private static (int Wire, string Read)[] RawScalarForms(ProtoMemberKind kind, string? enumTypeName,
            ProtoDataFormat format = ProtoDataFormat.Default)
        {
            // the format changes at most two things, mirroring the legacy per-wire read switch:
            // ZigZag swaps the wire-0 DECODE (only SignedVarint zags - the fixed tolerance arms
            // stay plain, exactly as ReadInt32's switch has it), and FixedSize promotes the
            // natural wire to forms[0], which the repeated run and packed-drain arms key on
            // (a fixed-size packed payload is fixed-width content). RawFormatReason has already
            // routed every other kind/format pairing to legacy-mode.
            if (format == ProtoDataFormat.ZigZag)
            {
                return kind switch
                {
                    ProtoMemberKind.Int32 =>
                    [
                        (0, "state.ReadRawZigZag32()"),
                        (5, "unchecked((int)state.ReadRawFixed32())"),
                        (1, "checked((int)unchecked((long)state.ReadRawFixed64()))"),
                    ],
                    ProtoMemberKind.Int64 =>
                    [
                        (0, "state.ReadRawZigZag64()"),
                        (1, "unchecked((long)state.ReadRawFixed64())"),
                        (5, "(long)unchecked((int)state.ReadRawFixed32())"),
                    ],
                    _ => [], // unreachable: RawFormatReason already filtered
                };
            }
            if (format == ProtoDataFormat.FixedSize)
            {
                return kind switch
                {
                    ProtoMemberKind.Int32 =>
                    [
                        (5, "unchecked((int)state.ReadRawFixed32())"),
                        (0, "unchecked((int)state.ReadRawVarint32())"),
                        (1, "checked((int)unchecked((long)state.ReadRawFixed64()))"),
                    ],
                    ProtoMemberKind.UInt32 =>
                    [
                        (5, "state.ReadRawFixed32()"),
                        (0, "state.ReadRawVarint32()"),
                        (1, "checked((uint)state.ReadRawFixed64())"),
                    ],
                    ProtoMemberKind.Int64 =>
                    [
                        (1, "unchecked((long)state.ReadRawFixed64())"),
                        (0, "unchecked((long)state.ReadRawVarint64())"),
                        (5, "(long)unchecked((int)state.ReadRawFixed32())"),
                    ],
                    ProtoMemberKind.UInt64 =>
                    [
                        (1, "state.ReadRawFixed64()"),
                        (0, "state.ReadRawVarint64()"),
                        (5, "(ulong)state.ReadRawFixed32()"),
                    ],
                    _ => [], // unreachable: RawFormatReason already filtered
                };
            }
            (int Wire, string Read)[] forms = kind switch
            {
                ProtoMemberKind.Bool =>
                [
                    (0, "state.ReadRawVarint32() != 0"),
                    (5, "state.ReadRawFixed32() != 0"),
                    (1, "state.ReadRawFixed64() != 0"),
                ],
                ProtoMemberKind.Int32 =>
                [
                    (0, "unchecked((int)state.ReadRawVarint32())"),
                    (5, "unchecked((int)state.ReadRawFixed32())"),
                    (1, "checked((int)unchecked((long)state.ReadRawFixed64()))"),
                ],
                ProtoMemberKind.UInt32 =>
                [
                    (0, "state.ReadRawVarint32()"),
                    (5, "state.ReadRawFixed32()"),
                    (1, "checked((uint)state.ReadRawFixed64())"),
                ],
                ProtoMemberKind.Int64 =>
                [
                    (0, "unchecked((long)state.ReadRawVarint64())"),
                    (1, "unchecked((long)state.ReadRawFixed64())"),
                    (5, "(long)unchecked((int)state.ReadRawFixed32())"),
                ],
                ProtoMemberKind.UInt64 =>
                [
                    (0, "state.ReadRawVarint64()"),
                    (1, "state.ReadRawFixed64()"),
                    (5, "(ulong)state.ReadRawFixed32()"),
                ],
                // double is fixed64-only: the fixed32 float promotion needs Int32BitsToSingle,
                // which netfx lacks - the one deliberate tolerance exception
                ProtoMemberKind.Double => [(1, "state.ReadRawDouble()")],
                // strings only reach the forms table from map sides: the single-member and
                // repeated arms have dedicated shapes (null guard, run consumption); a map side
                // is a plain read into the entry local, seeded "" for the absent-field case
                ProtoMemberKind.String => [(2, "state.ReadRawString()")],
                // bytes: replace. Only reached for OverwriteList members - a PLAIN bytes member
                // is special-cased at the emit site to state.AppendBytes (legacy concatenation),
                // because the generated model must merge identically to RuntimeTypeModel. The
                // raw surface itself keeps replace as its native default (notes/nano-core.md).
                ProtoMemberKind.Bytes => [(2, "state.ReadRawBytes()")],
                _ => [], // unreachable: RawReadEligible already filtered
            };
            if (enumTypeName is not null)
            {
                for (int i = 0; i < forms.Length; i++)
                {
                    forms[i] = (forms[i].Wire, $"({enumTypeName})({forms[i].Read})");
                }
            }
            return forms;
        }

        /// <summary>
        /// CONTRACT-level raw-read eligibility: shape and callbacks only. Member-level
        /// difficulty never disqualifies a contract - <see cref="RawMemberFallbackReason"/>
        /// routes such a member to a legacy-mode arm inside the raw body instead.
        /// </summary>
        private static bool RawReadEligible(ProtoContractPlan contract, out string? reason)
        {
            var hierarchy = contract.RootTypeName is not null || contract.SubTypes.Count != 0;
            if (contract.IsValueType || contract.IsTuple || contract.IsGroup
                || contract.SurrogateTypeName is not null
                || contract.ExternalSerializerTypeName is not null
                // abstract and non-default construction have classic shapes OUTSIDE a
                // hierarchy (the throw-on-null read, IFactory, the ctor accessor); inside one,
                // construction is SubTypeState's job and abstract roots are ordinary
                || (!hierarchy && (contract.IsAbstract || contract.SkipConstructor
                    || contract.UsesConstructorAccessor)))
            {
                reason = "contract shape (value type, tuple, surrogate or external serializer)";
                return false;
            }
            if (hierarchy)
            {
                // v1 exclusions: shapes whose choreography threads through SubTypeState in ways
                // the raw body does not reproduce yet - the factory hand-off for non-default
                // construction, and the OnBeforeDeserialize threading for callbacks
                if (contract.SkipConstructor || contract.UsesConstructorAccessor)
                {
                    reason = "hierarchy with non-default construction";
                    return false;
                }
                for (int i = 0; i < contract.Callbacks.Count; i++)
                {
                    if (contract.Callbacks[i].MethodName is not null)
                    {
                        reason = "hierarchy with serialization callbacks";
                        return false;
                    }
                }
            }
            // note: callbacks are NOT a gate outside a hierarchy. The deserialize pair maps
            // onto the raw body directly (before = after construction, ahead of the loop;
            // after = every exit, via a shared label since scope-end returns early), and the
            // serialize pair only touches the write body, which is classic regardless.
            reason = null;
            return true;
        }

        /// <summary>
        /// Why a member takes the LEGACY-MODE arm (StashTag + the classic member body, verbatim)
        /// instead of a native raw form; null means native. This is the gap-tracking surface: the
        /// reason lands as a comment in the emitted output and is tallied by the coverage census,
        /// so "what member shapes are still on the stateful path" stays a measured list rather
        /// than a guess. Note what is NOT here: IsRequired, [DefaultValue] and ShouldSerialize
        /// conditions are write-side facts that never change the read.
        /// </summary>
        private static string? RawMemberFallbackReason(ProtoMemberPlan member, HashSet<string> rawSet)
        {
            if (member.Map.Factory is not null)
            {
                if (member.WrappedValue || member.WrappedCollection) return "null-wrapped map";
                var map = member.Map;
                // native v1 is the exact Dictionary<K,V> shape; derived/immutable/interface
                // dictionaries have their own construction and insert semantics
                if (map.Factory != "CreateDictionary" || map.TakesCollectionType) return $"map shape {map.Factory}";
                if (member.DataFormat != ProtoDataFormat.Default) return "map with non-default DataFormat";
                if (member.MapKeyFormat != ProtoDataFormat.Default
                    || member.MapValueFormat != ProtoDataFormat.Default) return "map with per-side format";
                if (member.OverwriteList) return "OverwriteList map";
                if (member.IsReadOnly || member.UsesAccessor) return "map without a plain setter";
                if (map.ValueSerializerFactory is not null) return "map with repeated value";
                if (map.KeyKind == ProtoMemberKind.Message) return "map with message key";
                if (!NativeScalarKind(map.KeyKind) || map.KeyKind is ProtoMemberKind.Double
                    or ProtoMemberKind.Bytes) return $"map key kind {map.KeyKind}";
                if (map.ValueKind == ProtoMemberKind.Message)
                {
                    if (map.ValueTypeName is null || !rawSet.Contains(map.ValueTypeName))
                        return "map value type not raw-eligible";
                }
                else if (!NativeScalarKind(map.ValueKind) || map.ValueKind == ProtoMemberKind.Bytes)
                {
                    // bytes values excluded: the classic entry read APPENDS a duplicated value
                    // field within one entry, where the raw form would replace
                    return $"map value kind {map.ValueKind}";
                }
                return null;
            }
            if (member.WrappedValue || member.WrappedCollection) return "null-wrapped";
            if (RawFormatReason(member) is { } badFormat) return badFormat;
            if (member.AccessorReads) return "accessor-reached member";
            // UsesAccessor is a SETTER-side fact; a repeated member reads through Add on the
            // public getter, so only a scalar/message member needs the stateful path for it
            if (member.UsesAccessor && member.Repeated.Factory is null) return "accessor-reached setter";
            // note: {Name}Specified is assigned ON READ, but that is one extra statement per
            // arm rather than a shape change, so it is native (the assignment sits outside any
            // null test, matching classic; repeated/map members never assign it, also matching
            // classic, whose early paths skip it). ShouldSerialize is write-only and never
            // mattered here.
            // "this" is just the normal message-member plumbing; anything ELSE is a hand-written
            // serializer whose framing the raw pass has not derived
            if (member.SubSerializer is not (null or "this")) return "hand-written serializer";
            if (member.Repeated.Factory is not null)
            {
                // native repeated is List<T>-shaped (Add is the read mechanism) or an ARRAY
                // (collected into a scratch list per run, then append-merged into a new array
                // and assigned - ref-emit's vector semantics exactly)
                if (member.Repeated.Factory is not ("CreateList" or "CreateVector"))
                    return $"collection shape {member.Repeated.Factory}";
                if (member.Repeated.Factory == "CreateVector"
                    && (member.IsReadOnly || member.UsesAccessor))
                {
                    // the merge builds a NEW array, so the member must be plainly settable;
                    // a list mutates in place and tolerates a getter-only property, an array
                    // cannot
                    return "array without a plain setter";
                }
                if (member.OverwriteList) return "OverwriteList collection";
                // note: no nullable-element gate. AsRepeated erases element nullability from
                // the plan (IsNullable is always false here), and none is needed: a nullable
                // element takes the same emitted forms - the packed fast path alone is typed
                // to the non-nullable list and dodges via the element spelling at the emit site.
                // Double/Bytes are single-member kinds only for now (no packed-double or
                // repeated-bytes emission yet)
                if (member.Kind is ProtoMemberKind.Double or ProtoMemberKind.Bytes) return $"repeated {member.Kind}";
                if (member.Kind == ProtoMemberKind.Message)
                {
                    return member.TypeName is not null && rawSet.Contains(member.TypeName)
                        ? null : "element type not raw-eligible";
                }
                return NativeScalarKind(member.Kind) ? null : $"element kind {member.Kind}";
            }
            if (member.Kind == ProtoMemberKind.Message)
            {
                // nullable/struct messages have their own classic shapes (GetValueOrDefault
                // seeding, no null test); the native form is the plain reference sub-message
                if (member.IsNullable || member.MemberIsValueType) return "message shape (nullable or struct)";
                if (member.IsReadOnly) return "getter-only message";
                // only a NATIVE message member emits the direct RawRead_ call, so the target must
                // be raw-eligible; a fallen target is read via state.ReadMessage instead - this
                // replaces the old whole-contract cascade
                return member.TypeName is not null && rawSet.Contains(member.TypeName)
                    ? null : "target type not raw-eligible";
            }
            if (member.IsReadOnly) return "getter-only scalar";
            if (RawBclForm(member) is not null) return null;
            return NativeScalarKind(member.Kind) ? null : $"kind {member.Kind}";
        }

        /// <summary>
        /// The self-framing raw read for a compatibility-level BCL member, or null when the
        /// combination stays legacy-mode. The level selection mirrors <see cref="BclSuffix"/>
        /// exactly (member.CompatibilityLevel is the EFFECTIVE level, so a WellKnown-format
        /// promotion is already applied); the level-300 string forms of Guid/Decimal are not
        /// built yet and stay stateful. This serves the wire-2 arm only - fixed64 and group
        /// framings take StashTag arms to the wire-aware BclHelpers read, so the native form
        /// never sees them.
        /// </summary>
        private static string? RawBclForm(ProtoMemberPlan member) => member.Kind switch
        {
            ProtoMemberKind.DateTime => member.CompatibilityLevel >= 240
                ? "state.ReadRawTimestamp()" : "state.ReadRawDateTimeBcl()",
            ProtoMemberKind.TimeSpan => member.CompatibilityLevel >= 240
                ? "state.ReadRawDuration()" : "state.ReadRawTimeSpanBcl()",
            ProtoMemberKind.Guid when member.CompatibilityLevel < 300 => "state.ReadRawGuidBcl()",
            ProtoMemberKind.Decimal when member.CompatibilityLevel < 300 => "state.ReadRawDecimalBcl()",
            _ => null,
        };

        private static bool NativeScalarKind(ProtoMemberKind kind) => kind is
            ProtoMemberKind.Bool or ProtoMemberKind.Int32 or ProtoMemberKind.UInt32
            or ProtoMemberKind.Int64 or ProtoMemberKind.UInt64 or ProtoMemberKind.String
            or ProtoMemberKind.Double or ProtoMemberKind.Bytes;

        /// <summary>
        /// Whether the member's DataFormat has a native raw form; null means it does. The rules
        /// mirror what the format actually selects on the READ side (this pass emits no writes):
        /// TwosComplement is byte-identical to Default everywhere; on a sub-message every format
        /// is native because Group only changes the write and the native message arm already
        /// accepts both framings off the header; ZigZag is a different wire-0 decode
        /// (ReadRawZigZag32/64) for the signed varint kinds; FixedSize merely reorders the
        /// tolerance forms so the natural wire leads (which the repeated run/packed arms key on).
        /// Formats on enums, BCL kinds, bool and the rest stay legacy-mode.
        /// </summary>
        private static string? RawFormatReason(ProtoMemberPlan member)
        {
            // note TwosComplement never reaches here: the parse folds it onto Default, being
            // byte-identical for every type handled
            var format = member.DataFormat;
            if (format == ProtoDataFormat.Default) return null;
            if (member.EnumTypeName is not null) return $"non-default DataFormat ({format} on enum)";
            var kind = member.Kind;
            if (kind == ProtoMemberKind.Message) return null;
            if (kind is ProtoMemberKind.DateTime or ProtoMemberKind.TimeSpan
                or ProtoMemberKind.Guid or ProtoMemberKind.Decimal)
            {
                // every non-ZigZag format on the BCL kinds reads through the same arm set - |2
                // native, |1/|3 StashTag tolerance - and the write is classic regardless; a
                // WellKnown promotion is already folded into the effective level, and whether
                // the KIND itself goes native at this level is RawBclForm's decision, not a
                // format question. ZigZag throws while building the model and was dropped
                // upstream; named here only defensively.
                return format == ProtoDataFormat.ZigZag ? $"non-default DataFormat ({format} on {kind})" : null;
            }
            if (format == ProtoDataFormat.ZigZag
                && kind is ProtoMemberKind.Int32 or ProtoMemberKind.Int64) return null;
            if (format == ProtoDataFormat.FixedSize
                && kind is ProtoMemberKind.Int32 or ProtoMemberKind.UInt32
                    or ProtoMemberKind.Int64 or ProtoMemberKind.UInt64) return null;
            return $"non-default DataFormat ({format} on {kind})";
        }

        private static void EmitContract(StringBuilder sb, int indent, ProtoContractPlan contract, bool raw = false, bool rawWrite = false,
            bool listAsSpan = false, bool immutableAsSpan = false, Dictionary<string, ProtoContractPlan>? measurable = null,
            HashSet<string>? slotConsumers = null)
        {
            var self = $"{Serializers}.ISerializer<{contract.TypeName}>";

            // a hand-written serializer replaces the body entirely - including Features - so we hand
            // it out rather than implementing ISerializer<T> ourselves at all
            if (contract.ExternalSerializerTypeName is { } external)
            {
                Line(sb, indent, $"{self} {Serializers}.ISerializerProxy<{contract.TypeName}>.Serializer");
                Line(sb, indent + 1, $"=> {Serializers}.SerializerCache.Get<{external}, {contract.TypeName}>();");
                return;
            }

            // the option flag is what makes the classic engine ASK the IMeasuringSerializer
            // (ProtoWriter.Measure requires flag AND interface); InheritFrom copies only the
            // masked category and wire-type bits, so it cannot leak into member features
            var measuring = rawWrite && measurable is not null && measurable.ContainsKey(contract.TypeName);
            Line(sb, indent, $"{Features} {self}.Features");
            Line(sb, indent + 1, $"=> {Features}.CategoryMessage | {Features}."
                + (contract.IsGroup ? "WireTypeStartGroup" : "WireTypeString")
                + (measuring ? $" | {Features}.OptionTrySkipWritingWhenMeasuring" : "") + ";");
            sb.AppendLine();

            if (contract.SkipConstructor)
            {
                Line(sb, indent, $"{contract.TypeName} {Serializers}.IFactory<{contract.TypeName}>.Create(global::ProtoBuf.ISerializationContext context)");
                Line(sb, indent + 1, $"=> {Construct(contract)};");
                sb.AppendLine();
            }

            if (contract.RootTypeName is { } root)
            {
                EmitSubTypeContract(sb, indent, contract, root, raw, rawWrite, listAsSpan, immutableAsSpan, measurable);
                return;
            }


            // when the surrogate carries a serializer of its own there are no members to inline, so
            // we convert and hand over to it - the shape a well-known-type surrogate needs
            if (contract.SurrogateSerializer is { } surrogateSerializer)
            {
                Line(sb, indent, $"{contract.TypeName} {self}.Read(ref global::ProtoBuf.ProtoReader.State state, {contract.TypeName} value)");
                Line(sb, indent, "{");
                Line(sb, indent + 1, $"var surrogate = {ToSurrogate(contract, "value")};");
                Line(sb, indent + 1, $"surrogate = {surrogateSerializer}.Read(ref state, surrogate);");
                Line(sb, indent + 1, $"return {ToUnderlying(contract, "surrogate")};");
                Line(sb, indent, "}");
                sb.AppendLine();

                Line(sb, indent, $"void {self}.Write(ref global::ProtoBuf.ProtoWriter.State state, {contract.TypeName} value)");
                Line(sb, indent, "{");
                Line(sb, indent + 1, $"var surrogate = {ToSurrogate(contract, "value")};");
                Line(sb, indent + 1, $"{surrogateSerializer}.Write(ref state, surrogate);");
                Line(sb, indent, "}");
                return;
            }

            // otherwise a surrogate contract's serializer *is* the surrogate's, with a conversion at
            // each end; everything below then works on the converted local rather than on `value`
            var surrogate = contract.SurrogateTypeName;
            var instance = surrogate is null ? "value" : "surrogate";
            var bodyType = surrogate ?? contract.TypeName;

            // a raw-read-eligible contract's interface read proxies to the RawRead_ static: one body,
            // reachable both through the model (ReadMessage, the conformance suite, real consumers)
            // and by direct static call (generated siblings, benchmarks). Eligibility already
            // excludes every shape the classic body below exists to handle - surrogates, tuples,
            // abstract roots, callbacks - so the proxy is exact, not a shortcut.
            if (raw)
            {
                Line(sb, indent, $"{contract.TypeName} {self}.Read(ref global::ProtoBuf.ProtoReader.State state, {contract.TypeName} value)");
                Line(sb, indent + 1, $"=> RawRead_{Sanitise(contract.TypeName)}(ref state, value);");
                sb.AppendLine();
            }
            else
            {
            Line(sb, indent, $"{contract.TypeName} {self}.Read(ref global::ProtoBuf.ProtoReader.State state, {contract.TypeName} value)");
            Line(sb, indent, "{");
            if (surrogate is not null)
            {
                Line(sb, indent + 1, $"var {instance} = {ToSurrogate(contract, "value")};");
            }
            if (contract.IsTuple)
            {
                // a tuple is rebuilt through its constructor at the end, so the read works on locals;
                // they are seeded from the incoming value so repeated occurrences still merge
                foreach (var member in contract.Members)
                {
                    Line(sb, indent + 1, $"{member.DeclaredTypeName} arg{member.FieldNumber} = default;");
                }
                if (!contract.IsValueType)
                {
                    Line(sb, indent + 1, "if (value != null)");
                    Line(sb, indent + 1, "{");
                    foreach (var member in contract.Members)
                    {
                        Line(sb, indent + 2, $"arg{member.FieldNumber} = value.{Escape(member.Name)};");
                    }
                    Line(sb, indent + 1, "}");
                }
                else
                {
                    foreach (var member in contract.Members)
                    {
                        Line(sb, indent + 1, $"arg{member.FieldNumber} = value.{Escape(member.Name)};");
                    }
                }
            }
            // an abstract type with no sub-types cannot be constructed at all; ref-emit still emits
            // a serializer for it, whose read throws - which is what keeps its *referrers* working
            // while the member stays null
            else if (contract.IsAbstract)
            {
                Line(sb, indent + 1, $"if ({instance} is null) global::ProtoBuf.Meta.TypeModel"
                    + $".ThrowCannotCreateInstance(typeof({bodyType}));");
            }
            // a struct arrives by value and is never null, so there is nothing to construct
            else if (!contract.IsValueType)
            {
                Line(sb, indent + 1, $"{instance} ??= {Construct(contract, bodyType)};");
            }
            EmitCallback(sb, indent + 1, contract, instance, ProtoCallbackKind.BeforeDeserialize);
            EmitReadLoop(sb, indent + 1, contract, instance);
            if (contract.IsTuple)
            {
                var arguments = string.Join(", ", contract.Members.Select(static x => $"arg{x.FieldNumber}"));
                Line(sb, indent + 1, contract.IsTupleLiteral
                    ? $"{instance} = ({arguments});"
                    : $"{instance} = new {bodyType}({arguments});");
            }
            EmitCallback(sb, indent + 1, contract, instance, ProtoCallbackKind.AfterDeserialize);
            if (surrogate is not null) Line(sb, indent + 1, $"value = {ToUnderlying(contract, instance)};");
            Line(sb, indent + 1, "return value;");
            Line(sb, indent, "}");
            sb.AppendLine();
            }

            if (rawWrite && measurable is not null && measurable.ContainsKey(contract.TypeName))
            {
                // the measure-first shape (notes/nano-writer.md): the interface write proxies to a
                // RawWrite_ static exactly as the read proxies to RawRead_ - the static IS the
                // direct-call design, letting a native message member in a sibling contract emit
                // an exact length prefix (Measure_) and call the body directly, with no stateful
                // sub-message engine in between. Eligibility guarantees no surrogate, hierarchy,
                // extension data or before-serialize callback reaches here.
                var san = Sanitise(contract.TypeName);
                // the write pass consumes lengths BY POSITION, so the measure has to have run and
                // the read cursor has to be sitting at this object's first child. Two ways in:
                // the classic engine already measured us through the IMeasuringSerializer hook and
                // recorded where our run began (Leave), or nothing has measured us and we do it
                // here. Either way we then seek past our OWN slot to our first child's. gap B38.
                // Only a contract whose write actually READS a slot needs the measure prologue.
                // A fully-grouped tree reads none - no length is on the wire anywhere in it - and
                // giving it one costs a whole extra traversal for nothing; measured at 2,453ns ->
                // 3,934ns on a 512-wide grouped graph, which is gap B35 being undone by accident.
                if (slotConsumers is null || slotConsumers.Contains(contract.TypeName))
                {
                Line(sb, indent, $"void {self}.Write(ref global::ProtoBuf.ProtoWriter.State state, {contract.TypeName} value)");
                Line(sb, indent, "{");
                Line(sb, indent + 1, "var slots = state.RawSlots;");
                // a struct has no reference identity, so it can never be found by Leave; it always
                // takes the measure-here arm, which is correct and merely costs a walk
                if (contract.IsValueType)
                {
                    Line(sb, indent + 1, "var entry = slots.Mark();");
                    Line(sb, indent + 2, $"Measure_{san}(value, state.RawDepthBudget, slots);");
                }
                else
                {
                    Line(sb, indent + 1, "if (!slots.Leave(value, out var entry))");
                    Line(sb, indent + 1, "{");
                    Line(sb, indent + 2, "entry = slots.Mark();");
                    Line(sb, indent + 2, $"Measure_{san}(value, state.RawDepthBudget, slots);");
                    Line(sb, indent + 1, "}");
                }
                Line(sb, indent + 1, "slots.SeekTo(entry);");
                Line(sb, indent + 1, $"RawWrite_{san}(ref state, value, state.RawDepthBudget);");
                Line(sb, indent, "}");
                }
                else
                {
                    Line(sb, indent, $"void {self}.Write(ref global::ProtoBuf.ProtoWriter.State state, {contract.TypeName} value)");
                    Line(sb, indent + 1, $"=> RawWrite_{san}(ref state, value, state.RawDepthBudget);");
                }
                sb.AppendLine();
                Line(sb, indent, $"public static void RawWrite_{san}(ref global::ProtoBuf.ProtoWriter.State state, {contract.TypeName} value, int depth)");
                Line(sb, indent, "{");
                // the write recursion USED to be safe by construction - every write was
                // preceded by a measure, and the measure was depth-budgeted. A GROUPED member
                // breaks that: it has no length prefix, so nothing measures it, and the write
                // recurses unguarded. Spotted by Marc reading the emitted code. Guarding here
                // rather than only on the grouped edge keeps it uniform - the alternative is
                // working out which contracts are reachable through a group, which is exactly
                // the kind of predicate whose failure mode is a process-killing stack overflow
                Line(sb, indent + 1, "if (--depth < 0) global::ProtoBuf.ProtoWriter.State.ThrowRawTooDeep();");
                if (!contract.IsValueType && !contract.IsTuple && !contract.IsSealed
                    && !contract.IgnoreUnknownSubTypes)
                {
                    Line(sb, indent + 1, "global::ProtoBuf.Meta.TypeModel.ThrowUnexpectedSubtype(value);");
                }
                var writeBody = new StringBuilder();
                EmitWriteMembers(writeBody, indent + 1, contract, "value", raw: true, listAsSpan: listAsSpan, immutableAsSpan: immutableAsSpan, measurable: measurable, depth: "depth");
                EmitCallback(writeBody, indent + 1, contract, "value", ProtoCallbackKind.AfterSerialize);
                AppendFoldingLengthTemp(sb, indent + 1, writeBody, "len");
                Line(sb, indent, "}");
                sb.AppendLine();
                // pure arithmetic, mirroring RawWrite_'s guards statement for statement: any
                // divergence between the two is a corrupt stream, which is exactly what the
                // differential and conformance suites exist to catch. Only the measure recursion
                // carries the depth budget - the write recursion that follows traverses the graph
                // the measure just proved finite. The lengths dictionary is the ??= cache
                // (notes/nano-writer.md): populated post-order here, consumed at the write sites,
                // so each reference-typed object is measured once per root however deep or
                // shared it is; struct contracts have no identity and bypass it.
                // long arithmetic, deliberately: a single message body CAN exceed int.MaxValue
                // (many large byte[] members, a colossal repeated field), and classic handles it
                // with its long lengths throughout - int accumulation would overflow silently,
                // which is a corrupt stream, not an error
                // private, not public: these sit on a private sealed services class, so `public`
                // grants nothing a consumer can reach and reads as API that is not. Every caller
                // is either in this same class (the IMeasuringSerializer body, and the enclosing
                // contracts' measure statics, which is the sub-message recursion) or reflective -
                // and both reflective binders, NanoBench.ResolveMeasure and
                // AotConformanceTests.MeasurableContractTests, already pass NonPublic
                Line(sb, indent, $"private static long Measure_{san}({contract.TypeName} value, int depth, global::ProtoBuf.RawLengthBuffer slots)");
                Line(sb, indent, "{");
                Line(sb, indent + 1, "if (--depth < 0) global::ProtoBuf.ProtoWriter.State.ThrowRawTooDeep();");
                Line(sb, indent + 1, "long len = 0;");
                // `len` is the accumulator here, so the sub-message temp needs its own name
                var measureBody = new StringBuilder();
                EmitMeasureMembers(measureBody, indent + 1, contract, measurable, listAsSpan, immutableAsSpan);
                AppendFoldingLengthTemp(sb, indent + 1, measureBody, "sub");
                Line(sb, indent + 1, "return len;");
                Line(sb, indent, "}");
                sb.AppendLine();
                // the classic engine's measure hook: any STATEFUL path writing this contract -
                // a mixed parent, a map entry, a non-native collection element - asks here
                // first (flag + interface, ProtoWriter.Measure) and gets the arithmetic
                // instead of a null-writer traversal. A non-writer context answers -1, which
                // the engine treats as "measure by writing", exactly as before - and so does a
                // body wider than the interface's int reply, spilling the pathological giant
                // to the traversal, which is long-capable end to end.
                Line(sb, indent, $"int {Serializers}.IMeasuringSerializer<{contract.TypeName}>.Measure(global::ProtoBuf.ISerializationContext context, global::ProtoBuf.WireType wireType, {contract.TypeName} value)");
                // THE BOUNDARY: this measure and the matching Write are separate calls with
                // arbitrary work between them, so the positional cursor cannot span it - the
                // engine may measure several objects before writing any. Record where this run
                // began against the object, so the later Write can find it again: one hash per
                // crossing, none per node. gap B38.
                Line(sb, indent, "{");
                Line(sb, indent + 1, "if (!global::ProtoBuf.ProtoWriter.State.TryMeasureRawSlots(context, out var depth, out var slots)) return -1;");
                Line(sb, indent + 1, "var entry = slots.Mark();");
                Line(sb, indent + 1, $"var len = Measure_{san}(value, depth, slots);");
                // only a reference type can be found again by identity; a struct would box to a
                // different object on the way back and never match, so it is left to re-measure
                if (!contract.IsValueType) Line(sb, indent + 1, "slots.Enter(value, entry);");
                Line(sb, indent + 1, "return len <= int.MaxValue ? (int)len : -1;");
                Line(sb, indent, "}");
                return;
            }

            Line(sb, indent, $"void {self}.Write(ref global::ProtoBuf.ProtoWriter.State state, {contract.TypeName} value)");
            Line(sb, indent, "{");
            if (surrogate is not null) Line(sb, indent + 1, $"var {instance} = {ToSurrogate(contract, "value")};");
            // ThrowUnexpectedSubtype is constrained to reference types, and a struct, a sealed type
            // and a tuple all rule sub-types out at compile time - ref-emit omits it for each. Note
            // it tests the *surrogate*, which is what carries any sub-types. IgnoreUnknownSubTypes
            // asks for the same omission outright: it is assertKnownType: false in TypeSerializer.
            if (!contract.IsValueType && !contract.IsTuple && !contract.IsSealed
                && !contract.IgnoreUnknownSubTypes)
            {
                Line(sb, indent + 1, $"global::ProtoBuf.Meta.TypeModel.ThrowUnexpectedSubtype({instance});");
            }
            EmitCallback(sb, indent + 1, contract, instance, ProtoCallbackKind.BeforeSerialize);
            var members = new StringBuilder();
            EmitWriteMembers(members, indent + 1, contract, instance, raw: rawWrite, listAsSpan: listAsSpan, immutableAsSpan: immutableAsSpan, measurable: measurable);
            EmitCallback(members, indent + 1, contract, instance, ProtoCallbackKind.AfterSerialize);
            AppendFoldingLengthTemp(sb, indent + 1, members, "len");
            Line(sb, indent, "}");
        }

        /// <summary>
        /// A serialization callback, if the contract declares one for this point.
        /// </summary>
        /// <remarks>
        /// The placement is ref-emit's: the "before" hooks fire after construction but before the
        /// field loop, and the "after" hooks after it, so a deserialization callback sees a fully
        /// populated instance. The <c>System.Runtime.Serialization</c> spelling takes a
        /// <c>StreamingContext</c>, which comes from the state.
        /// </remarks>
        private static bool HasCallback(ProtoContractPlan contract, ProtoCallbackKind kind)
            => contract.Callbacks.Count > (int)kind && contract.Callbacks[(int)kind].MethodName is not null;

        private static void EmitCallback(StringBuilder sb, int indent, ProtoContractPlan contract,
            string instance, ProtoCallbackKind kind)
        {
            var callbacks = contract.Callbacks;
            if (callbacks.Count <= (int)kind) return;

            var callback = callbacks[(int)kind];
            if (callback.MethodName is not { } method) return;

            var argument = callback.TakesContext
                ? "global::ProtoBuf.SerializationContext.AsStreamingContext(state.Context)"
                : "";
            Line(sb, indent, $"{instance}.{method}({argument});");
        }

        /// <summary>
        /// The field-dispatch loop shared by <c>Read</c> and <c>ReadSubType</c>.
        /// </summary>
        /// <param name="instance">
        /// What the members hang off. A sub-type read works through <c>SubTypeState&lt;T&gt;</c>,
        /// so the instance has to be hoisted out of it - which also constructs it on demand.
        /// </param>
        private static void EmitReadLoop(StringBuilder sb, int indent, ProtoContractPlan contract,
            string instance, EquatableArray<ProtoSubTypePlan> subTypes = default,
            bool fromSubTypeState = false)
        {
            // an empty message is legal protobuf, and has nothing to switch on
            var unknown = contract.Extensible == ProtoExtensibleKind.None
                ? "state.SkipField();"
                : $"state.AppendExtensionData({(instance == "value" ? "value" : "value.Value")}{ExtensionType(contract)});";
            if (contract.Members.Count == 0 && subTypes.Count == 0)
            {
                Line(sb, indent, "int field;");
                Line(sb, indent, "while ((field = state.ReadFieldHeader()) > 0)");
                Line(sb, indent, "{");
                Line(sb, indent + 1, unknown);
                Line(sb, indent, "}");
                return;
            }

            Line(sb, indent, "int field;");
            Line(sb, indent, "while ((field = state.ReadFieldHeader()) > 0)");
            Line(sb, indent, "{");
            Line(sb, indent + 1, "switch (field)");
            Line(sb, indent + 1, "{");
            foreach (var member in contract.Members)
            {
                var number = member.FieldNumber.ToString(CultureInfo.InvariantCulture);
                Line(sb, indent + 2, $"case {number}:");
                Line(sb, indent + 2, "{");
                // a sub-type read holds the instance inside SubTypeState, and reading it is what
                // constructs it - so it is hoisted per case, exactly as ref-emit does
                if (fromSubTypeState) Line(sb, indent + 3, $"var {instance} = value.Value;");
                EmitClassicMemberBody(sb, indent, contract, member, instance);
                Line(sb, indent + 3, "break;");
                Line(sb, indent + 2, "}");
            }
            // a derived layer arrives as a nested sub-item at its own field number; reading it hands
            // the whole SubTypeState down, so the instance is constructed at the deepest layer
            foreach (var subType in subTypes)
            {
                var number = subType.FieldNumber.ToString(CultureInfo.InvariantCulture);
                Line(sb, indent + 2, $"case {number}:");
                Line(sb, indent + 3, $"value.ReadSubType<{subType.TypeName}>(ref state, this);");
                Line(sb, indent + 3, "break;");
            }
            // an extensible contract keeps what it does not recognise rather than discarding it; the
            // instance has to be materialised for that, which is why the sub-type form reads
            // value.Value here rather than using the per-case local
            Line(sb, indent + 2, "default:");
            Line(sb, indent + 3, unknown);
            Line(sb, indent + 3, "break;");
            Line(sb, indent + 1, "}");
            Line(sb, indent, "}");
        }

        /// <summary>
        /// The statements that read ONE member through the stateful surface - everything between
        /// the case label and its <c>break</c>. Shared verbatim by the classic field loop and the
        /// raw pass's legacy-mode arms (which enter via <c>state.StashTag(tag)</c>), so the two
        /// paths cannot drift: a member is either native raw or exactly its classic self.
        /// Statements land at <paramref name="indent"/> + 3, matching the classic loop's layout;
        /// the raw arm passes its own base + 1 to line up.
        /// </summary>
        /// <param name="self">
        /// The expression for "ourselves as the sub-serializer" - <c>this</c> in the classic
        /// instance body, the <c>s_default</c> shared instance inside a static RawRead_ body
        /// (CS0026 otherwise).
        /// </param>
        private static void EmitClassicMemberBody(StringBuilder sb, int indent,
            ProtoContractPlan contract, ProtoMemberPlan member, string instance, string self = "this")
        {
            var number = member.FieldNumber.ToString(CultureInfo.InvariantCulture);
            // a tuple reads into the locals it will pass to the constructor, not into the member
            var target = contract.IsTuple ? $"arg{number}" : MemberAccess(contract, member, instance);
            if (member.Map.Factory is not null)
            {
                    // same merge shape as a collection, but the key and value features - and any
                    // sub-serializers they need - ride alongside
                    Line(sb, indent + 3, $"var tmp{number} = {target};");
                    var readMap = $"{Map(member)}.ReadMap(ref state, {MapFeatures(member)}, tmp{number}, {MapElementFeatures(member)}{MapSubSerializers(member, self)})";
                    if (member.IsReadOnly)
                    {
                        Line(sb, indent + 3, $"{readMap};");
                    }
                    else
                    {
                        Line(sb, indent + 3, $"tmp{number} = {readMap};");
                        Line(sb, indent + 3, $"if (tmp{number} != null) {Assign(contract, member, instance, target, $"tmp{number}")}");
                    }
                    return;
                }
                if (member.Repeated.Factory is not null)
                {
                    // same merge shape as a sub-message: the existing collection is passed in, and
                    // the result assigned back only if non-null
                    Line(sb, indent + 3, $"var tmp{number} = {target};");
                    var readRepeated = $"{Repeated(member)}.ReadRepeated(ref state, {RepeatedFeatures(member)}, tmp{number}{RepeatedSubSerializer(member, self)})";
                    if (member.IsReadOnly)
                    {
                        Line(sb, indent + 3, $"{readRepeated};");
                    }
                    else
                    {
                        Line(sb, indent + 3, $"tmp{number} = {readRepeated};");
                        // ImmutableArray<T> is a struct and can never be null
                        Line(sb, indent + 3, member.Repeated.IsValueType
                            ? Assign(contract, member, instance, target, $"tmp{number}")
                            : $"if (tmp{number} != null) {Assign(contract, member, instance, target, $"tmp{number}")}");
                    }
                    return;
                }
                // a lone wrapped value has its own API: the extra message layer is not expressible
                // as features on an ordinary read, so ReadAny/WriteAny handle it
                if (member.WrappedValue)
                {
                    Line(sb, indent + 3, $"var tmp{number} = {target};");
                    Line(sb, indent + 3, $"tmp{number} = state.ReadAny<{member.DeclaredTypeName}>({WrappedFeatures(member, forRead: true)}, tmp{number}{WrappedSerializer(member)});");
                    Line(sb, indent + 3, NullableTarget(member)
                        ? $"if (tmp{number} != null) {Assign(contract, member, instance, target, $"tmp{number}")}"
                        : Assign(contract, member, instance, target, $"tmp{number}"));
                    return;
                }
                switch (member.Kind)
                {
                    case ProtoMemberKind.Bool:
                    case ProtoMemberKind.SByte:
                    case ProtoMemberKind.Byte:
                    case ProtoMemberKind.Int16:
                    case ProtoMemberKind.UInt16:
                    case ProtoMemberKind.Int32:
                    case ProtoMemberKind.UInt32:
                    case ProtoMemberKind.Int64:
                    case ProtoMemberKind.UInt64:
                    case ProtoMemberKind.Single:
                    case ProtoMemberKind.Double:
                    case ProtoMemberKind.Char:
                    // the BCL types read through BclHelpers, which needs no hint and no cast
                    case ProtoMemberKind.DateTime:
                    case ProtoMemberKind.TimeSpan:
                    case ProtoMemberKind.Guid:
                    case ProtoMemberKind.Decimal:
                    case ProtoMemberKind.DateOnly:
                    case ProtoMemberKind.TimeOnly:
                    case ProtoMemberKind.IntPtr:
                    case ProtoMemberKind.UIntPtr:
                    case ProtoMemberKind.Parseable:
                        if (ScalarReadHint(member) is { } hint) Line(sb, indent + 3, hint);
                        Line(sb, indent + 3, Assign(contract, member, instance, target, ScalarRead(member, discard: member.IsReadOnly)));
                        break;
                    case ProtoMemberKind.Uri:
                        // an empty string means null, and the assignment is guarded on that rather
                        // than on the string itself - ReadString never returns null for a present field
                        Line(sb, indent + 3, $"var tmp{number} = state.ReadString();");
                        if (member.IsReadOnly)
                        {
                            Line(sb, indent + 3, $"_ = tmp{number}.Length != 0 ? {NewUri($"tmp{number}")} : null;");
                            break;
                        }
                        Line(sb, indent + 3, $"if (tmp{number}.Length != 0) "
                            + Assign(contract, member, instance, target, NewUri($"tmp{number}")));
                        break;
                    case ProtoMemberKind.String when member.IsReadOnly:
                        Line(sb, indent + 3, "state.ReadString();");
                        break;
                    case ProtoMemberKind.String:
                        // a null string leaves the existing value alone, matching ref-emit
                        Line(sb, indent + 3, $"var tmp{number} = state.ReadString();");
                        Line(sb, indent + 3, $"if (tmp{number} != null) {Assign(contract, member, instance, target, $"tmp{number}")}");
                        break;
                    case ProtoMemberKind.Bytes when member.OverwriteList:
                        // "bytes" is a scalar here, but OverwriteList still reaches BlobSerializer,
                        // where it selects AppendBytes(default) over AppendBytes(existing) - replace
                        // rather than append. RequiresOldValue is false with it set, so ref-emit does
                        // not read the current value at all; the explicit default() is because the
                        // AppendBytes overloads (array, Memory, ReadOnlyMemory, ArraySegment) make a
                        // bare `default` ambiguous.
                        if (member.IsReadOnly)
                        {
                            Line(sb, indent + 3, $"state.AppendBytes(default({member.DeclaredTypeName}));");
                            break;
                        }
                        Line(sb, indent + 3, $"var tmp{number} = state.AppendBytes(default({member.DeclaredTypeName}));");
                        Line(sb, indent + 3, member.MemberIsValueType
                            ? Assign(contract, member, instance, target, $"tmp{number}")
                            : $"if (tmp{number} != null) {Assign(contract, member, instance, target, $"tmp{number}")}");
                        break;
                    case ProtoMemberKind.Bytes:
                        // AppendBytes, not ReadBytes: repeated occurrences concatenate onto the
                        // existing array rather than replacing it
                        Line(sb, indent + 3, $"var tmp{number} = {target};");
                        if (member.IsReadOnly)
                        {
                            Line(sb, indent + 3, $"state.AppendBytes(tmp{number});");
                            break;
                        }
                        Line(sb, indent + 3, $"tmp{number} = state.AppendBytes(tmp{number});");
                        // a struct shape can never come back null, and cannot be compared to null
                        Line(sb, indent + 3, member.MemberIsValueType
                            ? Assign(contract, member, instance, target, $"tmp{number}")
                            : $"if (tmp{number} != null) {Assign(contract, member, instance, target, $"tmp{number}")}");
                        break;
                    // a scalar-category hand-written serializer: the member is not a sub-message at
                    // all, so it is read straight through the serializer with no ReadMessage framing
                    // ...and where the category could not be established at compile time, ReadAny
                    // makes the same choice at run time from the serializer's own Features - it
                    // switches to ReadMessage for a message and serializer.Read for a scalar, which
                    // is exactly the branch we would otherwise have had to bake in
                    case ProtoMemberKind.Message when member.SubSerializerDynamic:
                        // a Nullable<TStruct> target cannot seed the read directly - Read/ReadAny
                        // take the bare T, since the struct itself is never null - so unwrap here and
                        // let Assign() convert the (always non-null) result back on the way out
                        Line(sb, indent + 3, member.IsNullable
                            ? $"var tmp{number} = {target}.GetValueOrDefault();"
                            : $"var tmp{number} = {target};");
                        Line(sb, indent + 3, $"tmp{number} = state.ReadAny<{member.TypeName}>(default, tmp{number}, "
                            + $"{SubSerializer(member, self)});");
                        Line(sb, indent + 3, Assign(contract, member, instance, target, $"tmp{number}"));
                        break;
                    case ProtoMemberKind.Message when member.SubSerializerIsScalar:
                        Line(sb, indent + 3, member.IsNullable
                            ? $"var tmp{number} = {target}.GetValueOrDefault();"
                            : $"var tmp{number} = {target};");
                        Line(sb, indent + 3, $"tmp{number} = {SubSerializer(member, self)}.Read(ref state, tmp{number});");
                        Line(sb, indent + 3, Assign(contract, member, instance, target, $"tmp{number}"));
                        break;
                    // in all three cases the *existing* value is passed in, so repeated occurrences
                    // merge rather than replace; and the category is Repeated, not Message
                    case ProtoMemberKind.Message when member.IsNullable:
                        // a nullable struct message: seed from the current value, assign the result
                        // straight back - the read cannot produce a null
                        Line(sb, indent + 3, $"var tmp{number} = {target}.GetValueOrDefault();");
                        Line(sb, indent + 3, Assign(contract, member, instance, target, $"state.ReadMessage<{member.TypeName}>({Features}.CategoryRepeated, tmp{number}, {SubSerializer(member, self)})"));
                        break;
                    case ProtoMemberKind.Message when member.MemberIsValueType:
                        Line(sb, indent + 3, $"var tmp{number} = {target};");
                        Line(sb, indent + 3, Assign(contract, member, instance, target, $"state.ReadMessage<{member.TypeName}>({Features}.CategoryRepeated, tmp{number}, {SubSerializer(member, self)})"));
                        break;
                    case ProtoMemberKind.Message:
                        Line(sb, indent + 3, $"var tmp{number} = {target};");
                        if (member.IsReadOnly)
                        {
                            // the instance it already holds is what gets populated
                            Line(sb, indent + 3, $"state.ReadMessage<{member.TypeName}>({Features}.CategoryRepeated, tmp{number}, {SubSerializer(member, self)});");
                            break;
                        }
                        Line(sb, indent + 3, $"tmp{number} = state.ReadMessage<{member.TypeName}>({Features}.CategoryRepeated, tmp{number}, {SubSerializer(member, self)});");
                        Line(sb, indent + 3, $"if (tmp{number} != null) {Assign(contract, member, instance, target, $"tmp{number}")}");
                        break;
                }
                // the presence flag is set whatever the value was - note it sits *outside* any null
                // test the assignment itself carries
                if (member.SpecifiedMember is { } specified)
                {
                    Line(sb, indent + 3, $"{instance}.{specified} = true;");
                }
        }

        /// <summary>
        /// The <c>typeof</c> argument that keys a typed extension bag, or nothing for the untyped
        /// form. Each layer of a hierarchy gets its own, so the same field number can appear at more
        /// than one level without colliding.
        /// </summary>
        private static string ExtensionType(ProtoContractPlan contract)
            => contract.Extensible == ProtoExtensibleKind.Typed ? $", typeof({contract.TypeName})" : "";

        /// <summary>The member writes shared by <c>Write</c> and <c>WriteSubType</c>.</summary>
        private static void EmitWriteMembers(StringBuilder sb, int baseIndent, ProtoContractPlan contract,
            string instance = "value", bool raw = false, bool listAsSpan = false, bool immutableAsSpan = false,
            Dictionary<string, ProtoContractPlan>? measurable = null,
            string depth = "state.RawDepthBudget")
        {
            // Whether an enclosing Measure_ has already reserved slots for this contract's raw
            // sub-message members. A contract can be raw-WRITING without being MEASURABLE - it then
            // emits its body inline in ISerializer.Write with no measure prologue - and in that case
            // nothing has filled the slots, so each site must measure on demand. Under the old
            // dictionary this was dynamic (a TryGetValue miss, "the miss arm serves a root write");
            // positionally it is a compile-time question, and this is it. gap B38.
            var enclosingMeasured = measurable is not null && measurable.ContainsKey(contract.TypeName);
            foreach (var member in contract.Members)
            {
                // a conditional member wraps its whole write, and *replaces* the trivial-value guard
                // rather than adding to it - see WriteGuardSuppressed
                var condition = member.WriteCondition;
                if (condition is not null)
                {
                    Line(sb, baseIndent, $"if ({instance}.{condition})");
                    Line(sb, baseIndent, "{");
                }
                var indent = condition is null ? baseIndent : baseIndent + 1;

                var number = member.FieldNumber.ToString(CultureInfo.InvariantCulture);
                // hoist to a local, as ref-emit does; the member could be a computed property, so
                // this one is about CORRECTNESS - reading it twice could yield two answers
                Line(sb, indent, $"var tmp{number} = {MemberAccess(contract, member, instance)};");

                // WriteAny handles the null itself, so there is no guard - not even for a null int?
                if (member.WrappedValue && member.Repeated.Factory is null && member.Map.Factory is null)
                {
                    Line(sb, indent, $"state.WriteAny<{member.DeclaredTypeName}>({number}, {WrappedFeatures(member)}, tmp{number}{WrappedSerializer(member)});");
                    goto written;
                }

                if (member.Map.Factory is not null)
                {
                    Line(sb, indent, $"if (tmp{number} != null)");
                    Line(sb, indent, "{");
                    Line(sb, indent + 1, $"{Map(member)}.WriteMap(ref state, {number}, {MapFeatures(member)}, tmp{number}, {MapElementFeatures(member)}{MapSubSerializers(member)});");
                    Line(sb, indent, "}");
                    goto written;
                }

                if (member.Repeated.Factory is not null)
                {
                    var repeatedTarget = raw ? RawRepeatedMessageTarget(member, measurable) : null;
                    if (raw && RawPackedWritable(member, listAsSpan, immutableAsSpan))
                    {
                        var guard = NeedsNullGuard(member);
                        if (guard)
                        {
                            Line(sb, indent, $"if (tmp{number} != null)");
                            Line(sb, indent, "{");
                        }
                        EmitRawPackedWrite(sb, guard ? indent + 1 : indent, member, number, listAsSpan, immutableAsSpan);
                        if (guard) Line(sb, indent, "}");
                        goto written;
                    }
                    if (raw && (RawRepeatedWritable(member, immutableAsSpan) || repeatedTarget is not null))
                    {
                        // List<T> and T[] are reference types and need the guard; a value-type
                        // collection (ImmutableArray<T>) must NOT have it - see NeedsNullGuard.
                        // Empty falls out of the loop itself either way
                        var guard = NeedsNullGuard(member);
                        if (guard)
                        {
                            Line(sb, indent, $"if (tmp{number} != null)");
                            Line(sb, indent, "{");
                        }
                        EmitRawRepeatedWrite(sb, guard ? indent + 1 : indent, member, number, listAsSpan, immutableAsSpan, repeatedTarget, depth, enclosingMeasured);
                        if (guard) Line(sb, indent, "}");
                        goto written;
                    }
                    var writeRepeated = $"{Repeated(member)}.WriteRepeated(ref state, {number}, {RepeatedFeatures(member)}, tmp{number}{RepeatedSubSerializer(member)});";
                    if (member.Repeated.IsValueType)
                    {
                        Line(sb, indent, writeRepeated);
                        goto written;
                    }
                    Line(sb, indent, $"if (tmp{number} != null)");
                    Line(sb, indent, "{");
                    Line(sb, indent + 1, writeRepeated);
                    Line(sb, indent, "}");
                    goto written;
                }

                if (member.IsNullable && member.Kind == ProtoMemberKind.Message)
                {
                    Line(sb, indent, $"if (tmp{number}.HasValue)");
                    Line(sb, indent, "{");
                    if (member.SubSerializerIsScalar || member.SubSerializerDynamic)
                    {
                        // a scalar-category (or undetermined-category) hand-written serializer:
                        // WriteAny takes the framing off the serializer itself, exactly as the
                        // non-nullable case does - the struct is never null, so presence has to be
                        // decided here instead
                        Line(sb, indent + 1, $"state.WriteAny<{member.TypeName}>({number}, tmp{number}.GetValueOrDefault(), {SubSerializer(member)});");
                    }
                    else
                    {
                        // a nullable struct message: presence decides, and the unwrapped value goes
                        // straight to WriteMessage
                        Line(sb, indent + 1, $"state.WriteMessage<{member.TypeName}>({number}, {Features}.CategoryRepeated, tmp{number}.GetValueOrDefault(), {SubSerializer(member)});");
                    }
                    Line(sb, indent, "}");
                    goto written;
                }

                if (member.IsNullable)
                {
                    // presence decides, not value - so a nullable zero *is* written, unlike a plain
                    // zero. A declared default then nests inside, rather than replacing the test.
                    Line(sb, indent, $"if (tmp{number}.HasValue)");
                    Line(sb, indent, "{");
                    Line(sb, indent + 1, $"var val{number} = tmp{number}.GetValueOrDefault();");
                    // a write condition replaces the declared-default test (the HasValue unwrap
                    // above is not a guard, and stays)
                    if (member.WriteCondition is null && member.DefaultLiteral is { } nullableDefault)
                    {
                        Line(sb, indent + 1, $"if (val{number} != {nullableDefault})");
                        Line(sb, indent + 1, "{");
                        EmitScalarWrite(sb, indent + 2, member, number, $"val{number}", raw: raw);
                        Line(sb, indent + 1, "}");
                    }
                    else
                    {
                        EmitScalarWrite(sb, indent + 1, member, number, $"val{number}", raw: raw);
                    }
                    Line(sb, indent, "}");
                    goto written;
                }

                // a tuple writes every scalar unconditionally: it is rebuilt through a constructor,
                // so "absent" and "default" cannot be told apart on the way back in
                if (contract.IsTuple && member.Kind is not (ProtoMemberKind.String
                    or ProtoMemberKind.Bytes or ProtoMemberKind.Message))
                {
                    EmitScalarWrite(sb, indent, member, number, $"tmp{number}", raw: raw);
                    goto written;
                }

                switch (member.Kind)
                {
                    // the date/time types are written unconditionally - zero is a legitimate date,
                    // so there is no "trivial" value to skip. TimeSpan is *not* one of these: it is
                    // guarded against TimeSpan.Zero
                    case ProtoMemberKind.DateTime:
                    case ProtoMemberKind.DateOnly:
                    case ProtoMemberKind.TimeOnly:
                        EmitScalarWrite(sb, indent, member, number, $"tmp{number}", raw: raw);
                        break;

                    // int32 has a convenience overload that writes its own field header; everything
                    // else needs the header emitting separately, as ref-emit does.
                    //
                    // NOT on the raw path, and this was a real hole (Marc, spotted by reading a
                    // golden): WriteInt32Varint goes through the STATEFUL WriteFieldHeader - which
                    // encodes the tag from a field number at run time and sets WireType on the
                    // writer - and then ImplWriteVarint32, the virtual hop. So the single commonest
                    // member shape in protobuf was bypassing the whole raw write path: no
                    // pre-encoded constant tag, no span-direct store, and two writer-object state
                    // writes that cut 9 exists to eliminate. Raw emission takes the general branch
                    // below instead, which is WriteRawTag + WriteRawVarint64
                    case ProtoMemberKind.Int32 when !raw && member.DataFormat == ProtoDataFormat.Default:
                        var int32Write = $"state.WriteInt32Varint({number}, {ScalarValue(member, $"tmp{number}")});";
                        Line(sb, indent, member.IsRequired || member.WriteCondition is not null
                            ? int32Write
                            : $"if ({ScalarGuard(member, $"tmp{number}")}) {int32Write}");
                        break;
                    case ProtoMemberKind.Int32:
                    case ProtoMemberKind.Bool:
                    case ProtoMemberKind.SByte:
                    case ProtoMemberKind.Byte:
                    case ProtoMemberKind.Int16:
                    case ProtoMemberKind.UInt16:
                    case ProtoMemberKind.UInt32:
                    case ProtoMemberKind.Int64:
                    case ProtoMemberKind.UInt64:
                    case ProtoMemberKind.Single:
                    case ProtoMemberKind.Double:
                    case ProtoMemberKind.Char:
                    case ProtoMemberKind.TimeSpan:
                    case ProtoMemberKind.Guid:
                    case ProtoMemberKind.Decimal:
                    case ProtoMemberKind.IntPtr:
                    case ProtoMemberKind.UIntPtr:
                        // IsRequired means field presence, so there is no test to emit at all
                        if (member.IsRequired || member.WriteCondition is not null)
                        {
                            EmitScalarWrite(sb, indent, member, number, $"tmp{number}", raw: raw);
                            break;
                        }
                        Line(sb, indent, $"if ({ScalarGuard(member, $"tmp{number}")})");
                        Line(sb, indent, "{");
                        EmitScalarWrite(sb, indent + 1, member, number, $"tmp{number}", raw: raw);
                        Line(sb, indent, "}");
                        break;
                    case ProtoMemberKind.String when member.DefaultLiteral is { } declared
                        && !member.IsRequired && member.WriteCondition is null:
                        // the null test has to be explicit here: WriteString skips nulls itself, but
                        // we must not compare a null against the declared default. A ShouldSerialize
                        // condition (or IsRequired) REPLACES this guard rather than nesting it - the
                        // scalar paths already did that, and this case missing the same treatment
                        // silently dropped a present-but-default string (FieldDescriptorProto's
                        // default_value = "" under ShouldSerializeDefaultValue, found by SchemaTests
                        // the moment the descriptor model was regenerated) - so those shapes fall
                        // through to the plain unguarded WriteString below.
                        Line(sb, indent, $"if (tmp{number} != null && tmp{number} != {declared})");
                        Line(sb, indent, "{");
                        if (raw)
                        {
                            Line(sb, indent + 1, $"state.WriteRawTag(({member.FieldNumber} << 3) | 2);  // {member.Name}");
                            Line(sb, indent + 1, $"state.WriteRawString(tmp{number});");
                        }
                        else
                        {
                            Line(sb, indent + 1, $"state.WriteString({number}, tmp{number});");
                        }
                        Line(sb, indent, "}");
                        break;
                    case ProtoMemberKind.String when raw:
                        // the raw form needs the null test the stateful WriteString(int, string)
                        // performed internally; the bytes are identical
                        Line(sb, indent, $"if (tmp{number} != null)");
                        Line(sb, indent, "{");
                        Line(sb, indent + 1, $"state.WriteRawTag(({member.FieldNumber} << 3) | 2);  // {member.Name}");
                        Line(sb, indent + 1, $"state.WriteRawString(tmp{number});");
                        Line(sb, indent, "}");
                        break;
                    case ProtoMemberKind.String:
                        // no null test: WriteString(int, string) skips nulls itself
                        Line(sb, indent, $"state.WriteString({number}, tmp{number});");
                        break;
                    case ProtoMemberKind.Parseable when !member.MemberIsValueType:
                        // a reference type has to be null-tested: ToString() would throw, and the
                        // bare WriteString(string) overload does not skip nulls the way the
                        // field-number one does
                        Line(sb, indent, $"if (tmp{number} != null)");
                        Line(sb, indent, "{");
                        EmitScalarWrite(sb, indent + 1, member, number, $"tmp{number}", raw: raw);
                        Line(sb, indent, "}");
                        break;
                    case ProtoMemberKind.Parseable:
                        // a value type is never null, and has no trivial value to compare against
                        EmitScalarWrite(sb, indent, member, number, $"tmp{number}", raw: raw);
                        break;
                    case ProtoMemberKind.Uri:
                        // the null test is explicit, unlike a plain string: WriteString(int, string)
                        // would skip a null itself, but OriginalString would already have thrown
                        Line(sb, indent, $"if (tmp{number} != null)");
                        Line(sb, indent, "{");
                        if (raw)
                        {
                            Line(sb, indent + 1, $"state.WriteRawTag(({member.FieldNumber} << 3) | 2);  // {member.Name}");
                            Line(sb, indent + 1, $"state.WriteRawString(tmp{number}.OriginalString);");
                        }
                        else
                        {
                            Line(sb, indent + 1, $"state.WriteString({number}, tmp{number}.OriginalString);");
                        }
                        Line(sb, indent, "}");
                        break;
                    // the struct shapes - ArraySegment<byte>, Memory<byte>, ReadOnlyMemory<byte> -
                    // can never be null, so ref-emit writes them unguarded. Not merely tidier:
                    // `!= null` does not compile against Memory<byte> at all
                    case ProtoMemberKind.Bytes when member.MemberIsValueType:
                        Line(sb, indent, $"state.WriteFieldHeader({number}, global::ProtoBuf.WireType.String);");
                        Line(sb, indent, $"state.WriteBytes(tmp{number});");
                        break;
                    case ProtoMemberKind.Bytes when raw && !member.MemberIsValueType:
                        // byte[] only: the struct storage shapes (Memory and friends) keep the
                        // classic overload resolution below
                        Line(sb, indent, $"if (tmp{number} != null)");
                        Line(sb, indent, "{");
                        Line(sb, indent + 1, $"state.WriteRawTag(({member.FieldNumber} << 3) | 2);  // {member.Name}");
                        Line(sb, indent + 1, $"state.WriteRawBytes(tmp{number});");
                        Line(sb, indent, "}");
                        break;
                    case ProtoMemberKind.Bytes:
                        // unlike WriteString, WriteBytes(byte[]) neither skips nulls nor writes its
                        // own field header, so both are explicit here
                        Line(sb, indent, $"if (tmp{number} != null)");
                        Line(sb, indent, "{");
                        Line(sb, indent + 1, $"state.WriteFieldHeader({number}, global::ProtoBuf.WireType.String);");
                        Line(sb, indent + 1, $"state.WriteBytes(tmp{number});");
                        Line(sb, indent, "}");
                        break;
                    // a scalar-category hand-written serializer frames the member by its own wire
                    // type, not as a sub-message. The wire type comes off the serializer's Features
                    // at runtime rather than being baked in: it is the serializer's to declare, and
                    // GetWireType() is public precisely for this
                    case ProtoMemberKind.Message when member.SubSerializerIsScalar || member.SubSerializerDynamic:
                        // WriteAny(int, T, ISerializer<T>) takes the features off the serializer and
                        // frames accordingly, which is exactly what is wanted and is *public* - the
                        // GetWireType extension that would let us write the header ourselves lives on
                        // an internal class, so generated code cannot reach it
                        Line(sb, indent, $"state.WriteAny<{member.TypeName}>({number}, tmp{number}, "
                            + $"{SubSerializer(member)});");
                        break;
                    case ProtoMemberKind.Message when raw && RawNativeMessageTarget(member, measurable) is { } target:
                    {
                        // measure-first (notes/nano-writer.md): an exact length prefix from the
                        // target's Measure_, then its RawWrite_ called directly - no stateful
                        // sub-message engine, no reserve-and-patch. The null guard is explicit
                        // where WriteMessage skipped nulls itself; a struct target is never null
                        // and was always written, so it stays unconditional. Only the measure
                        // walk is depth-budgeted: the write recursion that follows traverses the
                        // graph the measure just proved finite.
                        var targetName = Sanitise(member.TypeName!);
                        var inner = indent;
                        if (!target.IsValueType)
                        {
                            Line(sb, indent, $"if (tmp{number} != null)");
                            Line(sb, indent, "{");
                            inner++;
                        }
                        if (member.DataFormat == ProtoDataFormat.Group)
                        {
                            // THE point of a group, and the whole of gap B14: framed by a
                            // start/end tag pair rather than a length prefix, so there is no
                            // length to compute and the measure call is not merely cheap - it is
                            // ABSENT. A fully-grouped tree therefore writes without a single
                            // measure pass. The read side pays for it by scanning for the
                            // sentinel instead of being able to skip a known span.
                            Line(sb, inner, $"state.WriteRawTag(({member.FieldNumber} << 3) | 3);  // {member.Name} (start group)");
                            Line(sb, inner, $"RawWrite_{targetName}(ref state, tmp{number}, {depth});");
                            Line(sb, inner, $"state.WriteRawTag(({member.FieldNumber} << 3) | 4);  // {member.Name} (end group)");
                            if (!target.IsValueType) Line(sb, indent, "}");
                            break;
                        }
                        Line(sb, inner, $"state.WriteRawTag(({member.FieldNumber} << 3) | 2);  // {member.Name}");
                        // the eager measure pass already put this child's length in a slot;
                        // read it back by position. Both walks are pre-order over the same guards,
                        // so a bare Next() lands on the right one - no probe, no hash, no index
                        // arithmetic. The struct carve-out that used to sit here ("no reference
                        // identity to key on") went with the keying: positionally a struct child
                        // is an ordinary slot. gap B38.
                        if (enclosingMeasured)
                        {
                            Line(sb, inner, "len = state.RawSlots.Next();");
                        }
                        else
                        {
                            // nothing measured us, so measure this child now: one walk that fills
                            // its whole run, after which RawWrite_ consumes it slot by slot. Still
                            // linear - the re-measure that makes a lazy scheme O(n^2) would need
                            // EVERY level to do this, and below here everything is slot-driven
                            Line(sb, inner, $"var mark{number} = state.RawSlots.Mark();");
                            Line(sb, inner, $"len = Measure_{targetName}(tmp{number}, state.RawDepthBudget, state.RawSlots);");
                            Line(sb, inner, $"state.RawSlots.SeekTo(mark{number});");
                        }
                        Line(sb, inner, $"state.WriteRawVarint64((ulong)len);");
                        Line(sb, inner, $"{DriftCapture};");
                        Line(sb, inner, $"RawWrite_{targetName}(ref state, tmp{number}, {depth});");
                        Line(sb, inner, $"{DriftAssert}, \"{member.Name}\");");
                        if (!target.IsValueType) Line(sb, indent, "}");
                        break;
                    }
                    case ProtoMemberKind.Message:
                        // likewise WriteMessage/WriteGroup(int, ...) skip nulls themselves. Group
                        // affects the *write* only - its read is an ordinary ReadMessage
                        var writeMessage = member.DataFormat == ProtoDataFormat.Group ? "WriteGroup" : "WriteMessage";
                        Line(sb, indent, $"state.{writeMessage}<{member.TypeName}>({number}, {Features}.CategoryRepeated, tmp{number}, {SubSerializer(member)});");
                        break;
                }

            written:
                if (condition is not null) Line(sb, baseIndent, "}");
            }

            // the kept-but-unrecognised fields go out after every declared member
            if (contract.Extensible != ProtoExtensibleKind.None)
            {
                Line(sb, baseIndent, $"state.AppendExtensionData(value{ExtensionType(contract)});");
            }
        }

        /// <summary>
        /// A contract in a <c>[ProtoInclude]</c> hierarchy.
        /// </summary>
        /// <remarks>
        /// Both directions route through the <em>root</em>'s <c>ISubTypeSerializer</c>: that is what
        /// walks down the chain, writing each layer's own members and nesting the next layer inside a
        /// sub-type marker. So <c>ISerializer&lt;T&gt;</c> is a pair of one-line delegations for every
        /// type in the hierarchy, and the real work is in the sub-type pair, which sees only the
        /// members this layer declares.
        /// </remarks>
        private static void EmitSubTypeContract(StringBuilder sb, int indent, ProtoContractPlan contract, string root,
            bool raw = false, bool rawWrite = false, bool listAsSpan = false, bool immutableAsSpan = false,
            Dictionary<string, ProtoContractPlan>? measurable = null)
        {
            var self = $"{Serializers}.ISerializer<{contract.TypeName}>";
            var sub = $"{Serializers}.ISubTypeSerializer<{contract.TypeName}>";
            var rootSub = $"{Serializers}.ISubTypeSerializer<{root}>";
            // the root's ReadSubType returns the root type, so anything below it needs a cast back
            var cast = contract.TypeName == root ? "" : $"({contract.TypeName})";

            Line(sb, indent, $"{contract.TypeName} {self}.Read(ref global::ProtoBuf.ProtoReader.State state, {contract.TypeName} value)");
            Line(sb, indent + 1, $"=> {cast}(({rootSub})this).ReadSubType(ref state, "
                + $"global::ProtoBuf.Serializers.SubTypeState<{root}>.Create(state.Context, value));");
            sb.AppendLine();

            Line(sb, indent, $"void {self}.Write(ref global::ProtoBuf.ProtoWriter.State state, {contract.TypeName} value)");
            Line(sb, indent + 1, $"=> (({rootSub})this).WriteSubType(ref state, value);");
            sb.AppendLine();

            Line(sb, indent, $"void {sub}.WriteSubType(ref global::ProtoBuf.ProtoWriter.State state, {contract.TypeName} value)");
            Line(sb, indent, "{");
            if (contract.SubTypes.Count != 0)
            {
                // the runtime type decides which layer to nest; anything else is a type the model
                // was never told about
                Line(sb, indent + 1, "if (global::ProtoBuf.Meta.TypeModel.IsSubType(value))");
                Line(sb, indent + 1, "{");
                var keyword = "if";
                foreach (var subType in contract.SubTypes)
                {
                    var local = $"sub{subType.FieldNumber.ToString(CultureInfo.InvariantCulture)}";
                    Line(sb, indent + 2, $"{keyword} (value is {subType.TypeName} {local})");
                    Line(sb, indent + 2, "{");
                    var tag = subType.FieldNumber.ToString(CultureInfo.InvariantCulture);
                    if (subType.IsGroup)
                    {
                        // WriteSubType(int, ...) hard-codes WireType.String, so a grouped sub-type
                        // writes its own header and uses the overload that takes no field number
                        Line(sb, indent + 3, $"state.WriteFieldHeader({tag}, global::ProtoBuf.WireType.StartGroup);");
                        Line(sb, indent + 3, $"state.WriteSubType({local}, this);");
                    }
                    else
                    {
                        Line(sb, indent + 3, $"state.WriteSubType({tag}, {local}, this);");
                    }
                    Line(sb, indent + 2, "}");
                    keyword = "else if";
                }
                if (!contract.IgnoreUnknownSubTypes)
                {
                    Line(sb, indent + 2, "else");
                    Line(sb, indent + 2, "{");
                    Line(sb, indent + 3, "global::ProtoBuf.Meta.TypeModel.ThrowUnexpectedSubtype(value);");
                    Line(sb, indent + 2, "}");
                }
                Line(sb, indent + 1, "}");
            }
            else if (!contract.IsSealed && !contract.IgnoreUnknownSubTypes)
            {
                Line(sb, indent + 1, "global::ProtoBuf.Meta.TypeModel.ThrowUnexpectedSubtype(value);");
            }
            var subTypeMembers = new StringBuilder();
            EmitWriteMembers(subTypeMembers, indent + 1, contract, raw: rawWrite, listAsSpan: listAsSpan, immutableAsSpan: immutableAsSpan, measurable: measurable);
            AppendFoldingLengthTemp(sb, indent + 1, subTypeMembers, "len");
            Line(sb, indent, "}");
            sb.AppendLine();

            // the raw pass proxies here exactly as ISerializer.Read proxies to RawRead_: the
            // static is the live body, and this delegation is what the stateful machinery
            // (ReadBaseType, the sub-type narrowing) resolves through the model
            if (raw)
            {
                Line(sb, indent, $"{contract.TypeName} {sub}.ReadSubType(ref global::ProtoBuf.ProtoReader.State state, "
                    + $"global::ProtoBuf.Serializers.SubTypeState<{contract.TypeName}> value)");
                Line(sb, indent + 1, $"=> RawReadSub_{Sanitise(contract.TypeName)}(ref state, value);");
                return;
            }
            Line(sb, indent, $"{contract.TypeName} {sub}.ReadSubType(ref global::ProtoBuf.ProtoReader.State state, "
                + $"global::ProtoBuf.Serializers.SubTypeState<{contract.TypeName}> value)");
            Line(sb, indent, "{");
            EmitReadLoop(sb, indent + 1, contract, "obj", contract.SubTypes, fromSubTypeState: true);
            Line(sb, indent + 1, "return value.Value;");
            Line(sb, indent, "}");
        }

        /// <summary>
        /// The enum types that need an <c>ISerializerProxy</c>, keyed by type name.
        /// </summary>
        /// <remarks>
        /// Only *repeated* enums need one. A plain enum member is written inline (cast to its
        /// underlying type), but <c>RepeatedSerializer</c> resolves an <c>ISerializer&lt;TEnum&gt;</c>
        /// from the model instead â€” so without this a repeated enum throws "no serializer for type"
        /// at runtime.
        /// </remarks>
        private static SortedDictionary<string, ProtoMemberKind> EnumProxies(ProtoModelPlan plan)
        {
            var result = new SortedDictionary<string, ProtoMemberKind>(StringComparer.Ordinal);

            // an enum seeded as a contract in its own right is served by the same proxy
            foreach (var seeded in plan.Enums)
            {
                if (seeded.TypeName is { } name) result[name] = seeded.Underlying;
            }

            foreach (var contract in plan.Contracts)
            {
                foreach (var member in contract.Members)
                {
                    // a repeated enum resolves its serializer from the model, and so does a lone
                    // [NullWrappedValue] one - ReadAny/WriteAny take an ISerializer<TEnum?>
                    // ...and so does each side of a map, for the same reason
                    if (member.Map.Factory is not null)
                    {
                        if (member.Map.KeyEnumTypeName is { } key) result[key] = member.Map.KeyKind;
                        if (member.Map.ValueEnumTypeName is { } value) result[value] = member.Map.ValueKind;
                    }
                    if (member.Repeated.Factory is null && !member.WrappedValue) continue;
                    if (member.EnumTypeName is { } name) result[name] = member.Kind;
                }
            }
            return result;
        }

        /// <summary>
        /// Collection types the model must serve an <c>ISerializer&lt;TCollection&gt;</c> for: a map
        /// with a repeated value resolves one from the model rather than taking it inline.
        /// </summary>
        private static SortedDictionary<string, string> CollectionProxies(ProtoModelPlan plan)
        {
            var result = new SortedDictionary<string, string>(StringComparer.Ordinal);
            foreach (var contract in plan.Contracts)
            {
                foreach (var member in contract.Members)
                {
                    if (member.Map.ValueSerializerFactory is { } factory
                        && member.Map.ValueTypeName is { } name)
                    {
                        result[name] = factory;
                    }
                }
            }
            return result;
        }

        private static void EmitCollectionProxies(StringBuilder sb, int indent, ProtoModelPlan plan)
        {
            foreach (var pair in CollectionProxies(plan))
            {
                sb.AppendLine();
                Line(sb, indent, $"{Serializers}.ISerializer<{pair.Key}> {Serializers}.ISerializerProxy<{pair.Key}>.Serializer");
                Line(sb, indent + 1, $"=> {pair.Value};");
            }
        }

        private static void EmitEnumProxies(StringBuilder sb, int indent, ProtoModelPlan plan)
        {
            foreach (var pair in EnumProxies(plan))
            {
                // EnumSerializer<TEnum> implements both ISerializer<TEnum> and ISerializer<TEnum?>,
                // so the nullable proxy returns the very same instance
                var create = $"{Serializers}.EnumSerializer.Create{UnderlyingName(pair.Value)}<{pair.Key}>()";
                sb.AppendLine();
                Line(sb, indent, $"{Serializers}.ISerializer<{pair.Key}> {Serializers}.ISerializerProxy<{pair.Key}>.Serializer");
                Line(sb, indent + 1, $"=> {create};");
                sb.AppendLine();
                Line(sb, indent, $"{Serializers}.ISerializer<{pair.Key}?> {Serializers}.ISerializerProxy<{pair.Key}?>.Serializer");
                Line(sb, indent + 1, $"=> {create};");
            }
        }

        /// <summary>The <c>EnumSerializer.CreateXxx</c> suffix for an enum's underlying type.</summary>
        private static string UnderlyingName(ProtoMemberKind kind) => kind switch
        {
            ProtoMemberKind.SByte => "SByte",
            ProtoMemberKind.Byte => "Byte",
            ProtoMemberKind.Int16 => "Int16",
            ProtoMemberKind.UInt16 => "UInt16",
            ProtoMemberKind.UInt32 => "UInt32",
            ProtoMemberKind.Int64 => "Int64",
            ProtoMemberKind.UInt64 => "UInt64",
            _ => "Int32",
        };

        /// <summary>The <c>RepeatedSerializer</c> factory for a collection member.</summary>
        private static string Repeated(ProtoMemberPlan member)
        {
            var arguments = member.Repeated.TakesCollectionType
                ? $"<{member.DeclaredTypeName}, {member.ElementTypeName}>"
                : $"<{member.ElementTypeName}>";
            return $"{Serializers}.RepeatedSerializer.{member.Repeated.Factory}{arguments}()";
        }

        /// <summary>
        /// The features for a repeated member: the *element's* wire type, plus the packed opt-out.
        /// </summary>
        /// <remarks>
        /// Packing is a compile-time decision, not a runtime one: ref-emit bakes
        /// <c>OptionPackedDisabled</c> into the constant and simply omits it when
        /// <c>[ProtoMember(IsPacked = true)]</c> is set. Unpacked is the default, and that named
        /// argument is not supported yet, so this is always the disabled form.
        /// </remarks>
        private static string RepeatedFeatures(ProtoMemberPlan member)
        {
            // An element served by a hand-written serializer that is scalar - or whose category we
            // could not establish - states *no* wire type, and lets WriteRepeated/ReadRepeated take
            // it from the element serializer: both call features.InheritFrom(serializer.Features),
            // which fills in the category and the wire type precisely when they were not specified,
            // and reads the category off the serializer regardless. So the same deferral the unary
            // form gets from WriteAny/ReadAny is available here after all; it was only ever baked in
            // because we chose to bake it in.
            var result = member.SubSerializerIsScalar || member.SubSerializerDynamic
                ? null
                : $"{Features}.{ElementWireType(member)}";
            void Add(string token) => result = result is null ? token : result + " | " + token;
            if (!member.IsPacked) Add($"{Features}.OptionPackedDisabled");
            if (member.WrappedValue)
            {
                // field presence in the wrapper is what separates a null element from a zero one
                Add($"{Features}.OptionWrappedValue");
                if (member.WrappedValueGroup) Add($"{Features}.OptionWrappedValueGroup");
                Add($"{Features}.OptionWrappedValueFieldPresence");
            }
            if (member.WrappedCollection)
            {
                Add($"{Features}.OptionWrappedCollection");
                if (member.WrappedCollectionGroup) Add($"{Features}.OptionWrappedCollectionGroup");
            }
            if (member.OverwriteList) Add($"{Features}.OptionClearCollection");
            // every path adds OptionPackedDisabled unless IsPacked, so null here means "packed, and
            // deferring the wire type" - which is still a legal features value
            return result ?? "default";
        }

        private static string ElementWireType(ProtoMemberPlan member) => member.DataFormat switch
        {
            ProtoDataFormat.ZigZag => "WireTypeSignedVarint",
            // on a *collection* Group is not the write-only change it is on a scalar member: it goes
            // into the element features, so the element carries group markers in both directions.
            // Only a message element can be grouped - protobuf-net refuses a grouped scalar
            // collection outright, which GroupedScalarList pins
            ProtoDataFormat.Group => "WireTypeStartGroup",
            // a compatibility-level BCL element expresses its format through the *element serializer*
            // (GetInbuiltSerializer takes it), not through the wire type - a FixedSize Guid at level
            // 300 is GuidBytes, which is still length-prefixed. Applying the format here as well
            // produced a Fixed32 header over a length-prefixed body
            ProtoDataFormat.FixedSize when !IsBclKind(member.Kind)
                => Is64Bit(member.Kind) ? "WireTypeFixed64" : "WireTypeFixed32",
            _ => KindWireType(member.Kind),
        };

        /// <summary>
        /// The wire type a kind carries when no <c>DataFormat</c> is selecting one — used for
        /// collection elements and for each side of a map, where the format does not apply.
        /// </summary>
        /// <remarks>
        /// The compatibility-level BCL types are the trap here: they are length-prefixed, not
        /// varints, so a <c>List&lt;DateTime&gt;</c> whose element defaulted to <c>WireTypeVarint</c>
        /// disagreed with ref-emit on the wire. <c>DateOnly</c>/<c>TimeOnly</c> go the other way —
        /// they use <c>BclHelpers</c> but under a varint header — which is why this cannot simply
        /// ask "is it a BCL kind".
        /// </remarks>
        private static string KindWireType(ProtoMemberKind kind) => kind switch
        {
            ProtoMemberKind.Single => "WireTypeFixed32",
            ProtoMemberKind.Double => "WireTypeFixed64",
            ProtoMemberKind.String or ProtoMemberKind.Bytes or ProtoMemberKind.Message
                or ProtoMemberKind.Uri or ProtoMemberKind.Parseable
                or ProtoMemberKind.DateTime or ProtoMemberKind.TimeSpan
                or ProtoMemberKind.Guid or ProtoMemberKind.Decimal
                // a map nested as a map value is length-prefixed like any other sub-message
                or ProtoMemberKind.Map => "WireTypeString",
            _ => "WireTypeVarint",
        };

        /// <summary>
        /// The features for a lone <c>[NullWrappedValue]</c>: the value's own wire type plus the
        /// wrapping. Note there is no field-presence flag here â€” that is a collection concern, where
        /// a null and a zero would otherwise be indistinguishable.
        /// </summary>
        /// <param name="forRead">
        /// The read takes the wire type from the field header, so it passes the wrapping alone;
        /// only the write states it.
        /// </param>
        private static string WrappedFeatures(ProtoMemberPlan member, bool forRead = false)
        {
            var result = forRead
                ? $"{Features}.OptionWrappedValue"
                : $"{Features}.{ElementWireType(member)} | {Features}.OptionWrappedValue";
            if (member.WrappedValueGroup) result += $" | {Features}.OptionWrappedValueGroup";
            return result;
        }

        /// <summary>
        /// Nothing: <c>ReadAny</c>/<c>WriteAny</c> resolve the serializer themselves.
        /// </summary>
        /// <remarks>
        /// Ref-emit passes <c>this as ISerializer&lt;TEnum?&gt;</c> here, which we cannot: our
        /// services type implements <c>ISerializerProxy&lt;TEnum?&gt;</c> rather than
        /// <c>ISerializer&lt;TEnum?&gt;</c>, and C# rejects that cast on a sealed type where IL
        /// merely yields null. Both end up in the same place â€” <c>serializer ??=
        /// TypeModel.GetSerializer&lt;T&gt;(Model)</c>, which resolves the proxy through the model.
        /// </remarks>
        private static string WrappedSerializer(ProtoMemberPlan member) => "";

        /// <summary>Does the read need a null test before assigning back?</summary>
        private static bool NullableTarget(ProtoMemberPlan member)
            => member.Kind is ProtoMemberKind.String or ProtoMemberKind.Bytes;

        /// <summary>
        /// The serializer to hand a nested message: ourselves, unless the contract declares a
        /// hand-written one, in which case we never implement <c>ISerializer&lt;T&gt;</c> for it.
        /// </summary>
        /// <summary>
        /// Assert, at runtime, that each hand-written serializer's category is the one we generated
        /// for. It is the single thing about an external serializer that changes the emitted shape
        /// and that cannot be checked while generating — <c>[ProtoContract(IsScalar)]</c> may name a
        /// serializer in another assembly, whose <c>Features</c> we can only take on trust.
        /// </summary>
        /// <remarks>
        /// In the services type's constructor rather than in the proxy: members call
        /// <c>SerializerCache.Get&lt;X, T&gt;()</c> directly, so the proxy is not on the path at all
        /// and an assert there never runs — which is how the first attempt at this failed silently.
        /// The constructor runs once per model, and <c>Debug.Assert</c> is
        /// <c>[Conditional("DEBUG")]</c> resolved against the *consumer's* compilation, so a release
        /// build pays nothing but an empty constructor.
        /// </remarks>
        private static void EmitExternalCategoryAsserts(StringBuilder sb, int indent, ProtoModelPlan plan)
        {
            var external = plan.Contracts
                // only where the category was actually established: the assert exists to catch a
                // *stated* IsScalar that contradicts the serializer, and where nothing was stated
                // there is nothing to contradict - the framing is decided from these same Features
                // at run time instead
                .Where(static x => x.ExternalSerializerTypeName is not null
                    && x.ExternalSerializerCategoryKnown).ToList();
            if (external.Count == 0) return;

            Line(sb, indent, $"public {ServicesTypeName}()");
            Line(sb, indent, "{");
            foreach (var contract in external)
            {
                var expected = contract.ExternalSerializerIsScalar ? "CategoryScalar" : "CategoryMessage";
                var fix = contract.ExternalSerializerIsScalar ? "false" : "true";
                Line(sb, indent + 1, "global::System.Diagnostics.Debug.Assert(");
                Line(sb, indent + 2, $"({Serializers}.SerializerCache.Get<{contract.ExternalSerializerTypeName}, "
                    + $"{contract.TypeName}>().Features");
                Line(sb, indent + 3, $"& ({Features}.CategoryScalar | {Features}.CategoryMessage))");
                Line(sb, indent + 3, $"== {Features}.{expected},");
                Line(sb, indent + 2, $"\"{Simplify(contract.TypeName)} is generated as {expected}, but its "
                    + $"serializer disagrees; \"");
                Line(sb, indent + 3, $"+ \"set IsScalar = {fix} on its [ProtoContract] or [ProtoSerializer] "
                    + $"declaration, or correct the serializer.\");");
            }
            Line(sb, indent, "}");
            sb.AppendLine();
        }

        private static string SubSerializer(ProtoMemberPlan member, string self = "this") => member.SubSerializer ?? self;

        /// <summary>A message element needs a serializer passed along; a scalar does not.</summary>
        private static string RepeatedSubSerializer(ProtoMemberPlan member, string self = "this")
        {
            if (member.Kind == ProtoMemberKind.Message) return $", {SubSerializer(member, self)}";
            // a compatibility-level BCL element does not use the inbuilt default once the level or
            // format selects another form, so ref-emit hands the collection an explicit serializer.
            // CompatibilityLevel is already the *effective* one for the element
            return InbuiltSerializer(member.Kind, member.ElementTypeName,
                member.CompatibilityLevel, member.DataFormat) is { } inbuilt ? $", {inbuilt}" : "";
        }

        /// <summary>
        /// <c>TypeModel.GetInbuiltSerializer&lt;T&gt;(level, format)</c> for an element whose
        /// compatibility level selects something other than the level-200 form, or null when the
        /// inbuilt default already serves — which is what ref-emit passes in that case.
        /// </summary>
        /// <remarks>
        /// This is <c>CompilerContext.LoadSelfAsService</c>'s rule: it emits the call whenever
        /// <c>GetInbuiltSerializer</c> would return something that is not <c>PrimaryTypeProvider</c>,
        /// and a null reference otherwise. Only the four compatibility-level types have a second
        /// form to select, so only they can produce one.
        /// </remarks>
        private static string? InbuiltSerializer(ProtoMemberKind kind, string? typeName,
            int compatibilityLevel, ProtoDataFormat format)
        {
            if (typeName is null) return null;
            if (kind is not (ProtoMemberKind.DateTime or ProtoMemberKind.TimeSpan
                or ProtoMemberKind.Guid or ProtoMemberKind.Decimal))
            {
                return null;
            }
            if (compatibilityLevel <= 200) return null;
            return $"global::ProtoBuf.Meta.TypeModel.GetInbuiltSerializer<{typeName}>("
                + $"{CompatibilityLevelLiteral(compatibilityLevel)}, {DataFormatLiteral(format)})";
        }

        /// <summary>
        /// <c>ValueMember.GetEffectiveCompatibilityLevel</c>: at or below 200, <c>WellKnown</c>
        /// promotes to 240; above that it means nothing.
        /// </summary>
        private static int EffectiveCompatibilityLevel(int level, ProtoDataFormat format)
            => level > 200 ? level : format == ProtoDataFormat.WellKnown ? 240 : 200;

        private static string CompatibilityLevelLiteral(int level)
            => $"global::ProtoBuf.CompatibilityLevel.Level{level.ToString(CultureInfo.InvariantCulture)}";

        private static string DataFormatLiteral(ProtoDataFormat format)
            => "global::ProtoBuf.DataFormat." + format switch
            {
                ProtoDataFormat.Group => "Group",
                ProtoDataFormat.FixedSize => "FixedSize",
                ProtoDataFormat.ZigZag => "ZigZag",
                // TwosComplement is deliberately absent from ProtoDataFormat: it is byte-identical
                // to Default for every type we handle, so it maps onto it
                ProtoDataFormat.WellKnown => "WellKnown",
                _ => "Default",
            };

        /// <summary>
        /// The statement that stores a value into a member.
        /// </summary>
        /// <remarks>
        /// C# forbids assigning an <c>init</c>-only property after construction; IL does not, which
        /// is why ref-emit simply calls the setter. <c>[UnsafeAccessor]</c> is the equivalent, and
        /// unlike reflection it is resolved at publish time, so it stays AOT-safe.
        /// </remarks>
        private static string Assign(ProtoContractPlan contract, ProtoMemberPlan member,
            string instance, string target, string expression)
        {
            // a getter-only member has nowhere to put the result, so the read runs for its side
            // effects alone - which is the whole mechanism for a getter-only collection
            if (member.IsReadOnly) return $"{expression};";

            if (!member.UsesAccessor || contract.IsTuple) return $"{target} = {expression};";

            // the *instance*, not the literal "value": in a sub-type read the instance is hoisted
            // into a per-case local and `value` is the SubTypeState<T> wrapper, so hard-coding it
            // passed the wrapper to the accessor and would not compile
            var self = contract.IsValueType ? $"ref {instance}" : instance;

            // a field accessor hands back a ref, so the store is an ordinary assignment
            return member.AccessorField is null
                ? $"{AccessorName(contract, member)}({self}, {expression});"
                : $"{AccessorName(contract, member)}({self}) = {expression};";
        }

        /// <summary>
        /// How the member is named in generated code - normally ${instance}.{name}, but a non-public
        /// field can only be reached through its <c>[UnsafeAccessor]</c>, which serves both directions
        /// since it hands back a <c>ref</c>.
        /// </summary>
        private static string MemberAccess(ProtoContractPlan contract, ProtoMemberPlan member, string instance)
            => member.AccessorReads
                ? $"{AccessorName(contract, member)}({(contract.IsValueType ? "ref " : "")}{instance})"
                : $"{instance}.{Escape(member.Name)}";

        /// <summary>
        /// A member name as it has to appear in generated C#.
        /// </summary>
        /// <remarks>
        /// <see cref="Microsoft.CodeAnalysis.ISymbol.Name"/> is the *metadata* name, so a member the
        /// consumer declared as <c>@case</c> comes back as <c>case</c> and has to be re-escaped
        /// before it can be emitted. Code-first contracts almost never hit this — nobody writes
        /// <c>public int @case</c> by choice — but <c>.proto</c>-generated DTOs hit it routinely,
        /// since a schema field may be named after any C# keyword and protogen escapes it for them.
        /// Only *reserved* keywords need this; a contextual keyword such as <c>value</c> is already
        /// a legal identifier, which is what <see cref="SyntaxFacts.GetKeywordKind"/> distinguishes.
        /// Note the <c>[UnsafeAccessor]</c> <c>Name</c> argument is the opposite case — it is matched
        /// against metadata, so it takes the *unescaped* name.
        /// </remarks>
        private static string Escape(string name)
            => SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;

        /// <summary>The accessor that calls a contract's non-public parameterless constructor.</summary>
        private static string ConstructorAccessorName(ProtoContractPlan contract)
            => "Create_" + Sanitise(contract.TypeName);

        /// <summary>A name unique across the whole services type, since the accessors all live on it.</summary>
        private static string AccessorName(ProtoContractPlan contract, ProtoMemberPlan member)
            // the member name needs sanitising as much as the type's: under
            // ImplicitFields.AllFields the member can *be* a backing field, whose name renders as
            // `<Ignored>k__BackingField`
            => (member.AccessorField is null ? "Set_" : "Field_")
                + Sanitise(contract.TypeName) + "_" + Sanitise(member.Name);

        /// <summary>A type's full name, reduced to something legal in an identifier.</summary>
        private static string Sanitise(string typeName)
        {
            if (typeName.StartsWith("global::", StringComparison.Ordinal)) typeName = typeName.Substring(8);

            var sb = new StringBuilder(typeName.Length);
            foreach (var c in typeName)
            {
                sb.Append(char.IsLetterOrDigit(c) ? c : '_');
            }
            return sb.ToString();
        }

        /// <summary>
        /// The <c>[UnsafeAccessor]</c> declarations for everything C# will not let the generated
        /// code reach directly: init-only and non-public setters, backing fields, and non-public
        /// parameterless constructors.
        /// </summary>
        private static void EmitAccessors(StringBuilder sb, int indent, ProtoModelPlan plan)
        {
            foreach (var contract in plan.Contracts)
            {
                if (contract.UsesConstructorAccessor)
                {
                    // the surrogate is what gets constructed when there is one, and it is the
                    // surrogate the parse checked, so name it here too
                    var constructed = contract.SurrogateTypeName ?? contract.TypeName;
                    sb.AppendLine();
                    Line(sb, indent, "[global::System.Runtime.CompilerServices.UnsafeAccessor("
                        + "global::System.Runtime.CompilerServices.UnsafeAccessorKind.Constructor)]");
                    Line(sb, indent, $"private static extern {constructed} "
                        + $"{ConstructorAccessorName(contract)}();");
                }

                foreach (var member in contract.Members)
                {
                    if (!member.UsesAccessor || contract.IsTuple) continue;

                    var self = contract.IsValueType ? $"ref {contract.TypeName}" : contract.TypeName;
                    sb.AppendLine();
                    if (member.AccessorField is { } fieldName)
                    {
                        Line(sb, indent, "[global::System.Runtime.CompilerServices.UnsafeAccessor("
                            + "global::System.Runtime.CompilerServices.UnsafeAccessorKind.Field, "
                            + $"Name = \"{fieldName}\")]");
                        Line(sb, indent, $"private static extern ref {member.DeclaredTypeName} "
                            + $"{AccessorName(contract, member)}({self} target);");
                    }
                    else
                    {
                        Line(sb, indent, "[global::System.Runtime.CompilerServices.UnsafeAccessor("
                            + "global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, "
                            + $"Name = \"set_{member.Name}\")]");
                        Line(sb, indent, $"private static extern void {AccessorName(contract, member)}("
                            + $"{self} target, {member.DeclaredTypeName} value);");
                    }
                }
            }
        }

        /// <summary>The <c>MapSerializer</c> factory for a dictionary member.</summary>
        private static string Map(ProtoMemberPlan member)
        {
            var map = member.Map;
            var arguments = map.TakesCollectionType
                ? $"<{member.DeclaredTypeName}, {map.KeyTypeName}, {map.ValueTypeName}>"
                : $"<{map.KeyTypeName}, {map.ValueTypeName}>";
            return $"{Serializers}.MapSerializer.{map.Factory}{arguments}()";
        }

        /// <summary>
        /// The features for a map member: the map is always length-prefixed (or a group), and the
        /// key and value wire types are passed separately.
        /// </summary>
        /// <remarks>
        /// The member's own <c>DataFormat</c> selects the root wire type and nothing else —
        /// <c>Group</c> is the only value that changes anything, since a map is length-prefixed
        /// either way. The per-key and per-value formats come from <c>[ProtoMap]</c>.
        /// <c>OptionFailOnDuplicateKey</c> rides on whether the shape is a real protobuf <c>map</c>.
        /// </remarks>
        private static string MapFeatures(ProtoMemberPlan member)
        {
            var result = member.DataFormat == ProtoDataFormat.Group
                ? $"{Features}.WireTypeStartGroup"
                : $"{Features}.WireTypeString";
            if (!member.IsPacked) result += $" | {Features}.OptionPackedDisabled";
            // note the split: field presence rides on the *map*, the wrapping on the value
            if (member.WrappedValue) result += $" | {Features}.OptionWrappedValueFieldPresence";
            if (member.WrappedCollection)
            {
                result += $" | {Features}.OptionWrappedCollection";
                if (member.WrappedCollectionGroup) result += $" | {Features}.OptionWrappedCollectionGroup";
            }
            if (member.OverwriteList) result += $" | {Features}.OptionClearCollection";
            // DisableMap lands on the same flag an invalid map shape does: duplicates throw rather
            // than replacing, because reading switches from SetValues to AddRange
            if (!member.Map.IsValidProtobufMap || member.DisableMap)
            {
                result += $" | {Features}.OptionFailOnDuplicateKey";
            }
            return result;
        }

        private static string MapElementFeatures(ProtoMemberPlan member)
        {
            var value = $"{Features}.{MapWireType(member.Map.ValueKind, member.MapValueFormat)}";
            if (member.WrappedValue)
            {
                value += $" | {Features}.OptionWrappedValue";
                if (member.WrappedValueGroup) value += $" | {Features}.OptionWrappedValueGroup";
            }
            return $"{Features}.{MapWireType(member.Map.KeyKind, member.MapKeyFormat)}, {value}";
        }

        /// <summary>
        /// The wire type for one side of a map, which <c>[ProtoMap]</c>'s per-key and per-value
        /// <c>DataFormat</c> selects.
        /// </summary>
        /// <remarks>
        /// The format only bites where there is something to select, which was taken from ref-emit
        /// rather than assumed: a <c>string</c> key ignores <c>FixedSize</c> entirely, and the
        /// <c>FixedSize</c> width comes from the <em>element</em> type just as it does for a scalar
        /// member — <c>int</c> gives <c>Fixed32</c>, <c>long</c> gives <c>Fixed64</c>.
        /// </remarks>
        private static string MapWireType(ProtoMemberKind kind, ProtoDataFormat format) => kind switch
        {
            ProtoMemberKind.Message => format == ProtoDataFormat.Group ? "WireTypeStartGroup" : "WireTypeString",
            _ => KindWireType(kind) switch
            {
                // the format only bites where the default is a varint - which is why a string key
                // ignores FixedSize, and why Single/Double keep their own fixed widths
                "WireTypeVarint" => format switch
                {
                    ProtoDataFormat.ZigZag => "WireTypeSignedVarint",
                    ProtoDataFormat.FixedSize => Is64Bit(kind) ? "WireTypeFixed64" : "WireTypeFixed32",
                    _ => "WireTypeVarint",
                },
                var fixedByKind => fixedByKind,
            },
        };

        /// <summary>
        /// A message key or value needs us passed along as its serializer. The two are positional, so
        /// a message value alone still has to pass a null for the key.
        /// </summary>
        private static string MapSubSerializers(ProtoMemberPlan member, string self = "this")
        {
            // the two sides are positional, so a value serializer needs the key slot filled with
            // null. Either side may want `this` (a message) or an inbuilt (a levelled BCL type);
            // note the *declared* level is combined with that side's own [ProtoMap] format, since
            // the member's own DataFormat selects the map's root wire type and nothing else
            var key = member.Map.KeyKind == ProtoMemberKind.Message ? self
                : InbuiltSerializer(member.Map.KeyKind, member.Map.KeyTypeName,
                    EffectiveCompatibilityLevel(member.DeclaredCompatibilityLevel, member.MapKeyFormat),
                    member.MapKeyFormat);
            var value = member.Map.ValueKind == ProtoMemberKind.Message ? self
                : InbuiltSerializer(member.Map.ValueKind, member.Map.ValueTypeName,
                    EffectiveCompatibilityLevel(member.DeclaredCompatibilityLevel, member.MapValueFormat),
                    member.MapValueFormat);

            if (value is not null) return $", {key ?? "null"}, {value}";
            return key is null ? "" : $", {key}";
        }

        /// <summary>
        /// How a fresh instance is made: normally <c>new</c>, but SkipConstructor bypasses every
        /// constructor, exactly as ref-emit does.
        /// </summary>
        /// <param name="typeName">
        /// What to construct â€” the contract itself, or its surrogate when it has one.
        /// </param>
        /// <summary>
        /// Convert an instance to its surrogate. A cast covers an <c>explicit</c> operator as well as
        /// an <c>implicit</c> one - ref-emit relies on the implicit form, but only the cast compiles
        /// for both - unless the model named conversion methods instead, which is how a type with no
        /// usable operators is hooked up.
        /// </summary>
        private static string ToSurrogate(ProtoContractPlan contract, string value)
            => contract.ToSurrogate is { } method
                ? $"{method}({value})"
                : $"({contract.SurrogateTypeName}){value}";

        /// <summary>The converse; see <see cref="ToSurrogate"/>.</summary>
        private static string ToUnderlying(ProtoContractPlan contract, string surrogate)
            => contract.ToUnderlying is { } method
                ? $"{method}({surrogate})"
                : $"({contract.TypeName}){surrogate}";

        private static string Construct(ProtoContractPlan contract, string? typeName = null)
        {
            typeName ??= contract.TypeName;
            if (contract.SkipConstructor)
            {
                return $"({typeName})global::ProtoBuf.BclHelpers.GetUninitializedObject(typeof({typeName}))";
            }
            // C# will not let us call a non-public constructor; IL has no such restriction, which is
            // why the runtime model reaches it by reflection and we reach it by [UnsafeAccessor]
            return contract.UsesConstructorAccessor
                ? $"{ConstructorAccessorName(contract)}()"
                : $"new {typeName}()";
        }

        /// <summary>
        /// The unguarded write for a scalar: the caller owns whatever test precedes it.
        /// </summary>
        private static void EmitScalarWrite(StringBuilder sb, int indent, ProtoMemberPlan member, string number, string local,
            bool raw = false)
        {
            var expression = ScalarValue(member, local);
            // the raw write forms (notes/nano-writer.md): the tag is a compile-time constant and
            // the value write names its own encoding, skipping the WireType handshake entirely.
            // Guards and structure are untouched - only the statement form changes - so this is
            // safe for EVERY contract shape; writes need no eligibility. Default format only:
            // formats keep the classic statements for now. Note the signed kinds sign-extend
            // through 64 bits (a negative int32 is the 10-byte form on the wire).
            if (raw && member.DataFormat == ProtoDataFormat.Default && RawScalarWrite(member, expression) is { } rawWrite)
            {
                // a bool's whole field is the constant tag plus one byte that is 0 or 1, so it
                // collapses to a single op - and at the dominant single-byte tag, to one store
                if (member.Kind == ProtoMemberKind.Bool)
                {
                    Line(sb, indent, $"state.WriteRawTagBool(({member.FieldNumber} << 3) | 0, {expression});  // {member.Name}");
                    return;
                }
                Line(sb, indent, $"state.WriteRawTag(({member.FieldNumber} << 3) | {RawScalarWireBits(member.Kind)});  // {member.Name}");
                Line(sb, indent, rawWrite);
                return;
            }
            if (member.Kind == ProtoMemberKind.Parseable)
            {
                Line(sb, indent, $"state.WriteFieldHeader({number}, global::ProtoBuf.WireType.String);");
                Line(sb, indent, $"state.WriteString({expression}.ToString());");
            }
            else if (BclSuffix(member) is { } bcl)
            {
                Line(sb, indent, $"state.WriteFieldHeader({number}, global::ProtoBuf.WireType.{BclWireType(member)});");
                Line(sb, indent, $"global::ProtoBuf.BclHelpers.Write{bcl}(ref state, {expression});");
            }
            // the Int32 shortcut writes its own varint header, so it only applies at the default format
            else if (member.Kind == ProtoMemberKind.Int32 && member.DataFormat == ProtoDataFormat.Default)
            {
                Line(sb, indent, $"state.WriteInt32Varint({number}, {expression});");
            }
            else
            {
                Line(sb, indent, $"state.WriteFieldHeader({number}, global::ProtoBuf.WireType.{ScalarWireType(member)});");
                Line(sb, indent, $"state.{ScalarSuffix(member.Kind, "Write")}({expression});");
            }
        }

        /// <summary>The raw write statement for a scalar kind, or null where the classic
        /// statement stays (BCL kinds, Parseable, and anything not listed).</summary>
        private static string? RawScalarWrite(ProtoMemberPlan member, string expression) => member.Kind switch
        {
            ProtoMemberKind.Bool => $"state.WriteRawVarint32({expression} ? 1u : 0u);",
            // signed kinds sign-extend through 64 bits: a negative value is the 10-byte form
            ProtoMemberKind.Int32 or ProtoMemberKind.SByte or ProtoMemberKind.Int16
                => $"state.WriteRawVarint64(unchecked((ulong)(long){expression}));",
            ProtoMemberKind.UInt32 or ProtoMemberKind.Byte or ProtoMemberKind.UInt16 or ProtoMemberKind.Char
                => $"state.WriteRawVarint32({expression});",
            ProtoMemberKind.Int64 => $"state.WriteRawVarint64(unchecked((ulong){expression}));",
            ProtoMemberKind.UInt64 => $"state.WriteRawVarint64({expression});",
            ProtoMemberKind.Single => $"state.WriteRawSingle({expression});",
            ProtoMemberKind.Double => $"state.WriteRawDouble({expression});",
            // nint/nuint are ordinary varints, and ref-emit asks for width 64 REGARDLESS of the
            // platform - which is the only reason they are safe to support at all, since the wire
            // form must not vary by architecture
            ProtoMemberKind.IntPtr => $"state.WriteRawVarint64(unchecked((ulong)(long){expression}));",
            ProtoMemberKind.UIntPtr => $"state.WriteRawVarint64(unchecked((ulong){expression}));",
            // BclHelpers.WriteDateOnly/WriteTimeOnly are one-liners over WriteInt32/WriteInt64, so
            // the raw form writes the same varint directly rather than routing through a helper
            // that would need the stateful wire-type handshake
            ProtoMemberKind.DateOnly => $"state.WriteRawVarint64(unchecked((ulong)(long){expression}.DayNumber));",
            ProtoMemberKind.TimeOnly => $"state.WriteRawVarint64(unchecked((ulong){expression}.Ticks));",
            _ => null,
        };

        /// <summary>The wire-type bits for a raw scalar write's constant tag.</summary>
        private static int RawScalarWireBits(ProtoMemberKind kind) => kind switch
        {
            ProtoMemberKind.Single => 5,
            ProtoMemberKind.Double => 1,
            _ => 0,
        };

        /// <summary>
        /// Whether a repeated member's write takes the native loop rather than the stateful
        /// WriteRepeated. Unlike the scalar raw writes - which are unconditionally safe because
        /// only the statement form changes - a repeated write replaces the ENGINE, so it is
        /// gated to the shapes whose bytes are provably the classic unpacked default: per-element
        /// constant tag plus value, nothing for empty, throw on a null element.
        /// </summary>
        private static bool RawRepeatedWritable(ProtoMemberPlan member, bool immutableAsSpan)
        {
            // List<T> and T[] exactly; a derived-declared list is out because foreach binds to
            // the DECLARED type's GetEnumerator, which could be a hiding redeclaration
            if (member.Repeated.Factory is not ("CreateList" or "CreateVector" or "CreateImmutableArray")
                || member.Repeated.TakesCollectionType) return false;
            // ImmutableArray<T> has no enumerator we are willing to bind to (its default throws),
            // so it is admitted only where AsSpan is available - see RepeatedSpan
            if (member.Repeated.Factory == "CreateImmutableArray" && !immutableAsSpan) return false;
            // packed changes the framing entirely, and needs measure (plus the zero-length
            // header rules); wrapping moves every element into a presence message
            if (member.IsPacked || member.WrappedValue || member.WrappedCollection) return false;
            if (member.DataFormat != ProtoDataFormat.Default) return false;
            // message elements wait on the measure cut; a hand-written or deferred-category
            // element serializer frames itself and cannot be second-guessed here
            if (member.SubSerializer is not null || member.SubSerializerIsScalar
                || member.SubSerializerDynamic) return false;
            // `repeated bytes` - which protogen emits as List<byte[]> - is admitted only for the
            // ARRAY element spelling. The struct storage shapes (Memory<byte>, ReadOnlyMemory<byte>,
            // ArraySegment<byte>) are "bytes" too, but they are not null-testable the same way and
            // have no fixture; they keep the stateful path rather than being reasoned about here.
            if (member.Kind == ProtoMemberKind.Bytes) return member.ElementTypeName == "byte[]";
            return member.Kind is ProtoMemberKind.Bool
                or ProtoMemberKind.Int32 or ProtoMemberKind.SByte or ProtoMemberKind.Int16
                or ProtoMemberKind.UInt32 or ProtoMemberKind.Byte or ProtoMemberKind.UInt16
                or ProtoMemberKind.Char or ProtoMemberKind.Int64 or ProtoMemberKind.UInt64
                or ProtoMemberKind.Single or ProtoMemberKind.Double or ProtoMemberKind.String
                or ProtoMemberKind.IntPtr or ProtoMemberKind.UIntPtr
                or ProtoMemberKind.DateOnly or ProtoMemberKind.TimeOnly;
        }

        /// <summary>
        /// Whether a PACKED repeated member takes the raw path - `notes/packed-writes.md`.
        /// </summary>
        /// <remarks>
        /// <para>
        /// Separate from <see cref="RawRepeatedWritable"/> because it is a different engine, not a
        /// variation: packed writes ONE tag over a whole payload, and needs the payload measured
        /// before the length prefix can go down. Until this existed, <c>IsPacked</c> was refused
        /// outright - which did not merely cost the optimisation, it made the member
        /// measure-blocked, and by the fixed-point rule that removed the whole contract, and every
        /// contract referencing it, from measure-first.
        /// </para>
        /// <para>
        /// The element kinds are those the raw surface takes a span of directly. The narrow kinds
        /// (<c>sbyte</c>/<c>byte</c>/<c>short</c>/<c>ushort</c>/<c>char</c>) are absent deliberately
        /// and are not an oversight - a span pun reinterprets bytes, so a 1-2 byte element cannot
        /// become a 4-byte one. Note this excludes them at EVERY format, not just varint:
        /// <c>FixedSize</c> on those four is legal and gives <c>Fixed32</c> (they pass width 32 to
        /// <c>ValueMember.GetIntWireType</c>), which is a WIDEN rather than a pun and so wants
        /// <c>Vector.Widen</c> - the exact inverse of the <c>Vector.Narrow</c> the blit already
        /// uses. <c>char</c> is the odd one out: it hard-codes varint and ignores the format.
        /// </para>
        /// <para>
        /// <c>TakesCollectionType</c> is excluded, matching the unpacked path - though NOT for the
        /// same reason, and the difference is recorded because it is a live widening opportunity:
        /// there, a derived list is out because <c>foreach</c> binds to the DECLARED type's
        /// <c>GetEnumerator</c>, which could be a hiding redeclaration. <c>AsSpan</c> has no such
        /// hazard. It stays out here only because nothing yet fixtures a derived packed list, and
        /// a widening nobody has a test for is not a widening.
        /// </para>
        /// </remarks>
        private static bool RawPackedWritable(ProtoMemberPlan member, bool listAsSpan, bool immutableAsSpan)
        {
            if (!member.IsPacked) return false;
            if (member.Repeated.Factory is not ("CreateList" or "CreateVector" or "CreateImmutableArray")
                || member.Repeated.TakesCollectionType) return false;
            // ImmutableArray<T> reaches the surface only as a span too, and its AsSpan is
            // package-dependent rather than framework-versioned, so it gets its own probe
            if (member.Repeated.Factory == "CreateImmutableArray" && !immutableAsSpan) return false;
            // a List<T> reaches this surface ONLY as a span, so where CollectionsMarshal is absent
            // (net472, netstandard2.0) the member stays on the stateful path - and, since the
            // predicate also drives measurability, its contract stays measure-blocked down-level.
            // A smaller optimisation rather than a broken build, as everywhere else here; caught
            // by the traversal build, which is the only thing that compiles net472.
            if (member.Repeated.Factory == "CreateList" && !listAsSpan) return false;
            if (member.WrappedValue || member.WrappedCollection) return false;
            // the format re-frames the ELEMENT, so each is admitted only on the kinds that can
            // express it: FixedSize flattens an integer column to 4 or 8 bytes, and ZigZag is
            // signed-only. Anything else - Group, WellKnown on a scalar column - has nothing to
            // select here and stays on the stateful path. (TwosComplement needs no case: the
            // parse normalises it onto Default, being byte-identical for every type we handle.)
            switch (member.DataFormat)
            {
                case ProtoDataFormat.Default:
                    break;
                case ProtoDataFormat.FixedSize:
                    if (member.Kind is not (ProtoMemberKind.Int32 or ProtoMemberKind.UInt32
                        or ProtoMemberKind.Int64 or ProtoMemberKind.UInt64)) return false;
                    break;
                case ProtoDataFormat.ZigZag:
                    if (member.Kind is not (ProtoMemberKind.Int32 or ProtoMemberKind.Int64)) return false;
                    break;
                default:
                    return false;
            }
            if (member.SubSerializer is not null || member.SubSerializerIsScalar
                || member.SubSerializerDynamic) return false;
            // a nullable element is not a packed scalar column at all
            if (member.ElementTypeName?.EndsWith("?", StringComparison.Ordinal) == true) return false;
            return member.Kind is ProtoMemberKind.Bool
                or ProtoMemberKind.Int32 or ProtoMemberKind.UInt32
                or ProtoMemberKind.Int64 or ProtoMemberKind.UInt64
                or ProtoMemberKind.Single or ProtoMemberKind.Double;
        }

        /// <summary>
        /// The raw surface method suffix, and the element type its span is of. The FORMAT selects
        /// as much as the kind does: the same <c>int[]</c> is a varint column, a zigzag column or
        /// a flat four-byte column depending on how the member was declared.
        /// </summary>
        private static (string Api, string SpanType) PackedApi(ProtoMemberKind kind, ProtoDataFormat format)
        {
            if (format == ProtoDataFormat.ZigZag)
            {
                // NOT punned to unsigned: the zigzag transform is signed by definition
                return ("ZigZag", kind == ProtoMemberKind.Int32 ? "int" : "long");
            }
            if (format == ProtoDataFormat.FixedSize)
            {
                return kind is ProtoMemberKind.Int32 or ProtoMemberKind.UInt32
                    ? ("Fixed32", "uint") : ("Fixed64", "ulong");
            }
            return kind switch
            {
                ProtoMemberKind.Bool => ("Bool", "bool"),
                ProtoMemberKind.Int32 => ("Varint", "int"),
                ProtoMemberKind.UInt32 => ("Varint", "uint"),
                ProtoMemberKind.Int64 => ("Varint", "ulong"),  // a negative long IS a large ulong
                ProtoMemberKind.UInt64 => ("Varint", "ulong"),
                ProtoMemberKind.Single => ("Fixed32", "uint"),
                _ => ("Fixed64", "ulong"),
            };
        }

        /// <summary>
        /// The span handed to the raw packed surface, produced AT THE CALL SITE - which is the
        /// whole point of the design: the generator knows the collection shape and the element
        /// type, so the library needs no overload per collection and no arm per enum.
        /// </summary>
        private static string PackedSpan(ProtoMemberPlan member, string number, bool listAsSpan,
            bool immutableAsSpan)
        {
            var span = RepeatedSpan(member, number, listAsSpan, immutableAsSpan) ?? $"tmp{number}";
            var (_, spanType) = PackedApi(member.Kind, member.DataFormat);
            // the element's own spelling: an enum's is the enum, not its underlying type
            var element = member.EnumTypeName ?? member.ElementTypeName ?? spanType;
            if (element == spanType) return span;
            return $"global::System.Runtime.InteropServices.MemoryMarshal.Cast<{element}, {spanType}>({span})";
        }

        /// <summary>
        /// The <c>if (tmp != null)</c> guard a repeated member's write and measure need — or the
        /// empty string where the collection is a <b>value type</b> and the guard is not merely
        /// unnecessary but WRONG.
        /// </summary>
        /// <remarks>
        /// <c>ImmutableArray&lt;T&gt;</c> declares lifted equality operators over
        /// <c>ImmutableArray&lt;T&gt;?</c>, so <c>tmp != null</c> compiles for it — and evaluates
        /// to <b>false</b> for a <c>default</c> instance, because the nullable comparison unwraps
        /// both sides to a default value and finds them equal. The guard therefore SKIPS a default
        /// immutable array entirely.
        /// <para>
        /// For an unpacked member that is invisible, since an empty collection writes nothing
        /// anyway. For a <b>packed</b> one it is a wire divergence: protobuf-net writes the
        /// zero-length header (<c>12-00</c>) for an empty or default column, and the guarded code
        /// wrote nothing at all. Caught by the corpus differential, not by review.
        /// </para>
        /// <para>
        /// Dropping the guard is safe rather than merely convenient: every value-type collection
        /// reaching this path does so as a span, and <c>AsSpan()</c> on a default instance yields
        /// an <i>empty</i> span (checked on net472 and net8.0), which is exactly what a default is
        /// defined to mean here. See <c>ImmutableArraySpanTests</c>.
        /// </para>
        /// </remarks>
        private static bool NeedsNullGuard(ProtoMemberPlan member) => !member.Repeated.IsValueType;

        /// <summary>
        /// Whether a compatibility-level BCL member has an arithmetic measure — currently the
        /// level-200 <c>DateTime</c>/<c>TimeSpan</c> pair at the default format, whose body is the
        /// <c>ScaledTicks</c> message that <c>BclHelpers.Measure*</c> now sizes.
        /// </summary>
        /// <remarks>
        /// Everything else in the family still writes-to-count: level 240+ swaps in
        /// <c>Timestamp</c>/<c>Duration</c> (a seconds+nanos message, so different arithmetic),
        /// level 300 swaps <c>Guid</c> and <c>decimal</c> for their string forms, and the
        /// <c>FixedSize</c> variants carry no length prefix at all. Each needs its own measure and
        /// its own fixture; `notes/gaps.md` B26 has the order.
        /// </remarks>
        private static bool BclMeasurable(ProtoMemberPlan member)
        {
            // FixedSize on the date/time pair is measurable and CONSTANT - see BclFixedWidth
            if (BclFixedWidth(member) is not null) return true;
            // the ONE format that reaches these otherwise: FixedSize selects GuidBytes at level 300
            // (below it, the format is simply ignored - see BclWireType)
            if (member.DataFormat != ProtoDataFormat.Default
                && !(member.DataFormat == ProtoDataFormat.FixedSize
                    && member.Kind == ProtoMemberKind.Guid
                    && member.CompatibilityLevel >= 300)) return false;
            return member.Kind switch
            {
                // every level, for all four: 240+ swaps the date/time pair for Timestamp/Duration and
                // 300 swaps Guid/decimal for their string forms, and BclSuffix picks the method for
                // each - so the measure follows the writer without this needing to know the levels
                ProtoMemberKind.DateTime or ProtoMemberKind.TimeSpan
                    or ProtoMemberKind.Guid or ProtoMemberKind.Decimal => true,
                _ => false,
            };
        }

        /// <summary>
        /// The flat payload width of a BCL member whose framing carries no length prefix, or
        /// <c>null</c> where the member is length-prefixed and must be measured for real.
        /// </summary>
        /// <remarks>
        /// <c>DataFormat.FixedSize</c> on <c>DateTime</c>/<c>TimeSpan</c> selects a <c>Fixed64</c>
        /// header (see <see cref="BclWireType"/>), and under that header <c>BclHelpers.WriteDateTime</c>
        /// emits the flat eight-byte form rather than a message — so the whole member is tag plus
        /// exactly eight bytes, with nothing to compute. It is genuine protobuf, not a message body
        /// mislabelled: <c>09-80-80-85-75-3A-0F-38-00</c> is a tag and eight bytes.
        /// <para>
        /// The compatibility level does not reach it: the flat form is what the <c>Fixed64</c> header
        /// selects at every level, which is why there is no level test here unlike the arms below.
        /// </para>
        /// </remarks>
        private static int? BclFixedWidth(ProtoMemberPlan member)
            => member.DataFormat == ProtoDataFormat.FixedSize
                && member.Kind is ProtoMemberKind.DateTime or ProtoMemberKind.TimeSpan
                ? 8 : null;

        /// <summary>The body length for such a member — the payload, not the framing.</summary>
        /// <remarks>
        /// Keyed on <see cref="BclSuffix"/>, the same selector the <b>writer</b> uses, rather than on
        /// the kind: the level and format pick `Guid`/`GuidString`/`GuidBytes` (and
        /// `Decimal`/`DecimalString`, and `DateTime`/`Timestamp`), and measure must follow write
        /// exactly. Deriving both from one function is what makes them unable to drift apart.
        /// </remarks>
        private static string BclMeasureBody(ProtoMemberPlan member, string expression)
            => $"global::ProtoBuf.BclHelpers.Measure{BclSuffix(member)}({expression})";

        /// <summary>
        /// The span expression for a repeated member, or <c>null</c> if this member cannot be
        /// reached as one and must keep the enumerator.
        /// </summary>
        /// <remarks>
        /// Three shapes yield a span and the generator knows which it has, so the decision is made
        /// here rather than by overloading the library per collection:
        /// <list type="bullet">
        /// <item><description><c>T[]</c> - the array itself, on every framework;</description></item>
        /// <item><description><c>List&lt;T&gt;</c> - <c>CollectionsMarshal.AsSpan</c>, net5+;</description></item>
        /// <item><description><c>ImmutableArray&lt;T&gt;</c> - <c>AsSpan()</c>, package-dependent.</description></item>
        /// </list>
        /// <para>
        /// The immutable one needs <b>no default guard</b>, which is why it can share this path at
        /// all: <c>default(ImmutableArray&lt;T&gt;)</c> throws on <c>Length</c>/indexer/enumerator
        /// but <c>AsSpan()</c> yields an empty span (verified on net472 and net8.0), and
        /// protobuf-net already treats a default instance as empty - so the empty span writes
        /// exactly the bytes a default is supposed to write. See <c>ImmutableArraySpanTests</c>.
        /// </para>
        /// </remarks>
        private static string RepeatedSpan(ProtoMemberPlan member, string number, bool listAsSpan,
            bool immutableAsSpan)
            => member.Repeated.Factory switch
            {
                "CreateVector" => $"tmp{number}",
                "CreateList" when listAsSpan
                    => $"global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(tmp{number})",
                "CreateImmutableArray" when immutableAsSpan => $"tmp{number}.AsSpan()",
                _ => null,
            };

        /// <summary>The element count, without building a span merely to ask its length.</summary>
        private static string PackedCount(ProtoMemberPlan member, string number)
            => member.Repeated.Factory is "CreateVector" or "CreateImmutableArray"
                ? $"tmp{number}.Length" : $"tmp{number}.Count";

        /// <summary>
        /// One line: the whole member's contribution, framing included. The bool and fixed-width
        /// forms are O(1) in the count, so they never touch the payload.
        /// </summary>
        private static void EmitRawPackedMeasure(StringBuilder sb, int indent, ProtoMemberPlan member,
            string number, bool listAsSpan, bool immutableAsSpan)
        {
            var (api, _) = PackedApi(member.Kind, member.DataFormat);
            // Bool and the fixed widths are O(1) in the count and never look at the payload;
            // Varint and ZigZag must walk it (vectorised) to size the length prefix
            var arg = api is "Varint" or "ZigZag"
                ? PackedSpan(member, number, listAsSpan, immutableAsSpan)
                : PackedCount(member, number);
            Line(sb, indent,
                $"len += global::ProtoBuf.ProtoWriter.State.MeasureRawPacked{api}({member.FieldNumber}, {arg});  // {member.Name}");
        }

        private const string DriftCapture = "DebugCapturePosition(ref state, ref before)";
        private const string DriftAssert = "DebugAssertPosition(ref state, before + len";

        /// <summary>
        /// The DEBUG-only length-drift check: a measured length that disagrees with the bytes
        /// actually written is a corrupt stream, and it is the one failure this whole arc can
        /// produce that nothing else would catch.
        /// </summary>
        /// <remarks>
        /// <para>
        /// The classic buffer-writer path already validates ("Length mismatch; calculated 'x',
        /// actual 'y'") and the raw path had no equivalent. The differential corpus catches a
        /// <c>Measure_</c>/<c>RawWrite_</c> disagreement only for shapes IN the corpus; this
        /// catches it in the consumer's own contracts, which the corpus can never reach.
        /// </para>
        /// <para>
        /// <c>Position64</c> is safe to lean on here even though the raw path deliberately does not
        /// maintain most writer state: it is DERIVED (committed bytes plus the backend's pending
        /// buffer offset), and the buffer offset is exactly what a raw write advances. A stream
        /// flush mid-body is fine too - <c>_position64</c> gains what <c>Pending</c> loses.
        /// </para>
        /// <para>
        /// <c>[Conditional]</c> resolves against the CONSUMER's compilation, so their Release build
        /// drops the calls, and with them the capture local - measured as 0 IL locals and 2 bytes of
        /// IL, so this does not re-add what gap B16 removed. The bodies are <c>#if DEBUG</c>'d as
        /// well, so even an explicit call costs nothing there. <c>ref</c> rather than <c>out</c> is
        /// not a preference: CS0685 makes <c>out</c> illegal on a conditional member, precisely
        /// because the call may vanish and leave the target unassigned.
        /// </para>
        /// </remarks>
        private static void EmitLengthDriftHelpers(StringBuilder sb, int indent)
        {
            Line(sb, indent, "// DEBUG-only: prove each measured length against the bytes actually written.");
            Line(sb, indent, "// [Conditional] is resolved against YOUR compilation, so a Release build");
            Line(sb, indent, "// removes both calls and the capture local with them; the bodies are #if DEBUG'd");
            Line(sb, indent, "// too, so even calling one directly costs nothing there.");
            Line(sb, indent, "[global::System.Diagnostics.Conditional(\"DEBUG\")]");
            Line(sb, indent, "private static void DebugCapturePosition(ref global::ProtoBuf.ProtoWriter.State state, ref long position)");
            Line(sb, indent, "{");
            sb.AppendLine("#if DEBUG");
            Line(sb, indent + 1, "position = state.Position64;");
            sb.AppendLine("#endif");
            Line(sb, indent, "}");
            sb.AppendLine();
            Line(sb, indent, "[global::System.Diagnostics.Conditional(\"DEBUG\")]");
            Line(sb, indent, "private static void DebugAssertPosition(ref global::ProtoBuf.ProtoWriter.State state, long expected, string member)");
            Line(sb, indent, "{");
            sb.AppendLine("#if DEBUG");
            Line(sb, indent + 1, "var actual = state.Position64;");
            Line(sb, indent + 1, "// interpolated only on failure: this runs per length-prefixed member in a Debug build");
            Line(sb, indent + 1, "if (actual != expected) global::System.Diagnostics.Debug.Fail(");
            Line(sb, indent + 2, "$\"Length drift writing '{member}': measured length and bytes written differ by {actual - expected}.\");");
            sb.AppendLine("#endif");
            Line(sb, indent, "}");
        }

        /// <summary>
        /// Append an emitted body, folding its sub-message length temporaries onto ONE local
        /// where there is more than one of them (gap B16).
        /// </summary>
        /// <remarks>
        /// <para>
        /// The temps are all <c>long</c> and each is assigned then consumed immediately, so they
        /// fold with no type map and no lifetime overlap. Unlike the length-cache reference - which
        /// is simply read inline at every site, being a trivial property we own - this one cannot be
        /// eliminated, since it is an <c>out</c> target; but it need not be duplicated.
        /// </para>
        /// <para>
        /// The count is the point rather than the throughput: <c>MaxDepth</c> (512) only bounds
        /// recursion if frames are SMALL, and a contract with hundreds of message members was
        /// emitting a local per member. See <c>notes/gaps.md</c> B16 for the arithmetic.
        /// </para>
        /// <para>
        /// <b>One site keeps its declaration AT the site</b> (Marc): hoisting a single use to the
        /// top widens its scope and buys nothing. The reference-typed shape declares at the
        /// <c>out</c>, the value-typed one at the assignment, which is exactly what was emitted
        /// before folding existed.
        /// </para>
        /// <para>
        /// Whether the body needs the local at all is decided by inspecting what was actually
        /// emitted, rather than by restating the eligibility predicate here - that would be a
        /// second copy of it, free to drift from the first. It also keeps an unused local out of
        /// the consumer's build, where it would be CS0168.
        /// </para>
        /// </remarks>
        private static void AppendFoldingLengthTemp(StringBuilder sb, int indent, StringBuilder bodyBuilder, string name)
        {
            var body = bodyBuilder.ToString();
            // the temp is assigned from an arithmetic measure, or - on the write side since gap
            // B38 - from the ordered length buffer. Both spellings count towards the same local:
            // missing the second is why the descriptor model briefly emitted an undeclared `len`.
            var assignments = new[] { name + " = Measure_", name + " = state.RawSlots.Next()" };
            var sites = 0;
            string single = null;
            foreach (var assignment in assignments)
            {
                for (var at = body.IndexOf(assignment, StringComparison.Ordinal); at >= 0;
                    at = body.IndexOf(assignment, at + assignment.Length, StringComparison.Ordinal))
                {
                    sites++;
                    single = assignment;
                }
            }
            if (sites == 1)
            {
                var outParameter = "out " + name + ")";
                body = body.IndexOf(outParameter, StringComparison.Ordinal) >= 0
                    ? body.Replace(outParameter, "out var " + name + ")")
                    : body.Replace(single, "var " + single);
            }
            else if (sites > 1)
            {
                Line(sb, indent, $"long {name};");
            }
            // the drift check's capture target: one per body, and `= 0` because a `ref` argument
            // demands definite assignment - `out` being illegal on a conditional member (CS0685).
            // It disappears entirely from a Release build along with the calls that read it.
            if (body.IndexOf(DriftCapture, StringComparison.Ordinal) >= 0)
            {
                Line(sb, indent, "long before = 0;");
            }
            sb.Append(body);
        }

        /// <summary>The write mirror: the same span, the same framing decision, one call.</summary>
        private static void EmitRawPackedWrite(StringBuilder sb, int indent, ProtoMemberPlan member,
            string number, bool listAsSpan, bool immutableAsSpan)
        {
            var (api, _) = PackedApi(member.Kind, member.DataFormat);
            Line(sb, indent,
                $"state.WriteRawPacked{api}({member.FieldNumber}, {PackedSpan(member, number, listAsSpan, immutableAsSpan)});  // {member.Name}");
        }

        /// <summary>
        /// The native write loop for an eligible repeated member (see
        /// <see cref="RawRepeatedWritable"/> and <see cref="RawRepeatedMessageTarget"/>):
        /// byte-identical to the stateful unpacked default. A List&lt;T&gt; enumerates as a span
        /// where the framework offers it (net5+, probed) - no enumerator, no per-step version
        /// check; serialization already demands the collection not mutate mid-write, which is
        /// the same contract that check polices. An array's plain foreach is already an indexed
        /// loop. A message element takes the measure-first shape: exact prefix, direct call.
        /// </summary>
        private static void EmitRawRepeatedWrite(StringBuilder sb, int indent, ProtoMemberPlan member, string number,
            bool listAsSpan, bool immutableAsSpan, ProtoContractPlan? messageTarget = null,
            string depth = "state.RawDepthBudget", bool enclosingMeasured = true)
        {
            // a GROUPED message element is framed by a start/end tag pair rather than a length
            // prefix (gap B35): wire type 3 opens it, 4 closes it, and the field number is the same
            // in both - so the two tags fold to the same constant length and there is no length to
            // compute at all. Same reasoning as the unary grouped member; what was missing is that
            // declining it here cost the whole CONTRACT its measure-first eligibility.
            var grouped = messageTarget is not null && member.DataFormat == ProtoDataFormat.Group;
            var wire = grouped ? 3
                : member.Kind is ProtoMemberKind.String or ProtoMemberKind.Message
                or ProtoMemberKind.Bytes ? 2 : RawScalarWireBits(member.Kind);
            var source = RepeatedSpan(member, number, listAsSpan, immutableAsSpan) ?? $"tmp{number}";
            var item = $"item{number}";
            Line(sb, indent, $"foreach (var {item} in {source})");
            Line(sb, indent, "{");
            // AsRepeated erases element nullability from the plan (it is an ordinary element on
            // the wire), so nullability is read off the element type's own spelling, exactly as
            // the packed read fast path does
            var nullableElement = member.ElementTypeName?.EndsWith("?", StringComparison.Ordinal) == true;
            if (member.Kind is ProtoMemberKind.String or ProtoMemberKind.Bytes || nullableElement
                || (messageTarget is not null && !messageTarget.IsValueType))
            {
                Line(sb, indent + 1, $"if ({item} is null) global::ProtoBuf.ProtoWriter.State.ThrowNullRepeatedContents<{member.ElementTypeName}>();");
            }
            Line(sb, indent + 1, $"state.WriteRawTag(({member.FieldNumber} << 3) | {wire});  // {member.Name}");
            if (grouped)
            {
                // no length prefix, so nothing to measure and nothing for the drift check to prove
                var targetName = Sanitise(member.TypeName!);
                Line(sb, indent + 1, $"RawWrite_{targetName}(ref state, {item}, {depth});");
                Line(sb, indent + 1, $"state.WriteRawTag(({member.FieldNumber} << 3) | 4);  // {member.Name} (end group)");
            }
            else if (messageTarget is not null)
            {
                var targetName = Sanitise(member.TypeName!);
                if (enclosingMeasured)
                {
                    Line(sb, indent + 1, "len = state.RawSlots.Next();");   // gap B38, as above
                }
                else
                {
                    Line(sb, indent + 1, $"var mark{number} = state.RawSlots.Mark();");
                    Line(sb, indent + 1, $"len = Measure_{targetName}({item}, state.RawDepthBudget, state.RawSlots);");
                    Line(sb, indent + 1, $"state.RawSlots.SeekTo(mark{number});");
                }
                Line(sb, indent + 1, $"state.WriteRawVarint64((ulong)len);");
                Line(sb, indent + 1, $"{DriftCapture};");
                Line(sb, indent + 1, $"RawWrite_{targetName}(ref state, {item}, {depth});");
                Line(sb, indent + 1, $"{DriftAssert}, \"{member.Name}\");");
            }
            else if (member.Kind == ProtoMemberKind.String)
            {
                Line(sb, indent + 1, $"state.WriteRawString({item});");
            }
            else if (member.Kind == ProtoMemberKind.Bytes)
            {
                // WriteRawBytes emits its own length prefix, exactly as the unary bytes write does
                Line(sb, indent + 1, $"state.WriteRawBytes({item});");
            }
            else
            {
                var local = nullableElement ? $"{item}.GetValueOrDefault()" : item;
                Line(sb, indent + 1, RawScalarWrite(member, ScalarValue(member, local))!);
            }
            Line(sb, indent, "}");
        }

        /// <summary>
        /// The contract-shape half of measure eligibility: no surrogate (either direction), no
        /// hierarchy, not group-framed (a group member is framed by markers, not a length
        /// prefix), and no before-serialize callback - measure runs before the write pipeline
        /// would fire it, so a callback that mutates state would falsify the already-computed
        /// prefix. Extension data is measurable: the blob carries its own headers, so its size
        /// is its length (MeasureRawExtensionData) - which is what lets the .proto-generated DTO
        /// trees, IExtensible throughout, take the measure-first shape at all.
        /// </summary>
        private static bool RawMeasurableShape(ProtoContractPlan contract)
            => contract.ExternalSerializerTypeName is null
            && contract.SurrogateTypeName is null
            && contract.SurrogateSerializer is null
            && contract.RootTypeName is null && contract.SubTypes.Count == 0
            && !contract.IsGroup
            && !HasCallback(contract, ProtoCallbackKind.BeforeSerialize);

        /// <summary>
        /// Whether this member stops its contract having a pure-arithmetic measure. This is the
        /// write-side mirror of size predictability, NOT of write nativeness: a member whose
        /// statement stays stateful (unary int32 via WriteInt32Varint) is still measurable,
        /// because the BYTES are fixed by kind, format and value. What blocks: anything whose
        /// size needs the engine (maps, wrapping, non-default formats, BCL kinds, parseable
        /// ToString - which would also run twice - inbuilt or hand-written serializers), and a
        /// message member whose target has no Measure_ of its own.
        /// </summary>
        private static bool RawMemberMeasureBlocked(ProtoMemberPlan member, Dictionary<string, ProtoContractPlan> measurable, bool listAsSpan, bool immutableAsSpan)
        {
            if (member.Map.Factory is not null) return true;
            if (member.WrappedValue || member.WrappedCollection) return true;
            // A packed column vets its OWN format - RawPackedWritable admits FixedSize on the
            // integer kinds and ZigZag on the signed ones - so it has to be asked BEFORE the
            // blanket non-default-format block below, or those two are refused there and never
            // reach the repeated arm at all. That is exactly what happened when the format arms
            // were added: the writes went raw (the write dispatch asks separately) while the
            // MEASURE stayed blocked, so the contracts got raw statements and no Measure_ - all
            // the throughput, none of the cascade fix, and nothing failing to say so.
            //
            // Same shape as the Group note below: a blanket format refusal here does not cost the
            // member, it costs the whole containing contract, to a fixed point.
            if (RawPackedWritable(member, listAsSpan, immutableAsSpan)) return false;
            // Group is the ONE non-default format that does not need the engine, and blocking it
            // was backwards: a grouped sub-message carries no length prefix, so its size is
            // start-tag + body + end-tag, every part of which is known when the target is
            // measurable - and the tags fold, since the field number is a constant. Blocking it
            // removed the CONTAINING contract from the measurable set, and that exclusion runs to
            // a fixed point, so one grouped member dropped a whole tree onto write-to-count -
            // i.e. reaching for groups because they are faster produced the opposite.
            // Restricted to a unary message member: a grouped COLLECTION or MAP frames each
            // element, which is a different sum and is not attempted here.
            // Group is admitted for a message member whether it is unary or REPEATED (gap B35);
            // the repeated branch below then decides via RawRepeatedMessageTarget. Requiring
            // `Repeated.Factory is null` here is what cost the benchmark 5.7x: one repeated grouped
            // member disqualified its whole contract, and the exclusion cascades to a fixed point,
            // so a member that was never even populated took the contract off measure-first.
            if (member.DataFormat != ProtoDataFormat.Default
                && !BclMeasurable(member)
                && !(member.DataFormat == ProtoDataFormat.Group
                    && member.Kind == ProtoMemberKind.Message
                    && member.Map.Factory is null)) return true;
            if (member.Repeated.Factory is not null)
            {
                if (RawRepeatedWritable(member, immutableAsSpan) || RawPackedWritable(member, listAsSpan, immutableAsSpan)) return false;
                // measurable even though the WRITE stays stateful - see RawRepeatedBclMeasurable
                if (RawRepeatedBclMeasurable(member)) return false;
                return RawRepeatedMessageTarget(member, measurable) is null;
            }
            // a nullable STRUCT message would measure one GetValueOrDefault copy and write
            // another; the copies are field-identical, but the shape is parked until a fixture
            // proves it rather than reasoned safe
            if (member.IsNullable && member.Kind == ProtoMemberKind.Message) return true;
            // the level-200 date/time pair is measurable now that BclHelpers can size the body
            if (BclMeasurable(member)) return false;
            return member.Kind switch
            {
                ProtoMemberKind.Bool or ProtoMemberKind.Int32 or ProtoMemberKind.SByte
                    or ProtoMemberKind.Int16 or ProtoMemberKind.UInt32 or ProtoMemberKind.Byte
                    or ProtoMemberKind.UInt16 or ProtoMemberKind.Char or ProtoMemberKind.Int64
                    or ProtoMemberKind.UInt64 or ProtoMemberKind.Single or ProtoMemberKind.Double
                    or ProtoMemberKind.String or ProtoMemberKind.Uri
                    // pure varints on the raw path - see RawScalarWrite; no BclHelpers sizing needed
                    or ProtoMemberKind.IntPtr or ProtoMemberKind.UIntPtr
                    or ProtoMemberKind.DateOnly or ProtoMemberKind.TimeOnly => false,
                ProtoMemberKind.Bytes => member.MemberIsValueType,
                ProtoMemberKind.Message => member.SubSerializerIsScalar || member.SubSerializerDynamic
                    || member.SubSerializer is not (null or "this")
                    || member.TypeName is null || !measurable.ContainsKey(member.TypeName),
                _ => true,
            };
        }

        /// <summary>
        /// The measurable target of a plain unary message member, or null where the classic
        /// WriteMessage stays. The nullable-struct shape is excluded (it never reaches the kind
        /// switch anyway); an inbuilt-serialized member has no plan entry, so the dictionary
        /// lookup excludes it naturally.
        /// </summary>
        private static ProtoContractPlan? RawNativeMessageTarget(ProtoMemberPlan member,
            Dictionary<string, ProtoContractPlan>? measurable)
            => !member.IsNullable
                // Group joins Default here: it is framed by a start/end tag pair instead of a
                // length prefix, so it takes the raw path too - and takes it more cheaply, since
                // there is no length to compute. See the emit site, which skips the measure call
                // entirely rather than measuring and discarding
                && (member.DataFormat == ProtoDataFormat.Default
                    || member.DataFormat == ProtoDataFormat.Group)
                && member.SubSerializer is null or "this"
                && !member.SubSerializerIsScalar && !member.SubSerializerDynamic
                && member.TypeName is not null
                && measurable is not null && measurable.TryGetValue(member.TypeName, out var target)
                ? target : null;

        /// <summary>
        /// The measurable target of a repeated message member: the cut-2 collection gates plus
        /// a measurable element. A nullable-struct element is parked with its unary sibling.
        /// </summary>
        private static ProtoContractPlan? RawRepeatedMessageTarget(ProtoMemberPlan member,
            Dictionary<string, ProtoContractPlan>? measurable)
            => member.Kind == ProtoMemberKind.Message
                && member.Repeated.Factory is "CreateList" or "CreateVector"
                && !member.Repeated.TakesCollectionType
                && !member.IsPacked && !member.WrappedValue && !member.WrappedCollection
                // Group joins Default here (gap B35): a grouped element is start-tag + body +
                // end-tag, which both the write and the measure now emit
                && member.DataFormat is ProtoDataFormat.Default or ProtoDataFormat.Group
                && member.SubSerializer is null or "this"
                && member.ElementTypeName?.EndsWith("?", StringComparison.Ordinal) != true
                && member.TypeName is not null
                && measurable is not null && measurable.TryGetValue(member.TypeName, out var target)
                ? target : null;

        /// <summary>
        /// A repeated member whose ELEMENT is a measurable compatibility-level BCL type. Such a
        /// member is still written by the stateful <c>RepeatedSerializer</c> — there is no raw
        /// repeated BCL write — but it can be measured, and that is the whole point: measure and
        /// write eligibility are independent, exactly as they already are for a UNARY BCL member,
        /// which is measurable while being written with <c>WriteFieldHeader</c> + <c>BclHelpers</c>.
        /// </summary>
        /// <remarks>
        /// Before this, a single <c>List&lt;DateTime&gt;</c> dropped its whole contract back to
        /// write-to-count, because the repeated branch is tested BEFORE the BCL arm and nothing in it
        /// admitted these kinds (gap B26 item 4). A nullable element is excluded: protobuf-net rejects
        /// null elements outright, so the shape has no wire form to agree with.
        /// </remarks>
        private static bool RawRepeatedBclMeasurable(ProtoMemberPlan member)
            => member.Repeated.Factory is not null
                && member.Kind is ProtoMemberKind.DateTime or ProtoMemberKind.TimeSpan
                    or ProtoMemberKind.Guid or ProtoMemberKind.Decimal
                && member.ElementTypeName?.EndsWith("?", StringComparison.Ordinal) != true
                && BclMeasurable(member);

        /// <summary>The generator-side varint size, for folding constant tag lengths.</summary>
        private static int VarintLen(uint value)
        {
            int n = 1;
            while ((value >>= 7) != 0) n++;
            return n;
        }

        /// <summary>
        /// The size expression for a raw scalar's payload - the measure mirror of
        /// <see cref="RawScalarWrite"/>, byte for byte. A constant ("1", "4", "8") is returned
        /// as such so the caller can fold it into the tag length.
        /// </summary>
        private static string? RawScalarMeasure(ProtoMemberPlan member, string expression) => member.Kind switch
        {
            ProtoMemberKind.Bool => "1",
            ProtoMemberKind.Int32 or ProtoMemberKind.SByte or ProtoMemberKind.Int16
                => $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint64(unchecked((ulong)(long){expression}))",
            ProtoMemberKind.UInt32 or ProtoMemberKind.Byte or ProtoMemberKind.UInt16 or ProtoMemberKind.Char
                => $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint32({expression})",
            ProtoMemberKind.Int64 => $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint64(unchecked((ulong){expression}))",
            ProtoMemberKind.UInt64 => $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint64({expression})",
            ProtoMemberKind.Single => "4",
            ProtoMemberKind.Double => "8",
            ProtoMemberKind.IntPtr => $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint64(unchecked((ulong)(long){expression}))",
            ProtoMemberKind.UIntPtr => $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint64(unchecked((ulong){expression}))",
            ProtoMemberKind.DateOnly => $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint64(unchecked((ulong)(long){expression}.DayNumber))",
            ProtoMemberKind.TimeOnly => $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint64(unchecked((ulong){expression}.Ticks))",
            _ => null,
        };

        /// <summary>
        /// One member's contribution to <c>len</c>, tag length folded as a literal; the payload
        /// half comes from <see cref="RawScalarMeasure"/> or the caller's own expression.
        /// </summary>
        private static string MeasureAdd(ProtoMemberPlan member, int wire, string payload)
        {
            var tagLen = VarintLen((uint)((member.FieldNumber << 3) | wire));
            return int.TryParse(payload, out var constant)
                ? $"len += {tagLen + constant};  // {member.Name}"
                : $"len += {tagLen} + {payload};  // {member.Name}";
        }

        /// <summary>
        /// A grouped sub-message's contribution: the body plus a start-group and an end-group tag,
        /// with no length prefix — the shape that makes groups cheap to write.
        /// </summary>
        /// <remarks>
        /// Both tags carry the same field number and differ only in wire type (3 = StartGroup,
        /// 4 = EndGroup), and those two bits cannot cross a varint boundary — the low three bits
        /// of the tag are the wire type — so the two encoded lengths are always equal, and the
        /// pair folds to one literal.
        /// </remarks>
        private static string MeasureAddGroup(ProtoMemberPlan member, string payload)
        {
            var tagLen = VarintLen((uint)((member.FieldNumber << 3) | 3));
            return $"len += {tagLen * 2} + {payload};  // {member.Name} (group: no length prefix)";
        }

        /// <summary>
        /// The measure mirror of <see cref="EmitWriteMembers"/> for a measurable contract: the
        /// same member order, the same guards, and payload arithmetic in place of writes. The
        /// eligibility fixed point guarantees every member here has a form; a kind falling to
        /// the default arm is a generator bug, thrown at generation time rather than emitted as
        /// a silently short prefix.
        /// </summary>
        private static void EmitMeasureMembers(StringBuilder sb, int baseIndent, ProtoContractPlan contract,
            Dictionary<string, ProtoContractPlan> measurable, bool listAsSpan, bool immutableAsSpan)
        {
            foreach (var member in contract.Members)
            {
                var condition = member.WriteCondition;
                if (condition is not null)
                {
                    Line(sb, baseIndent, $"if (value.{condition})");
                    Line(sb, baseIndent, "{");
                }
                var indent = condition is null ? baseIndent : baseIndent + 1;
                var number = member.FieldNumber.ToString(CultureInfo.InvariantCulture);
                Line(sb, indent, $"var tmp{number} = {MemberAccess(contract, member, "value")};");

                if (member.Repeated.Factory is not null)
                {
                    // the measure must guard exactly as the write does, or the two disagree on an
                    // empty/default collection and the length prefix is wrong - see NeedsNullGuard
                    var repeatedGuard = NeedsNullGuard(member);
                    if (repeatedGuard)
                    {
                        Line(sb, indent, $"if (tmp{number} != null)");
                        Line(sb, indent, "{");
                    }
                    var body = repeatedGuard ? indent + 1 : indent;
                    if (RawPackedWritable(member, listAsSpan, immutableAsSpan))
                    {
                        EmitRawPackedMeasure(sb, body, member, number, listAsSpan, immutableAsSpan);
                    }
                    else
                    {
                        EmitRawRepeatedMeasure(sb, body, member, number, listAsSpan, immutableAsSpan,
                            RawRepeatedMessageTarget(member, measurable));
                    }
                    if (repeatedGuard) Line(sb, indent, "}");
                    goto measured;
                }

                if (member.IsNullable)
                {
                    // presence decides, not value; a declared default nests inside, exactly as
                    // the write does
                    Line(sb, indent, $"if (tmp{number}.HasValue)");
                    Line(sb, indent, "{");
                    Line(sb, indent + 1, $"var val{number} = tmp{number}.GetValueOrDefault();");
                    if (BclMeasurable(member))
                    {
                        // a BCL body is length-prefixed, so it is tag + varint(len) + len rather
                        // than a single expression - and RawScalarMeasure has nothing for these,
                        // which previously emitted `len += 1 + ;` and failed to compile. Presence
                        // has already decided, so there is no inner value test either way.
                        if (BclFixedWidth(member) is { } nullableFixed)
                        {
                            // no length prefix: tag + a flat payload, folded to one literal
                            Line(sb, indent + 1, MeasureAdd(member, 1, nullableFixed.ToString()));
                            Line(sb, indent, "}");
                            goto measured;
                        }
                        var nullableBody = $"bcl{number}";
                        Line(sb, indent + 1, $"var {nullableBody} = {BclMeasureBody(member, $"val{number}")};");
                        Line(sb, indent + 1, MeasureAdd(member, 2,
                            $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint32((uint){nullableBody}) + {nullableBody}"));
                        Line(sb, indent, "}");
                        goto measured;
                    }
                    var measureNullable = RawScalarMeasure(member, ScalarValue(member, $"val{number}"))!;
                    if (member.DefaultLiteral is { } nullableDefault)
                    {
                        Line(sb, indent + 1, $"if (val{number} != {nullableDefault})");
                        Line(sb, indent + 1, "{");
                        Line(sb, indent + 2, MeasureAdd(member, RawScalarWireBits(member.Kind), measureNullable));
                        Line(sb, indent + 1, "}");
                    }
                    else
                    {
                        Line(sb, indent + 1, MeasureAdd(member, RawScalarWireBits(member.Kind), measureNullable));
                    }
                    Line(sb, indent, "}");
                    goto measured;
                }

                // a tuple measures every scalar unconditionally, as it writes
                if (contract.IsTuple && member.Kind is not (ProtoMemberKind.String
                    or ProtoMemberKind.Bytes or ProtoMemberKind.Message))
                {
                    if (BclMeasurable(member))
                    {
                        // third branch that has to know about the length-prefixed BCL body, after
                        // the nullable one and the switch below. RawScalarMeasure has nothing for
                        // these kinds, and the `!` turns that into `len += 1 + ;` - which compiles
                        // nowhere and is caught by the goldens rather than by review.
                        if (BclFixedWidth(member) is { } tupleFixed)
                        {
                            Line(sb, indent, MeasureAdd(member, 1, tupleFixed.ToString()));
                            goto measured;
                        }
                        var tupleBody = $"bcl{number}";
                        Line(sb, indent, $"var {tupleBody} = {BclMeasureBody(member, $"tmp{number}")};");
                        Line(sb, indent, MeasureAdd(member, 2,
                            $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint32((uint){tupleBody}) + {tupleBody}"));
                        goto measured;
                    }
                    Line(sb, indent, MeasureAdd(member, RawScalarWireBits(member.Kind),
                        RawScalarMeasure(member, ScalarValue(member, $"tmp{number}"))!));
                    goto measured;
                }

                switch (member.Kind)
                {
                    // the level-200 date/time pair: a length-prefixed ScaledTicks body, so the
                    // contribution is tag + varint(bodyLen) + bodyLen. DateTime is written
                    // UNCONDITIONALLY (zero is a legitimate date) while TimeSpan is guarded against
                    // Zero, and the measure has to make the same choice or the prefix is wrong.
                    case ProtoMemberKind.DateTime or ProtoMemberKind.TimeSpan
                        or ProtoMemberKind.Guid or ProtoMemberKind.Decimal when BclMeasurable(member):
                    {
                        var body = $"bcl{number}";
                        // a fixed-width member has no length prefix and needs no body local: the
                        // whole contribution folds to one literal (BclFixedWidth)
                        var fixedWidth = BclFixedWidth(member);
                        var contribution = fixedWidth is { } width
                            ? MeasureAdd(member, 1, width.ToString())
                            : MeasureAdd(member, 2,
                                $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint32((uint){body}) + {body}");
                        void EmitBody(int at)
                        {
                            if (fixedWidth is null)
                            {
                                Line(sb, at, $"var {body} = {BclMeasureBody(member, $"tmp{number}")};");
                            }
                            Line(sb, at, contribution);
                        }
                        if (member.Kind == ProtoMemberKind.DateTime
                            || member.IsRequired || member.WriteCondition is not null)
                        {
                            EmitBody(indent);
                        }
                        else
                        {
                            Line(sb, indent, $"if ({ScalarGuard(member, $"tmp{number}")})");
                            Line(sb, indent, "{");
                            EmitBody(indent + 1);
                            Line(sb, indent, "}");
                        }
                        break;
                    }

                    // DateOnly/TimeOnly are written UNCONDITIONALLY - zero is a legitimate date, so
                    // there is no trivial value to skip - and the measure has to agree exactly or
                    // the length prefix is wrong. Kept as its own arm rather than folded in below,
                    // because the difference is the guard, not the sizing.
                    case ProtoMemberKind.DateOnly or ProtoMemberKind.TimeOnly:
                        Line(sb, indent, MeasureAdd(member, RawScalarWireBits(member.Kind),
                            RawScalarMeasure(member, ScalarValue(member, $"tmp{number}"))!));
                        break;

                    case ProtoMemberKind.Bool or ProtoMemberKind.Int32 or ProtoMemberKind.SByte
                        or ProtoMemberKind.Int16 or ProtoMemberKind.UInt32 or ProtoMemberKind.Byte
                        or ProtoMemberKind.UInt16 or ProtoMemberKind.Char or ProtoMemberKind.Int64
                        or ProtoMemberKind.UInt64 or ProtoMemberKind.Single or ProtoMemberKind.Double
                        // nint/nuint ARE guarded, unlike the date/time pair above
                        or ProtoMemberKind.IntPtr or ProtoMemberKind.UIntPtr:
                        var add = MeasureAdd(member, RawScalarWireBits(member.Kind),
                            RawScalarMeasure(member, ScalarValue(member, $"tmp{number}"))!);
                        // IsRequired means field presence: no guard, as on the write
                        if (member.IsRequired || member.WriteCondition is not null)
                        {
                            Line(sb, indent, add);
                        }
                        else
                        {
                            Line(sb, indent, $"if ({ScalarGuard(member, $"tmp{number}")}) {add}");
                        }
                        break;
                    case ProtoMemberKind.String when member.DefaultLiteral is { } declared
                        && !member.IsRequired && member.WriteCondition is null:
                        Line(sb, indent, $"if (tmp{number} != null && tmp{number} != {declared})");
                        Line(sb, indent, "{");
                        Line(sb, indent + 1, MeasureAdd(member, 2,
                            $"global::ProtoBuf.ProtoWriter.State.MeasureRawString(tmp{number})"));
                        Line(sb, indent, "}");
                        break;
                    case ProtoMemberKind.String:
                        Line(sb, indent, $"if (tmp{number} != null)");
                        Line(sb, indent, "{");
                        Line(sb, indent + 1, MeasureAdd(member, 2,
                            $"global::ProtoBuf.ProtoWriter.State.MeasureRawString(tmp{number})"));
                        Line(sb, indent, "}");
                        break;
                    case ProtoMemberKind.Uri:
                        Line(sb, indent, $"if (tmp{number} != null)");
                        Line(sb, indent, "{");
                        Line(sb, indent + 1, MeasureAdd(member, 2,
                            $"global::ProtoBuf.ProtoWriter.State.MeasureRawString(tmp{number}.OriginalString)"));
                        Line(sb, indent, "}");
                        break;
                    case ProtoMemberKind.Bytes:
                        Line(sb, indent, $"if (tmp{number} != null)");
                        Line(sb, indent, "{");
                        Line(sb, indent + 1, MeasureAdd(member, 2,
                            $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint32((uint)tmp{number}.Length) + tmp{number}.Length"));
                        Line(sb, indent, "}");
                        break;
                    case ProtoMemberKind.Message:
                    {
                        var target = measurable[member.TypeName!];
                        var targetName = Sanitise(member.TypeName!);
                        var inner = indent;
                        if (!target.IsValueType)
                        {
                            Line(sb, indent, $"if (tmp{number} != null)");
                            Line(sb, indent, "{");
                            inner++;
                        }
                        // THE SLOT BELONGS TO THE SITE, not to the contract being measured, and
                        // that is the whole correctness argument: a slot is reserved exactly where
                        // the write will call Next(), one for one, in the same order. Three cases,
                        // and getting any of them wrong shifts every later length (gap B38):
                        //   - length-prefixed raw write -> reserve here, fill after the recursion;
                        //   - GROUPED raw write -> no length on the wire, so no slot, but the body
                        //     is still walked by RawWrite_ so its own sites still reserve;
                        //   - classic write -> a null buffer, which suppresses reservation all the
                        //     way down: that sub-tree is re-measured by its own Write entry.
                        // Measure-eligibility is WIDER than write-eligibility (the measure arm takes
                        // anything in `measurable`; the write arm additionally refuses a nullable
                        // member, a non-default format, ...), which under the old dictionary was
                        // free - an entry nobody read cost nothing - and positionally is not.
                        var unaryTarget = RawNativeMessageTarget(member, measurable);
                        var unaryGrouped = member.DataFormat == ProtoDataFormat.Group;
                        if (unaryTarget is not null && !unaryGrouped)
                        {
                            Line(sb, inner, $"var slot{number} = slots.Reserve();");
                            Line(sb, inner, $"sub = Measure_{targetName}(tmp{number}, depth, slots);");
                            Line(sb, inner, $"slots.Set(slot{number}, sub);");
                        }
                        else
                        {
                            Line(sb, inner, $"sub = Measure_{targetName}(tmp{number}, depth, {(unaryTarget is null ? "null" : "slots")});");
                        }
                        if (member.DataFormat == ProtoDataFormat.Group)
                        {
                            // no length prefix: a start-group tag, the body, an end-group tag.
                            // Both tags carry the same field number and differ only in wire type
                            // (3 vs 4), which cannot change their encoded length - so this is the
                            // body plus two folded constants, and no varint measure at all
                            Line(sb, inner, MeasureAddGroup(member, "sub"));
                        }
                        else
                        {
                            Line(sb, inner, MeasureAdd(member, 2,
                                $"global::ProtoBuf.ProtoWriter.State.MeasureRawVarint64((ulong)sub) + sub"));
                        }
                        if (!target.IsValueType) Line(sb, indent, "}");
                        break;
                    }
                    default:
                        throw new InvalidOperationException(
                            $"unmeasurable member slipped eligibility: {contract.TypeName}.{member.Name} ({member.Kind})");
                }

            measured:
                if (condition is not null) Line(sb, baseIndent, "}");
            }

            // the kept-but-unrecognised fields go out after every declared member, and carry
            // their own headers - so their size is simply the blob's length
            if (contract.Extensible != ProtoExtensibleKind.None)
            {
                Line(sb, baseIndent, $"len += global::ProtoBuf.ProtoWriter.State.MeasureRawExtensionData(value{ExtensionType(contract)});");
            }
        }

        /// <summary>
        /// The measure mirror of <see cref="EmitRawRepeatedWrite"/>. Fixed-width elements of a
        /// non-nullable spelling fold to count-times-constant; everything else loops. A null
        /// element throws HERE, before a single byte is written - the measure runs first, so it
        /// owns the failure the stateful engine raised mid-write.
        /// </summary>
        private static void EmitRawRepeatedMeasure(StringBuilder sb, int indent, ProtoMemberPlan member, string number,
            bool listAsSpan, bool immutableAsSpan, ProtoContractPlan? messageTarget)
        {
            // the compatibility-level BCL kinds are length-prefixed too, which RawScalarWireBits
            // does not know - it answers for the raw SCALAR kinds only
            var wire = member.Kind is ProtoMemberKind.String or ProtoMemberKind.Message
                or ProtoMemberKind.Bytes || RawRepeatedBclMeasurable(member)
                ? 2 : RawScalarWireBits(member.Kind);
            var tagLen = VarintLen((uint)((member.FieldNumber << 3) | wire));
            var nullableElement = member.ElementTypeName?.EndsWith("?", StringComparison.Ordinal) == true;
            var count = member.Repeated.Factory is "CreateVector" or "CreateImmutableArray"
                ? $"tmp{number}.Length" : $"tmp{number}.Count";
            if (!nullableElement && member.Kind is ProtoMemberKind.Bool or ProtoMemberKind.Single or ProtoMemberKind.Double)
            {
                var width = member.Kind switch
                {
                    ProtoMemberKind.Bool => 1,
                    ProtoMemberKind.Single => 4,
                    _ => 8,
                };
                // the long literal keeps the count-fold in 64-bit arithmetic: a colossal
                // collection could overflow an int multiply where the sum is still legal
                Line(sb, indent, $"len += {count} * {tagLen + width}L;  // {member.Name}");
                return;
            }
            var source = RepeatedSpan(member, number, listAsSpan, immutableAsSpan) ?? $"tmp{number}";
            var item = $"item{number}";
            Line(sb, indent, $"foreach (var {item} in {source})");
            Line(sb, indent, "{");
            if (member.Kind is ProtoMemberKind.String or ProtoMemberKind.Bytes || nullableElement
                || (messageTarget is not null && !messageTarget.IsValueType))
            {
                Line(sb, indent + 1, $"if ({item} is null) global::ProtoBuf.ProtoWriter.State.ThrowNullRepeatedContents<{member.ElementTypeName}>();");
            }
            if (RawRepeatedBclMeasurable(member))
            {
                // the unary BCL shape, per element: tag + varint(body) + body. Its own local rather
                // than the shared `sub`, which is reserved for sub-message lengths and is declared
                // by matching on `sub = Measure_`
                var elementBody = $"bcl{number}";
                Line(sb, indent + 1, $"var {elementBody} = {BclMeasureBody(member, item)};");
                Line(sb, indent + 1, $"len += {tagLen} + global::ProtoBuf.ProtoWriter.State.MeasureRawVarint32((uint){elementBody}) + {elementBody};");
            }
            else if (messageTarget is not null)
            {
                var targetName = Sanitise(member.TypeName!);
                // reached only where messageTarget is non-null, and the caller obtained that from
                // RawRepeatedMessageTarget - i.e. it IS the write-eligibility test. A grouped
                // element carries no length, so it takes no slot; see the unary site's note
                if (member.DataFormat == ProtoDataFormat.Group)
                {
                    Line(sb, indent + 1, $"sub = Measure_{targetName}({item}, depth, slots);");
                }
                else
                {
                    Line(sb, indent + 1, $"var slot{number} = slots.Reserve();");
                    Line(sb, indent + 1, $"sub = Measure_{targetName}({item}, depth, slots);");
                    Line(sb, indent + 1, $"slots.Set(slot{number}, sub);");
                }
                // a grouped element carries no length prefix: start tag + body + end tag, and both
                // tags encode to the same width (same field number, wire type differs only in the
                // low three bits), so they fold to one constant - MeasureAddGroup's shape, per item
                Line(sb, indent + 1, member.DataFormat == ProtoDataFormat.Group
                    ? $"len += {tagLen * 2} + sub;"
                    : $"len += {tagLen} + global::ProtoBuf.ProtoWriter.State.MeasureRawVarint64((ulong)sub) + sub;");
            }
            else if (member.Kind == ProtoMemberKind.String)
            {
                Line(sb, indent + 1, $"len += {tagLen} + global::ProtoBuf.ProtoWriter.State.MeasureRawString({item});");
            }
            else if (member.Kind == ProtoMemberKind.Bytes)
            {
                // identical in shape to the unary bytes measure: a length prefix, then the payload
                Line(sb, indent + 1, $"len += {tagLen} + global::ProtoBuf.ProtoWriter.State.MeasureRawVarint32((uint){item}.Length) + {item}.Length;");
            }
            else
            {
                var local = nullableElement ? $"{item}.GetValueOrDefault()" : item;
                var payload = RawScalarMeasure(member, ScalarValue(member, local))!;
                Line(sb, indent + 1, int.TryParse(payload, out var constant)
                    ? $"len += {tagLen + constant};"
                    : $"len += {tagLen} + {payload};");
            }
            Line(sb, indent, "}");
        }

        /// <summary>
        /// The value handed to the write method: an enum needs casting down to its underlying type,
        /// while a char converts to ushort implicitly.
        /// </summary>
        private static string ScalarValue(ProtoMemberPlan member, string local)
            => member.EnumTypeName is null ? local : $"({UnderlyingKeyword(member.Kind)}){local}";

        /// <summary>
        /// The value read back: cast up to the enum type, or to char, since the read methods deal in
        /// the underlying scalar.
        /// </summary>
        /// <summary>ZigZag reads need a wire-type hint first; no other format does.</summary>
        private static string? ScalarReadHint(ProtoMemberPlan member)
            => member.DataFormat == ProtoDataFormat.ZigZag
                ? "state.Hint(global::ProtoBuf.WireType.SignedVarint);" : null;

        /// <summary>
        /// The <c>BclHelpers</c> method suffix for a compatibility-level BCL type, or null if this
        /// member is not one.
        /// </summary>
        /// <remarks>
        /// Taken from ref-emit at each level. Note the level has already absorbed
        /// <c>DataFormat.WellKnown</c>, and that <c>FixedSize</c> selects the 16-byte Guid only at
        /// level 300 â€” below that it is simply ignored.
        /// </remarks>
        private static string? BclSuffix(ProtoMemberPlan member) => member.Kind switch
        {
            ProtoMemberKind.DateTime => member.CompatibilityLevel >= 240 ? "Timestamp" : "DateTime",
            ProtoMemberKind.TimeSpan => member.CompatibilityLevel >= 240 ? "Duration" : "TimeSpan",
            ProtoMemberKind.Guid => member.CompatibilityLevel >= 300
                ? (member.DataFormat == ProtoDataFormat.FixedSize ? "GuidBytes" : "GuidString")
                : "Guid",
            ProtoMemberKind.Decimal => member.CompatibilityLevel >= 300 ? "DecimalString" : "Decimal",

            // these two also live on BclHelpers, but are *not* compatibility-level types: the level
            // does not reach them, and the header is a varint rather than a length prefix
            ProtoMemberKind.DateOnly => "DateOnly",
            ProtoMemberKind.TimeOnly => "TimeOnly",
            _ => null,
        };

        /// <param name="discard">
        /// The result is going nowhere, so it is emitted as a bare statement â€” which means the casts
        /// have to go, since a cast expression is not a valid C# statement.
        /// </param>
        /// <summary>
        /// The field-header wire type for a BCL member. Length-prefixed by default, but
        /// <c>DataFormat</c> shifts some combinations â€” and not uniformly.
        /// </summary>
        /// <remarks>
        /// This is a probed table, not a rule: ref-emit takes the wire type from whichever serializer
        /// (type, level, format) resolves to, and the result has real quirks. <c>decimal</c> ignores
        /// the format entirely; <c>Guid</c> honours <c>Group</c> but ignores <c>FixedSize</c> below
        /// level 300 (where it instead selects the 16-byte form); <c>DateTime</c> and
        /// <c>TimeSpan</c> honour both. <c>ZigZag</c> is refused â€” it throws while building the model.
        /// </remarks>
        private static string BclWireType(ProtoMemberPlan member) => member.Kind switch
        {
            // DateOnly/TimeOnly are BclHelpers calls but not compatibility-level types; ref-emit
            // gives them a plain varint header, and DataFormat does not shift it
            ProtoMemberKind.DateOnly or ProtoMemberKind.TimeOnly => "Varint",
            _ => BclWireTypeByFormat(member),
        };

        private static string BclWireTypeByFormat(ProtoMemberPlan member) => member.DataFormat switch
        {
            ProtoDataFormat.Group when member.Kind != ProtoMemberKind.Decimal => "StartGroup",
            ProtoDataFormat.FixedSize when member.Kind
                is ProtoMemberKind.DateTime or ProtoMemberKind.TimeSpan => "Fixed64",
            _ => "String",
        };

        /// <summary>
        /// <c>UriDecorator</c>'s read: relative and absolute both round-trip, hence the kind.
        /// </summary>
        private static string NewUri(string text)
            => $"new global::System.Uri({text}, global::System.UriKind.RelativeOrAbsolute)";

        private static string ScalarRead(ProtoMemberPlan member, bool discard = false)
        {
            if (member.Kind == ProtoMemberKind.Parseable)
            {
                return $"{member.DeclaredTypeName}.Parse(state.ReadString())";
            }
            if (BclSuffix(member) is { } bcl) return $"global::ProtoBuf.BclHelpers.Read{bcl}(ref state)";

            var call = $"state.{ScalarSuffix(member.Kind, "Read")}()";
            if (discard) return call;
            if (member.EnumTypeName is { } enumType) return $"({enumType}){call}";
            return member.Kind == ProtoMemberKind.Char ? $"(char){call}" : call;
        }

        private static string UnderlyingKeyword(ProtoMemberKind kind) => kind switch
        {
            ProtoMemberKind.SByte => "sbyte",
            ProtoMemberKind.Byte => "byte",
            ProtoMemberKind.Int16 => "short",
            ProtoMemberKind.UInt16 => "ushort",
            ProtoMemberKind.Int32 => "int",
            ProtoMemberKind.UInt32 => "uint",
            ProtoMemberKind.Int64 => "long",
            ProtoMemberKind.UInt64 => "ulong",
            _ => kind.ToString(),
        };

        /// <summary>The <c>ReadXxx</c>/<c>WriteXxx</c> name for a scalar kind.</summary>
        private static string ScalarSuffix(ProtoMemberKind kind, string prefix) => prefix + (kind switch
        {
            ProtoMemberKind.Bool => "Boolean",
            ProtoMemberKind.Single => "Single",
            ProtoMemberKind.Double => "Double",
            ProtoMemberKind.Char => "UInt16", // a char goes on the wire as a ushort
            _ => kind.ToString(), // SByte, Byte, Int16, UInt16, Int32, UInt32, Int64, UInt64
        });

        private static string ScalarWireType(ProtoMemberPlan member) => member.DataFormat switch
        {
            // ZigZag is always the signed varint; FixedSize picks its width from the member
            ProtoDataFormat.ZigZag => "SignedVarint",
            ProtoDataFormat.FixedSize => Is64Bit(member.Kind) ? "Fixed64" : "Fixed32",
            _ => member.Kind switch
            {
                ProtoMemberKind.Single => "Fixed32",
                ProtoMemberKind.Double => "Fixed64",
                _ => "Varint",
            },
        };

        private static bool Is64Bit(ProtoMemberKind kind)
            => kind is ProtoMemberKind.Int64 or ProtoMemberKind.UInt64 or ProtoMemberKind.Double
                // ref-emit asks GetIntWireType for width 64 regardless of the platform
                or ProtoMemberKind.IntPtr or ProtoMemberKind.UIntPtr;

        /// <summary>
        /// The "is this worth writing" test: a member equal to its default is omitted, where the
        /// default is <c>[DefaultValue]</c> if declared and the type's own default otherwise.
        /// </summary>
        private static string ScalarGuard(ProtoMemberPlan member, string local)
        {
            // note: IsRequired is handled by the callers omitting the test entirely, rather than
            // by returning "true" here - generated code is read by people
            if (member.DefaultLiteral is { } declared) return $"{local} != {declared}";

            // an enum compares against its own zero, which need not have a declared name
            if (member.EnumTypeName is { } enumType) return $"{local} != default({enumType})";

            return member.Kind switch
            {
                ProtoMemberKind.Bool => local,
                ProtoMemberKind.Single => $"{local} != 0f",
                ProtoMemberKind.Double => $"{local} != 0d",
                // DateTime is the odd one out: ref-emit writes it unconditionally, so it never
                // reaches here (see the write, which skips the test for it entirely)
                ProtoMemberKind.TimeSpan => $"{local} != global::System.TimeSpan.Zero",
                ProtoMemberKind.Guid => $"{local} != global::System.Guid.Empty",
                ProtoMemberKind.Decimal => $"{local} != 0m",
                _ => $"{local} != 0",
            };
        }

        private static void Line(StringBuilder sb, int indent, string text)
            => sb.Append(' ', indent * 4).AppendLine(text);
    }
