        // the runtime surface the emitted code binds to; all of it is public API on protobuf-net.Grpc,
        // so generated code never needs InternalsVisibleTo
        private const string EmptyTypeName = "global::ProtoBuf.Grpc.Internal.Empty";
        private const string ReshapeTypeName = "global::ProtoBuf.Grpc.Internal.Reshape";
        private const string RegistryTypeName = "global::ProtoBuf.Grpc.Internal.GeneratedProxyRegistry";
        private const string BinderConfigurationTypeName = "global::ProtoBuf.Grpc.Configuration.BinderConfiguration";
        private const string CallContextTypeName = "global::ProtoBuf.Grpc.CallContext";
        private const string ServerMethodBinderTypeName = "global::ProtoBuf.Grpc.Configuration.IServerMethodBinder";
        private const string GeneratedNamespace = "ProtoBuf.Grpc.Generated";
        private const string GeneratedCodeAttribute = "[global::System.CodeDom.Compiler.GeneratedCode(\"protobuf-net.BuildTools\", \"1.0\")]";

        /// <summary>
        /// Emit the client proxy, the server bindings, and the module initializer that registers both.
        /// </summary>
        private static string Emit(GrpcInterfaceModel contract)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("#pragma warning disable CS0618 // ProtoBuf.Grpc.Internal.Reshape is intentionally obsoleted for direct consumption");
            sb.AppendLine();
            sb.Append("namespace ").AppendLine(GeneratedNamespace);
            sb.AppendLine("{");

            EmitClientProxy(sb, contract);
            sb.AppendLine();
            EmitServerBindings(sb, contract);
            sb.AppendLine();
            EmitModuleInitializer(sb, contract);

            sb.AppendLine("}");
            return sb.ToString();
        }

        /// <summary>
        /// A <c>[ModuleInitializer]</c> per contract, so that consumption is a static reference graph
        /// the trimmer and the AOT compiler can both see; nothing looks up attributes at runtime.
        /// </summary>
        private static void EmitModuleInitializer(StringBuilder sb, GrpcInterfaceModel contract)
        {
            sb.Append("    ").AppendLine(GeneratedCodeAttribute);
            sb.Append("    internal static class ").AppendLine(contract.InitTypeName);
            sb.AppendLine("    {");
            sb.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
            sb.AppendLine("        internal static void Init()");
            sb.AppendLine("        {");
            sb.Append("            ").Append(RegistryTypeName).Append(".RegisterClient<").Append(contract.InterfaceFullName)
                .Append(">(").Append(contract.ProxyTypeName).AppendLine(".Create);");
            sb.Append("            ").Append(RegistryTypeName).Append(".RegisterServer(typeof(").Append(contract.InterfaceFullName)
                .Append("), typeof(").Append(contract.ServerBindingsTypeName).AppendLine("));");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
        }

        // -------- client --------

        private static void EmitClientProxy(StringBuilder sb, GrpcInterfaceModel contract)
        {
            sb.Append("    ").AppendLine(GeneratedCodeAttribute);
            sb.AppendLine("    [global::System.Diagnostics.DebuggerNonUserCode]");
            sb.Append("    internal sealed class ").Append(contract.ProxyTypeName)
                .Append(" : global::Grpc.Core.ClientBase, ").AppendLine(contract.InterfaceFullName);
            sb.AppendLine("    {");

            // Marshallers and Method<,> descriptors are instance fields built from the caller-supplied
            // BinderConfiguration: that is where custom marshaller factories live, so resolving them
            // from the static BinderConfiguration.Default (or in a static initializer) would break every
            // service whose payloads aren't marshallable under the defaults.
            var payloadTypes = PayloadTypes(contract);
            var marshallers = new Dictionary<string, string>(StringComparer.Ordinal);
            var index = 0;
            foreach (var payload in payloadTypes)
            {
                var field = "__m" + index++;
                marshallers.Add(payload, field);
                sb.Append("        private readonly global::Grpc.Core.Marshaller<").Append(payload).Append("> ").Append(field).AppendLine(";");
            }

            var methodFields = new string[contract.Operations.Length];
            for (var i = 0; i < contract.Operations.Length; i++)
            {
                var operation = contract.Operations[i];
                methodFields[i] = "__op" + i;
                sb.Append("        private readonly ").Append(MethodType(operation)).Append(" ").Append(methodFields[i]).AppendLine(";");
            }
            sb.AppendLine();

            sb.Append("        public ").Append(contract.ProxyTypeName)
                .Append("(global::Grpc.Core.CallInvoker callInvoker, ").Append(BinderConfigurationTypeName).AppendLine(" config) : base(callInvoker)");
            sb.AppendLine("        {");
            sb.Append("            if (config is null) config = ").Append(BinderConfigurationTypeName).AppendLine(".Default;");
            foreach (var payload in payloadTypes)
            {
                sb.Append("            ").Append(marshallers[payload]).Append(" = config.GetMarshaller<").Append(payload).AppendLine(">();");
            }
            for (var i = 0; i < contract.Operations.Length; i++)
            {
                var operation = contract.Operations[i];
                sb.Append("            ").Append(methodFields[i]).Append(" = new ").Append(MethodType(operation)).Append("(")
                    .Append(MethodTypeEnum(operation.Kind)).Append(", ")
                    .Append(Literal(contract.ServiceName)).Append(", ")
                    .Append(Literal(operation.OperationName)).Append(", ")
                    .Append(marshallers[operation.RequestTypeFullName]).Append(", ")
                    .Append(marshallers[operation.ResponseTypeFullName]).AppendLine(");");
            }
            sb.AppendLine("        }");
            sb.AppendLine();

            // the single-argument form is what a manual [Proxy(typeof(...))] consumer constructs
            sb.Append("        public ").Append(contract.ProxyTypeName).AppendLine("(global::Grpc.Core.CallInvoker callInvoker)");
            sb.Append("            : this(callInvoker, ").Append(BinderConfigurationTypeName).AppendLine(".Default) { }");
            sb.AppendLine();

            sb.Append("        public static ").Append(contract.InterfaceFullName)
                .Append(" Create(global::Grpc.Core.CallInvoker callInvoker, ").Append(BinderConfigurationTypeName).AppendLine(" config)");
            sb.Append("            => new ").Append(contract.ProxyTypeName).AppendLine("(callInvoker, config);");
            sb.AppendLine();
            sb.Append("        public static ").Append(contract.InterfaceFullName).AppendLine(" Create(global::Grpc.Core.CallInvoker callInvoker)");
            sb.Append("            => new ").Append(contract.ProxyTypeName).AppendLine("(callInvoker);");
            sb.AppendLine();

            sb.Append("        public override string ToString() => ").Append(Literal(contract.ServiceName + " / CallInvoker")).AppendLine(";");
            sb.AppendLine();

            for (var i = 0; i < contract.Operations.Length; i++)
            {
                EmitClientOperation(sb, contract, contract.Operations[i], methodFields[i]);
            }

            // the runtime proxy implements these as no-ops rather than binding them, because
            // infrastructure (ASP.NET Core DI, for one) calls Dispose on whatever it is handed
            if (contract.ImplementsDisposable)
            {
                sb.AppendLine("        void global::System.IDisposable.Dispose() { }");
                sb.AppendLine();
            }
            if (contract.ImplementsAsyncDisposable)
            {
                sb.AppendLine("        global::System.Threading.Tasks.ValueTask global::System.IAsyncDisposable.DisposeAsync() => default;");
                sb.AppendLine();
            }

            sb.AppendLine("    }");
        }

        private static void EmitClientOperation(StringBuilder sb, GrpcInterfaceModel contract, GrpcOperationModel operation, string methodField)
        {
            // explicit interface implementation, so the proxy's own surface stays out of the way;
            // qualified with the interface that declares the operation, which is the base when the
            // contract inherits it
            sb.Append("        ").Append(operation.ReturnTypeDisplay).Append(" ").Append(operation.DeclaringInterfaceFullName)
                .Append(".").Append(operation.MethodName).Append("(");
            for (var i = 0; i < operation.Parameters.Length; i++)
            {
                if (i > 0) sb.Append(", ");
                sb.Append(operation.Parameters[i].TypeDisplay).Append(" ").Append(operation.Parameters[i].Name);
            }
            sb.AppendLine(")");
            sb.AppendLine("        {");

            if (operation.Context == GrpcContextKind.CancellationToken)
            {
                sb.Append("            ").Append(CallContextTypeName).Append(" __ctx = (").Append(CallContextTypeName)
                    .Append(")").Append(ContextParameterName(operation)).AppendLine(";");
            }

            var request = operation.RequestShape == GrpcArgShape.Void
                ? EmptyTypeName + ".Instance"
                : operation.Parameters[0].Name;

            var context = operation.Context switch
            {
                GrpcContextKind.CallContext => "in " + ContextParameterName(operation),
                GrpcContextKind.CancellationToken => "in __ctx",
                _ => "in " + CallContextTypeName + ".Default",
            };

            sb.Append("            ");
            if (!(operation.ResponseShape == GrpcResultShape.Sync && operation.VoidResponse)) sb.Append("return ");
            sb.Append(ReshapeTypeName).Append(".").Append(ClientReshapeMethod(operation)).Append("(")
                .Append(context).Append(", this.CallInvoker, ").Append(methodField).Append(", ").Append(request).AppendLine(", null);");

            sb.AppendLine("        }");
            sb.AppendLine();
        }

