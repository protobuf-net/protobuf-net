#nullable enable
// The per-operation client and server bodies here - the Reshape call selection, the server handler
// shapes, and the response-adaptation switch - are adapted from
// https://github.com/protobuf-net/protobuf-net/pull/1255 by Victor Irzak (@virzak), which moved them
// from https://github.com/protobuf-net/protobuf-net.Grpc/pull/364.
//
// What is new here is everything about *where the code goes*: into the consumer's declared partial
// rather than a fixed namespace, with a typeof-chain CreateClient override instead of a registry,
// marshallers sourced from a named [ProtoModel], and server bindings as nested
// IServiceMethodProvider<TImpl> implementations instead of a MakeGenericMethod'd Bind<TService>.
using ProtoBuf.BuildTools.Internal.Grpc;
using System;
using System.Collections.Generic;
using System.Text;

namespace ProtoBuf.BuildTools.Generators
{
    public sealed partial class GrpcProxyGenerator
    {
        // every name below is public API on protobuf-net.Grpc / Grpc.Core / Grpc.AspNetCore.Server,
        // so generated code never needs InternalsVisibleTo and this generator needs no runtime changes
        private const string EmptyTypeName = "global::ProtoBuf.Grpc.Internal.Empty";

        /// <summary>
        /// The wire type of a byte stream. Like <c>Empty</c>, <c>MarshallerCache</c> pre-seeds its
        /// bespoke marshaller, so it resolves without a <c>TypeModel</c> and without reflection.
        /// </summary>
        private const string BytesValueTypeName = "global::ProtoBuf.Grpc.Internal.BytesValue";
        private const string ReshapeTypeName = "global::ProtoBuf.Grpc.Internal.Reshape";
        private const string BinderConfigurationTypeName = "global::ProtoBuf.Grpc.Configuration.BinderConfiguration";
        private const string MarshallerFactoryTypeName = "global::ProtoBuf.Grpc.Configuration.MarshallerFactory";
        private const string ProtoBufMarshallerFactoryTypeName = "global::ProtoBuf.Grpc.Configuration.ProtoBufMarshallerFactory";
        private const string ServiceBinderTypeName = "global::ProtoBuf.Grpc.Configuration.ServiceBinder";
        private const string CallContextTypeName = "global::ProtoBuf.Grpc.CallContext";
        private const string ServerCallContextTypeName = "global::Grpc.Core.ServerCallContext";
        private const string GeneratedCodeAttribute = "[global::System.CodeDom.Compiler.GeneratedCode(\"protobuf-net.BuildTools\", \"1.0\")]";

        private const string MemberTypes = "global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes";

        /// <summary>Mirrors <c>ProtoBuf.Internal.DynamicAccess.ContractType</c>, which is internal.</summary>
        private const string DynamicallyAccessedMembers
            = "global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMembers("
            + MemberTypes + ".PublicConstructors | " + MemberTypes + ".NonPublicConstructors | "
            + MemberTypes + ".PublicParameterlessConstructor | "
            + MemberTypes + ".PublicProperties | " + MemberTypes + ".NonPublicProperties | "
            + MemberTypes + ".PublicFields | " + MemberTypes + ".NonPublicFields | "
            + MemberTypes + ".PublicMethods | " + MemberTypes + ".NonPublicMethods | "
            + MemberTypes + ".PublicNestedTypes | " + MemberTypes + ".NonPublicNestedTypes)";

        private static string Emit(GrpcModelPlan plan, bool hasAspNetCore, bool annotateTrimming)
        {
            if (plan.DownLevel) return EmitDownLevel(plan);

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("#pragma warning disable CS0618 // ProtoBuf.Grpc.Internal.Reshape is intentionally obsoleted for direct consumption");
            sb.AppendLine();

            var indent = 0;
            if (!string.IsNullOrEmpty(plan.NamespaceName))
            {
                sb.Append("namespace ").AppendLine(plan.NamespaceName);
                sb.AppendLine("{");
                indent = 1;
            }

            EmitFactory(sb, indent, plan, hasAspNetCore, annotateTrimming);

            if (hasAspNetCore && HasAnyServerBindings(plan))
            {
                sb.AppendLine();
                EmitRegistration(sb, indent, plan);
            }

            if (indent != 0) sb.AppendLine("}");
            return sb.ToString();
        }

        /// <summary>
        /// The shape emitted below the language floor: enough to satisfy <c>ClientFactory</c>, with the
        /// client half handed to the reflective runtime factory.
        /// </summary>
        /// <remarks>
        /// <para>
        /// Everything here has to parse at the consumer's language version, which is by definition
        /// below C# 9 and may be 7.3 (the net4x and netstandard2.0 default) - so no <c>#nullable</c>
        /// directive, no nullable annotations and no target-typed <c>new</c>. Expression-bodied members
        /// and auto-property initialisers are C# 6 and are fine.
        /// </para>
        /// <para>
        /// The marshallers deliberately stay on <c>BinderConfiguration.Default</c> even where a Model
        /// was named: the serializer generator's own floor is C# 12, so down here that model type has
        /// no generated half and no <c>Instance</c> to reference.
        /// </para>
        /// <para>
        /// No registration method is emitted, and that asymmetry is the point. The client half can be
        /// delegated because <c>ClientFactory.Default</c> is a real fallback; there is no equivalent
        /// for the server, and an <c>AddMyServices()</c> that ran but bound nothing would give a server
        /// that starts and serves nothing. A missing method is a loud compile error next to a warning
        /// that explains it, which is the better failure.
        /// </para>
        /// </remarks>
        private static string EmitDownLevel(GrpcModelPlan plan)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine();

            var indent = 0;
            if (!string.IsNullOrEmpty(plan.NamespaceName))
            {
                sb.Append("namespace ").AppendLine(plan.NamespaceName);
                sb.AppendLine("{");
                indent = 1;
            }

            Line(sb, indent, GeneratedCodeAttribute);
            Line(sb, indent, $"partial class {plan.TypeName}");
            Line(sb, indent, "{");

            if (plan.EmitConstructor)
            {
                var accessibility = plan.IsSealed ? "private" : "protected";
                Line(sb, indent + 1, $"{accessibility} {plan.TypeName}() {{ }}");
                sb.AppendLine();
            }

            if (plan.EmitInstance)
            {
                Line(sb, indent + 1, $"public static {plan.TypeName} Instance {{ get; }} = new {plan.TypeName}();");
                sb.AppendLine();
            }

            Line(sb, indent + 1, "/// <summary>No build-time proxies were generated: the language version is below"
                + $" C# {MinimumLanguageVersionDisplay}, so this falls back to the reflective runtime factory."
                + " Raise LangVersion to get trim/AOT-friendly proxies.</summary>");
            Line(sb, indent + 1, $"protected override {BinderConfigurationTypeName} BinderConfiguration");
            Line(sb, indent + 2, $"=> {BinderConfigurationTypeName}.Default;");
            sb.AppendLine();
            Line(sb, indent + 1, "/// <inheritdoc/>");
            Line(sb, indent + 1, "public override TService CreateClient<TService>(global::Grpc.Core.CallInvoker channel)");
            Line(sb, indent + 2, $"=> global::{ClientFactoryTypeName}.Default.CreateClient<TService>(channel);");

            Line(sb, indent, "}");
            if (indent != 0) sb.AppendLine("}");
            return sb.ToString();
        }

        private static bool HasAnyServerBindings(GrpcModelPlan plan)
        {
            foreach (var contract in plan.Contracts)
            {
                if (contract.ImplementationTypeFullName is not null) return true;
            }
            return false;
        }

        // -------- the consumer's partial --------

        private static void EmitFactory(StringBuilder sb, int indent, GrpcModelPlan plan, bool hasAspNetCore, bool annotateTrimming)
        {
            Line(sb, indent, GeneratedCodeAttribute);
            Line(sb, indent, $"partial class {plan.TypeName}");
            Line(sb, indent, "{");

            if (plan.EmitConstructor)
            {
                // removes the implicit public constructor, so `new MyServices()` no longer compiles
                // and Instance is the obvious route. protected rather than private where the type is
                // not sealed, or nothing could derive from it. Declaring any constructor opts out.
                var accessibility = plan.IsSealed ? "private" : "protected";
                Line(sb, indent + 1, "/// <summary>Use <see cref=\"Instance\"/>; a client factory holds a"
                    + " marshaller cache, and is intended to be shared rather than constructed per use.</summary>");
                Line(sb, indent + 1, $"{accessibility} {plan.TypeName}() {{ }}");
                sb.AppendLine();
            }

            if (plan.EmitInstance)
            {
                Line(sb, indent + 1, "/// <summary>A shared instance of this factory; it is thread-safe"
                    + " and caches marshallers, so it is intended to be reused.</summary>");
                Line(sb, indent + 1, $"public static {plan.TypeName} Instance {{ get; }} = new {plan.TypeName}();");
                sb.AppendLine();
            }

            EmitBinderConfiguration(sb, indent + 1, plan, annotateTrimming);
            EmitCreateClient(sb, indent + 1, plan);

            foreach (var contract in plan.Contracts)
            {
                sb.AppendLine();
                EmitClientProxy(sb, indent + 1, contract);
            }

            if (hasAspNetCore)
            {
                foreach (var contract in plan.Contracts)
                {
                    if (contract.ImplementationTypeFullName is null) continue;
                    sb.AppendLine();
                    EmitServerProvider(sb, indent + 1, contract);
                }
            }

            Line(sb, indent, "}");
        }

        /// <summary>
        /// The marshaller source. This is the single most important line the generator emits.
        /// </summary>
        /// <remarks>
        /// Pointing this at a <c>[ProtoModel]</c>-generated <c>TypeModel</c> is what makes the payload
        /// side static. Left at <c>BinderConfiguration.Default</c> it would be
        /// <c>RuntimeTypeModel.Default</c>, whose serializers are built by reflection and ref-emit -
        /// so the proxies would be AOT-safe and the bytes they carry would not.
        /// </remarks>
        private static void EmitBinderConfiguration(StringBuilder sb, int indent, GrpcModelPlan plan, bool annotateTrimming)
        {
            Line(sb, indent, "/// <inheritdoc/>");
            Line(sb, indent, $"protected override {BinderConfigurationTypeName} BinderConfiguration => __config;");
            sb.AppendLine();

            if (plan.ModelTypeFullName is null)
            {
                // PBN3010 has already said this is a mistake; emitting the default keeps the build
                // working (and correct under JIT) rather than failing over a warning. Note we must
                // *not* pre-populate marshallers onto BinderConfiguration.Default - it is shared
                // process-wide, and mutating it would reach every other consumer.
                Line(sb, indent, $"private readonly {BinderConfigurationTypeName} __config = {BinderConfigurationTypeName}.Default;");
                sb.AppendLine();
                return;
            }

            var model = plan.ModelTypeFullName;
            Line(sb, indent, $"private readonly {BinderConfigurationTypeName} __config = __CreateConfiguration();");
            sb.AppendLine();

            // The marshaller cache is pre-populated, and this is load-bearing rather than an
            // optimisation. Left to resolve itself, MarshallerCache.CreateMarshaller<T> asks
            // MarshallerFactory.CanSerialize(typeof(T)) -> TypeModel.CanSerialize(Type) ->
            // DynamicStub -> Type.MakeGenericType(ConcreteStub<T>), whose failure is swallowed into
            // a "no, can't serialize that" - so under native AOT every payload fails with
            // "No marshaller available for X" even though the model has a perfectly good serializer
            // for it. Verified by a native publish of src/AotGrpcSmoke, which fails exactly that way
            // without this. SetMarshaller is public, and GetMarshaller<T> checks the cache first.
            Line(sb, indent, $"private static {BinderConfigurationTypeName} __CreateConfiguration()");
            Line(sb, indent, "{");
            Line(sb, indent + 1, $"var config = {BinderConfigurationTypeName}.Create(");
            Line(sb, indent + 2, $"new {MarshallerFactoryTypeName}[] {{ {ProtoBufMarshallerFactoryTypeName}.Create({model}.Instance) }});");
            foreach (var payload in AllPayloadTypes(plan))
            {
                Line(sb, indent + 1, $"config.SetMarshaller<{payload}>(__CreateMarshaller<{payload}>());");
            }
            Line(sb, indent + 1, "return config;");
            Line(sb, indent, "}");
            sb.AppendLine();

            // The write path's fallback arm calls TypeModel.Serialize<T>(Stream, T, object), which
            // demands DynamicAccess.ContractType on T; without restating it these helpers produce an
            // IL2091. Restating pushes the demand to the callers, which are the SetMarshaller<T>
            // lines above - concrete contract types - so it terminates immediately and costs nothing.
            // DynamicAccess is internal to protobuf-net, hence spelling the flags out; same approach,
            // and same constant, as ProtoModelGenerator's GetSerializer<T> override.
            var annotated = annotateTrimming ? $"[{DynamicallyAccessedMembers}] T" : "T";

            Line(sb, indent, $"private static global::Grpc.Core.Marshaller<T> __CreateMarshaller<{annotated}>()");
            Line(sb, indent + 1, "=> new global::Grpc.Core.Marshaller<T>(__Serialize<T>, __Deserialize<T>);");
            sb.AppendLine();

            // mirrors ProtoBufMarshallerFactory's contextual path, including its buffer-writer probe
            // (the managed gRPC implementation does not implement GetBufferWriter)
            Line(sb, indent, $"private static void __Serialize<{annotated}>(T value, global::Grpc.Core.SerializationContext ctx)");
            Line(sb, indent, "{");
            Line(sb, indent + 1, $"var measurer = (global::ProtoBuf.IMeasuredProtoOutput<global::System.Buffers.IBufferWriter<byte>>){model}.Instance;");
            Line(sb, indent + 1, "using var measured = measurer.Measure(value);");
            Line(sb, indent + 1, "int length = checked((int)measured.Length);");
            Line(sb, indent + 1, "ctx.SetPayloadLength(length);");
            Line(sb, indent + 1, "global::System.Buffers.IBufferWriter<byte>? writer;");
            Line(sb, indent + 1, "try { writer = ctx.GetBufferWriter(); }");
            Line(sb, indent + 1, "catch (global::System.NotSupportedException) { writer = null; }");
            Line(sb, indent + 1, "catch (global::System.NotImplementedException) { writer = null; }");
            Line(sb, indent + 1, "if (writer is not null)");
            Line(sb, indent + 1, "{");
            Line(sb, indent + 2, "measurer.Serialize(measured, writer);");
            Line(sb, indent + 2, "ctx.Complete();");
            Line(sb, indent + 1, "}");
            Line(sb, indent + 1, "else");
            Line(sb, indent + 1, "{");
            Line(sb, indent + 2, "var buffer = new byte[length];");
            Line(sb, indent + 2, "using var ms = new global::System.IO.MemoryStream(buffer);");
            Line(sb, indent + 2, $"{model}.Instance.Serialize(ms, value);");
            Line(sb, indent + 2, "ctx.Complete(buffer);");
            Line(sb, indent + 1, "}");
            Line(sb, indent, "}");
            sb.AppendLine();

            Line(sb, indent, "private static T __Deserialize<T>(global::Grpc.Core.DeserializationContext ctx)");
            Line(sb, indent + 1, $"=> ((global::ProtoBuf.IProtoInput<global::System.Buffers.ReadOnlySequence<byte>>){model}.Instance)");
            Line(sb, indent + 2, ".Deserialize<T>(ctx.PayloadAsReadOnlySequence());");
            sb.AppendLine();
        }

        /// <summary>Every payload type across every contract on the plan, ordered for stability.</summary>
        private static SortedSet<string> AllPayloadTypes(GrpcModelPlan plan)
        {
            var payloads = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var contract in plan.Contracts)
            {
                foreach (var payload in PayloadTypes(contract)) payloads.Add(payload);
            }
            // Empty and BytesValue are pre-registered by MarshallerCache itself, with hand-written
            // marshallers, and neither is a contract in anyone's model - so they must not be handed to
            // the generated model's serializer. Overriding BytesValue's would be the worse of the two:
            // it is the wire type of every byte stream, so it would change what those put on the wire.
            payloads.Remove(EmptyTypeName);
            payloads.Remove(BytesValueTypeName);
            return payloads;
        }

        /// <summary>
        /// Client dispatch as a compile-time <c>typeof</c> chain.
        /// </summary>
        /// <remarks>
        /// There is no <c>base</c> to fall back to - <c>ClientFactory.CreateClient&lt;T&gt;</c> is
        /// abstract - and falling back to <c>ClientFactory.Default</c> would quietly reintroduce
        /// ref-emit, which is the whole thing being avoided. So an unlisted contract throws, exactly
        /// as <c>TypeModel</c>'s "no serializer for type" is the backstop for a dropped contract.
        /// </remarks>
        private static void EmitCreateClient(StringBuilder sb, int indent, GrpcModelPlan plan)
        {
            Line(sb, indent, "/// <inheritdoc/>");
            Line(sb, indent, "public override TService CreateClient<TService>(global::Grpc.Core.CallInvoker channel)");
            Line(sb, indent, "{");
            foreach (var contract in plan.Contracts)
            {
                Line(sb, indent + 1, $"if (typeof(TService) == typeof({contract.InterfaceFullName}))");
                Line(sb, indent + 2, $"return (TService)(object)new {contract.ProxyTypeName}(channel, BinderConfiguration);");
            }
            // Both causes have to be covered, and the original message only covered one: a contract can
            // be absent because it was never named, or because it *was* named and then dropped with a
            // build warning. Telling the second consumer to add the attribute they already added is the
            // worst version of this message, since it sends them looking in the one place that is fine.
            Line(sb, indent + 1, "throw new global::System.InvalidOperationException(");
            Line(sb, indent + 2, $"\"No build-time gRPC proxy for \" + typeof(TService).FullName + \" in {plan.TypeName}; \"");
            Line(sb, indent + 2, "+ \"either it is not named by [ProtoService], or it was dropped at build time - \"");
            Line(sb, indent + 2, "+ \"check the build log for a PBN40xx warning naming it.\");");
            Line(sb, indent, "}");
        }

        // -------- client --------

        private static void EmitClientProxy(StringBuilder sb, int indent, GrpcInterfaceModel contract)
        {
            Line(sb, indent, GeneratedCodeAttribute);
            Line(sb, indent, "[global::System.Diagnostics.DebuggerNonUserCode]");
            Line(sb, indent, $"private sealed class {contract.ProxyTypeName} : global::Grpc.Core.ClientBase, {contract.InterfaceFullName}");
            Line(sb, indent, "{");

            // Marshallers and Method<,> descriptors are instance fields built from the supplied
            // BinderConfiguration: that is where the model (and any custom marshaller factory) lives,
            // so resolving them from a static default would defeat the point of naming a model.
            var payloadTypes = PayloadTypes(contract);
            var marshallers = new Dictionary<string, string>(StringComparer.Ordinal);
            var index = 0;
            foreach (var payload in payloadTypes)
            {
                var field = "__m" + index++;
                marshallers.Add(payload, field);
                Line(sb, indent + 1, $"private readonly global::Grpc.Core.Marshaller<{payload}> {field};");
            }

            var methodFields = new string[contract.Operations.Length];
            for (var i = 0; i < contract.Operations.Length; i++)
            {
                methodFields[i] = "__op" + i;
                Line(sb, indent + 1, $"private readonly {MethodType(contract.Operations[i])} {methodFields[i]};");
            }
            sb.AppendLine();

            Line(sb, indent + 1, $"internal {contract.ProxyTypeName}(global::Grpc.Core.CallInvoker callInvoker, {BinderConfigurationTypeName} config) : base(callInvoker)");
            Line(sb, indent + 1, "{");
            foreach (var payload in payloadTypes)
            {
                Line(sb, indent + 2, $"{marshallers[payload]} = config.GetMarshaller<{payload}>();");
            }
            for (var i = 0; i < contract.Operations.Length; i++)
            {
                var operation = contract.Operations[i];
                Line(sb, indent + 2, $"{methodFields[i]} = new {MethodType(operation)}("
                    + $"{MethodTypeEnum(operation.Kind)}, {Literal(contract.ServiceName)}, {Literal(operation.OperationName)}, "
                    + $"{marshallers[operation.RequestTypeFullName]}, {marshallers[operation.ResponseTypeFullName]});");
            }
            Line(sb, indent + 1, "}");
            sb.AppendLine();

            Line(sb, indent + 1, $"public override string ToString() => {Literal(contract.ServiceName + " / CallInvoker")};");
            sb.AppendLine();

            for (var i = 0; i < contract.Operations.Length; i++)
            {
                EmitClientOperation(sb, indent + 1, contract.Operations[i], methodFields[i]);
            }

            // the runtime proxy implements these as no-ops rather than binding them, because
            // infrastructure (ASP.NET Core DI, for one) calls Dispose on whatever it is handed
            if (contract.ImplementsDisposable)
            {
                Line(sb, indent + 1, "void global::System.IDisposable.Dispose() { }");
                sb.AppendLine();
            }
            if (contract.ImplementsAsyncDisposable)
            {
                Line(sb, indent + 1, "global::System.Threading.Tasks.ValueTask global::System.IAsyncDisposable.DisposeAsync() => default;");
                sb.AppendLine();
            }

            Line(sb, indent, "}");
        }

        private static void EmitClientOperation(StringBuilder sb, int indent, GrpcOperationModel operation, string methodField)
        {
            // explicit interface implementation, qualified with the interface that *declares* the
            // operation - which is the base when the contract inherits it. Getting that wrong is one
            // of the three bugs the source PR's port surfaced.
            var parameters = new StringBuilder();
            for (var i = 0; i < operation.Parameters.Length; i++)
            {
                if (i > 0) parameters.Append(", ");
                parameters.Append(operation.Parameters[i].TypeDisplay).Append(' ').Append(operation.Parameters[i].Name);
            }
            Line(sb, indent, $"{operation.ReturnTypeDisplay} {operation.DeclaringInterfaceFullName}.{operation.MethodName}({parameters})");
            Line(sb, indent, "{");

            if (operation.Context == GrpcContextKind.CancellationToken)
            {
                Line(sb, indent + 1, $"{CallContextTypeName} __ctx = ({CallContextTypeName}){ContextParameterName(operation)};");
            }

            var request = operation.RequestShape == GrpcArgShape.Void
                ? EmptyTypeName + ".Instance"
                : operation.Parameters[0].Name;

            var context = operation.Context switch
            {
                GrpcContextKind.CallContext => "in " + ContextParameterName(operation),
                GrpcContextKind.CancellationToken => "in __ctx",
                _ => "in " + CallContextTypeName + ".Default",
            };

            var prefix = operation.ResponseShape == GrpcResultShape.Sync && operation.VoidResponse ? "" : "return ";
            Line(sb, indent + 1, $"{prefix}{ReshapeTypeName}.{ClientReshapeMethod(operation)}("
                + $"{context}, this.CallInvoker, {methodField}, {request}, null);");
            Line(sb, indent, "}");
            sb.AppendLine();
        }

        // -------- server --------

        /// <summary>
        /// Server bindings as an <c>IServiceMethodProvider&lt;TImpl&gt;</c> nested in the factory.
        /// </summary>
        /// <remarks>
        /// <para>
        /// <c>AddCodeFirstGrpc</c> registers its own provider through <c>TryAddEnumerable</c>, and
        /// <c>MapGrpcService&lt;TImpl&gt;</c> calls <em>every</em> registered provider for that type -
        /// so a generated provider is simply added alongside, and needs no new API in
        /// protobuf-net.Grpc at all. The generated registration extension deliberately does not call
        /// <c>AddCodeFirstGrpc</c>, so the reflective provider is never registered and there is
        /// nothing to double-bind against.
        /// </para>
        /// <para>
        /// Because the implementation type is named at compile time, this closes its generics
        /// statically: no <c>MakeGenericMethod</c>, and so none of the IL3050/IL2060 suppressions the
        /// registry-based approach needed.
        /// </para>
        /// </remarks>
        private static void EmitServerProvider(StringBuilder sb, int indent, GrpcInterfaceModel contract)
        {
            var impl = contract.ImplementationTypeFullName!;
            var providerInterface = $"global::Grpc.AspNetCore.Server.Model.IServiceMethodProvider<{impl}>";

            Line(sb, indent, GeneratedCodeAttribute);
            Line(sb, indent, $"internal sealed class {contract.ProviderTypeName} : {providerInterface}");
            Line(sb, indent, "{");
            Line(sb, indent + 1, $"private readonly {BinderConfigurationTypeName} __cfg;");
            sb.AppendLine();
            Line(sb, indent + 1, $"internal {contract.ProviderTypeName}({BinderConfigurationTypeName} config) => __cfg = config;");
            sb.AppendLine();
            Line(sb, indent + 1, $"void {providerInterface}.OnServiceMethodDiscovery(");
            Line(sb, indent + 2, $"global::Grpc.AspNetCore.Server.Model.ServiceMethodProviderContext<{impl}> context)");
            Line(sb, indent + 1, "{");

            foreach (var operation in contract.Operations)
            {
                var sameType = string.Equals(operation.RequestTypeFullName, operation.ResponseTypeFullName, StringComparison.Ordinal);
                var operationLiteral = Literal(operation.MethodName);

                // per-operation try/catch so one unmarshallable payload names itself in the host's
                // startup log rather than failing the whole contract anonymously
                Line(sb, indent + 2, "try");
                Line(sb, indent + 2, "{");
                Line(sb, indent + 3, $"var __m_req = __cfg.GetMarshaller<{operation.RequestTypeFullName}>();");
                if (!sameType)
                {
                    Line(sb, indent + 3, $"var __m_resp = __cfg.GetMarshaller<{operation.ResponseTypeFullName}>();");
                }
                Line(sb, indent + 3, $"var __op = new {MethodType(operation)}({MethodTypeEnum(operation.Kind)}, "
                    + $"{Literal(contract.ServiceName)}, {Literal(operation.OperationName)}, __m_req, {(sameType ? "__m_req" : "__m_resp")});");

                // Metadata carries things like [Authorize] from the contract, so it cannot be dropped
                // without changing behaviour. Via the *configured* binder, not ServiceBinder.Default:
                // BinderConfiguration.Binder is public from protobuf-net.Grpc 1.3.6, and using the
                // default would silently ignore a consumer's custom GetMetadata override.
                //
                // The GetMethod is the one reflective call left on this path; it is bounded to
                // startup, and is over an interface the generated code already references statically.
                //
                // The parameter types are passed rather than relying on the by-name overload, and that
                // is a correctness fix rather than a nicety: Type.GetMethod(string) throws
                // AmbiguousMatchException as soon as a contract carries two operations of the same name.
                // That is a legal contract - [Operation] gives them distinct names on the wire - and it
                // used to compile perfectly and then fail at server startup.
                //
                // Reconstructing the attributes at compile time and dropping this call is deliberately
                // NOT done, and the reason is a measurement rather than a limitation: the reflective
                // route survives a native publish intact - AotGrpcSmoke carries attributes at all three
                // levels plus a real [Authorize], and every one arrives after ILC, since the typeof()s
                // just above root the metadata that keeps them.
                //
                // So a constructed list would buy one less startup-time reflective call, and cost the
                // consumer's override: GetMetadata is virtual and BinderConfiguration.Create takes a
                // custom ServiceBinder, so building the list here silently ignores it - the very bug the
                // paragraph above is about. The machinery to do it exists and is proven correct
                // (MetadataGather, AttributeRenderer, and the src/AotGrpcMetadataDiff oracle); it is the
                // trade that does not pay. See notes/aot/grpc.md.
                if (operation.MetadataExpressions.IsDefault)
                {
                    // something on this operation could not be reconstructed, so it keeps the reflective
                    // lookup and PBN4019 says why - see BuildMetadata
                    Line(sb, indent + 3, "var __meta = __cfg.Binder.GetMetadata(");
                    Line(sb, indent + 4, $"typeof({operation.DeclaringInterfaceFullName}).GetMethod({operationLiteral},");
                    Line(sb, indent + 5, $"new global::System.Type[] {{ {ParameterTypeOfs(operation)} }})!,");
                    Line(sb, indent + 4, $"typeof({contract.InterfaceFullName}), typeof({impl}));");
                }
                else if (operation.MetadataExpressions.Length == 0)
                {
                    Line(sb, indent + 3, "var __meta = global::System.Array.Empty<object>();");
                }
                else
                {
                    Line(sb, indent + 3, "var __meta = new object[]");
                    Line(sb, indent + 3, "{");
                    foreach (var expression in operation.MetadataExpressions)
                    {
                        Line(sb, indent + 4, expression + ",");
                    }
                    Line(sb, indent + 3, "};");
                }

                var addMethod = operation.Kind switch
                {
                    GrpcMethodKind.ServerStreaming => "AddServerStreamingMethod",
                    GrpcMethodKind.ClientStreaming => "AddClientStreamingMethod",
                    GrpcMethodKind.DuplexStreaming => "AddDuplexStreamingMethod",
                    _ => "AddUnaryMethod",
                };
                var delegateType = operation.Kind switch
                {
                    GrpcMethodKind.ServerStreaming => "ServerStreamingServerMethod",
                    GrpcMethodKind.ClientStreaming => "ClientStreamingServerMethod",
                    GrpcMethodKind.DuplexStreaming => "DuplexStreamingServerMethod",
                    _ => "UnaryServerMethod",
                };
                // the three-arity server-method delegates live in Grpc.AspNetCore.Server.Model, not
                // Grpc.Core - Grpc.Core's own are two-arity, with no TService
                Line(sb, indent + 3, $"context.{addMethod}<{operation.RequestTypeFullName}, {operation.ResponseTypeFullName}>("
                    + $"__op, __meta, new global::Grpc.AspNetCore.Server.Model.{delegateType}<{impl}, "
                    + $"{operation.RequestTypeFullName}, {operation.ResponseTypeFullName}>({ServerHandlerName(operation)}));");
                Line(sb, indent + 2, "}");
                Line(sb, indent + 2, "catch (global::System.Exception __ex)");
                Line(sb, indent + 2, "{");
                Line(sb, indent + 3, $"throw new global::System.InvalidOperationException(\"Failed to bind '\" + {operationLiteral}"
                    + $" + \"' on \" + typeof({contract.InterfaceFullName}).FullName + \": \" + __ex.Message, __ex);");
                Line(sb, indent + 2, "}");
            }

            Line(sb, indent + 1, "}");

            foreach (var operation in contract.Operations)
            {
                sb.AppendLine();
                EmitServerHandler(sb, indent + 1, impl, operation);
            }

            Line(sb, indent, "}");
        }

        private static string ServerHandlerName(GrpcOperationModel operation) => operation.MethodName + "_Server_" + operation.Kind;

        private static void EmitServerHandler(StringBuilder sb, int indent, string impl, GrpcOperationModel operation)
        {
            var name = ServerHandlerName(operation);
            switch (operation.Kind)
            {
                case GrpcMethodKind.Unary:
                    Line(sb, indent, $"private static global::System.Threading.Tasks.Task<{operation.ResponseTypeFullName}> {name}("
                        + $"{impl} service, {operation.RequestTypeFullName} request, {ServerCallContextTypeName} ctx)");
                    Line(sb, indent, "{");
                    EmitServerContextLocal(sb, indent + 1, operation);
                    EmitServerReturn(sb, indent + 1, operation, ServiceCall(operation, "request"));
                    Line(sb, indent, "}");
                    break;

                case GrpcMethodKind.ServerStreaming:
                    Line(sb, indent, $"private static global::System.Threading.Tasks.Task {name}("
                        + $"{impl} service, {operation.RequestTypeFullName} request, "
                        + $"global::Grpc.Core.IServerStreamWriter<{operation.ResponseTypeFullName}> writer, {ServerCallContextTypeName} ctx)");
                    Line(sb, indent, "{");
                    EmitServerContextLocal(sb, indent + 1, operation);
                    if (operation.ResponseShape is GrpcResultShape.TaskStream or GrpcResultShape.ValueTaskStream)
                    {
                        // a byte stream is written by Reshape.WriteStream, which is not generic and takes
                        // Task<Stream> - so a ValueTask<Stream> is converted, exactly as ServerInvokerLookup
                        // does with ToTaskT. writeTrailer: true matches the runtime, which always sends the
                        // total-length trailer even though the client does not demand it.
                        var source = ServiceCall(operation, "request")
                            + (operation.ResponseShape == GrpcResultShape.ValueTaskStream ? ".AsTask()" : "");
                        Line(sb, indent + 1, $"return {ReshapeTypeName}.WriteStream({source}, writer, ctx, true);");
                    }
                    else
                    {
                        Line(sb, indent + 1, $"return {ReshapeTypeName}.WriteTo<{operation.ResponseTypeFullName}>("
                            + $"{ServiceCall(operation, "request")}, writer, ctx.CancellationToken);");
                    }
                    Line(sb, indent, "}");
                    break;

                case GrpcMethodKind.ClientStreaming:
                    Line(sb, indent, $"private static global::System.Threading.Tasks.Task<{operation.ResponseTypeFullName}> {name}("
                        + $"{impl} service, global::Grpc.Core.IAsyncStreamReader<{operation.RequestTypeFullName}> reader, {ServerCallContextTypeName} ctx)");
                    Line(sb, indent, "{");
                    EmitServerContextLocal(sb, indent + 1, operation);
                    EmitRequestStreamLocal(sb, indent + 1, operation);
                    EmitServerReturn(sb, indent + 1, operation, ServiceCall(operation, "seq"));
                    Line(sb, indent, "}");
                    break;

                case GrpcMethodKind.DuplexStreaming:
                    Line(sb, indent, $"private static global::System.Threading.Tasks.Task {name}("
                        + $"{impl} service, global::Grpc.Core.IAsyncStreamReader<{operation.RequestTypeFullName}> reader, "
                        + $"global::Grpc.Core.IServerStreamWriter<{operation.ResponseTypeFullName}> writer, {ServerCallContextTypeName} ctx)");
                    Line(sb, indent, "{");
                    EmitServerContextLocal(sb, indent + 1, operation);
                    EmitRequestStreamLocal(sb, indent + 1, operation);
                    Line(sb, indent + 1, $"return {ReshapeTypeName}.WriteTo<{operation.ResponseTypeFullName}>("
                        + $"{ServiceCall(operation, "seq")}, writer, ctx.CancellationToken);");
                    Line(sb, indent, "}");
                    break;
            }
        }

        private static void EmitServerContextLocal(StringBuilder sb, int indent, GrpcOperationModel operation)
        {
            switch (operation.Context)
            {
                case GrpcContextKind.CallContext:
                    Line(sb, indent, $"var __cc = new {CallContextTypeName}(service, ctx);");
                    break;
                case GrpcContextKind.CancellationToken:
                    Line(sb, indent, "var __ct = ctx.CancellationToken;");
                    break;
            }
        }

        private static void EmitRequestStreamLocal(StringBuilder sb, int indent, GrpcOperationModel operation)
            => Line(sb, indent, $"var seq = {ReshapeTypeName}.AsAsyncEnumerable<{operation.RequestTypeFullName}>(reader, ctx.CancellationToken);");

        /// <summary>
        /// Adapt whatever the service method returns to the <c>Task&lt;TResponse&gt;</c> the binder wants.
        /// </summary>
        private static void EmitServerReturn(StringBuilder sb, int indent, GrpcOperationModel operation, string call)
        {
            switch (operation.ResponseShape)
            {
                case GrpcResultShape.Task when operation.VoidResponse:
                    Line(sb, indent, $"return {ReshapeTypeName}.EmptyTask({call});");
                    break;
                case GrpcResultShape.Task:
                    Line(sb, indent, $"return {call};");
                    break;
                case GrpcResultShape.ValueTask when operation.VoidResponse:
                    Line(sb, indent, $"return {ReshapeTypeName}.EmptyValueTask({call});");
                    break;
                case GrpcResultShape.ValueTask:
                    Line(sb, indent, $"return {call}.AsTask();");
                    break;
                case GrpcResultShape.Sync when operation.VoidResponse:
                    Line(sb, indent, $"{call};");
                    Line(sb, indent, $"return {EmptyTypeName}.InstanceTask;");
                    break;
                case GrpcResultShape.Sync:
                    Line(sb, indent, $"return global::System.Threading.Tasks.Task.FromResult({call});");
                    break;
                default:
                    Line(sb, indent, "throw new global::System.NotSupportedException(\"Unsupported response shape\");");
                    break;
            }
        }

        private static string ServiceCall(GrpcOperationModel operation, string requestExpression)
        {
            var args = new List<string>(2);
            if (!operation.VoidRequest) args.Add(requestExpression);
            switch (operation.Context)
            {
                case GrpcContextKind.CallContext: args.Add("__cc"); break;
                case GrpcContextKind.CancellationToken: args.Add("__ct"); break;
            }
            return "service." + operation.MethodName + "(" + string.Join(", ", args) + ")";
        }

        // -------- registration --------

        /// <summary>
        /// The one line the consumer writes on the server, generated into their own assembly.
        /// </summary>
        /// <remarks>
        /// Deliberately <c>AddGrpc()</c> and not <c>AddCodeFirstGrpc()</c>: the latter registers the
        /// reflection-and-Expression.Compile provider, which would bind every contract a second time.
        /// This is the non-magic half - a one-time call in Program.cs that you can read - which is why
        /// no interceptor is proposed for it.
        /// </remarks>
        private static void EmitRegistration(StringBuilder sb, int indent, GrpcModelPlan plan)
        {
            Line(sb, indent, GeneratedCodeAttribute);
            Line(sb, indent, $"internal static class {plan.TypeName}ServiceCollectionExtensions");
            Line(sb, indent, "{");
            Line(sb, indent + 1, $"/// <summary>Registers the build-time gRPC bindings generated for <see cref=\"{plan.TypeName}\"/>.</summary>");
            Line(sb, indent + 1, "internal static global::Grpc.AspNetCore.Server.IGrpcServerBuilder "
                + $"{plan.RegistrationMethodName}(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
            Line(sb, indent + 1, "{");
            Line(sb, indent + 2, "var __builder = global::Microsoft.Extensions.DependencyInjection.GrpcServicesExtensions.AddGrpc(services);");
            Line(sb, indent + 2, $"{BinderConfigurationTypeName} __cfg = {plan.TypeName}.Instance;");

            // Also register the factory as a service, so anything resolving a ClientFactory from the
            // container gets this one. That is the seam AddCodeFirstGrpcClient uses - its clients call
            // services.GetService<ClientFactory>() - so a project calling this method gets DI-registered
            // clients on the build-time proxies for free, with no second step to remember.
            //
            // TryAddSingleton, not TryAddEnumerable: this is one service, not a set. TryAddEnumerable is
            // right for the IServiceMethodProvider registrations above, where several coexist, and wrong
            // here. And Try rather than Add, so a consumer who registered their own choice keeps it.
            Line(sb, indent + 2, "global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions"
                + $".TryAddSingleton<{ClientFactoryFullName}>(services, {plan.TypeName}.Instance);");
            foreach (var contract in plan.Contracts)
            {
                if (contract.ImplementationTypeFullName is null) continue;
                var impl = contract.ImplementationTypeFullName;
                Line(sb, indent + 2, "global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddEnumerable(services,");
                Line(sb, indent + 3, "global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Singleton<"
                    + $"global::Grpc.AspNetCore.Server.Model.IServiceMethodProvider<{impl}>>(");
                Line(sb, indent + 4, $"new {plan.TypeName}.{contract.ProviderTypeName}(__cfg)));");
            }
            Line(sb, indent + 2, "return __builder;");
            Line(sb, indent + 1, "}");
            Line(sb, indent, "}");
        }

        // -------- shared --------

        private static void Line(StringBuilder sb, int indent, string value)
            => sb.Append(' ', indent * 4).AppendLine(value);

        /// <summary>
        /// The operation's parameter types as a <c>typeof(...)</c> list, for the exact
        /// <c>GetMethod</c> overload.
        /// </summary>
        private static string ParameterTypeOfs(GrpcOperationModel operation)
        {
            var sb = new StringBuilder();
            foreach (var parameter in operation.Parameters)
            {
                if (sb.Length != 0) sb.Append(", ");
                sb.Append("typeof(").Append(parameter.TypeOfDisplay).Append(')');
            }
            return sb.ToString();
        }

        /// <summary>Every payload type on the contract, ordered so field names are stable.</summary>
        private static SortedSet<string> PayloadTypes(GrpcInterfaceModel contract)
        {
            var payloads = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var operation in contract.Operations)
            {
                payloads.Add(operation.RequestTypeFullName);
                payloads.Add(operation.ResponseTypeFullName);
            }
            return payloads;
        }

        private static string MethodType(GrpcOperationModel operation)
            => "global::Grpc.Core.Method<" + operation.RequestTypeFullName + ", " + operation.ResponseTypeFullName + ">";

        private static string ContextParameterName(GrpcOperationModel operation)
        {
            var index = operation.RequestShape == GrpcArgShape.Void ? 0 : 1;
            return operation.Parameters.Length > index ? operation.Parameters[index].Name : "context";
        }

        private static string MethodTypeEnum(GrpcMethodKind kind) => kind switch
        {
            GrpcMethodKind.ServerStreaming => "global::Grpc.Core.MethodType.ServerStreaming",
            GrpcMethodKind.ClientStreaming => "global::Grpc.Core.MethodType.ClientStreaming",
            GrpcMethodKind.DuplexStreaming => "global::Grpc.Core.MethodType.DuplexStreaming",
            _ => "global::Grpc.Core.MethodType.Unary",
        };

        /// <summary>The <c>Reshape</c> helper that adapts the client call to the declared shape.</summary>
        private static string ClientReshapeMethod(GrpcOperationModel operation)
            => (operation.Kind, operation.ResponseShape, operation.VoidResponse) switch
            {
                (GrpcMethodKind.Unary, GrpcResultShape.Task, _) => "UnaryTaskAsync",
                (GrpcMethodKind.Unary, GrpcResultShape.ValueTask, false) => "UnaryValueTaskAsync",
                (GrpcMethodKind.Unary, GrpcResultShape.ValueTask, true) => "UnaryValueTaskAsyncVoid",
                (GrpcMethodKind.Unary, GrpcResultShape.Sync, false) => "UnarySync",
                (GrpcMethodKind.Unary, GrpcResultShape.Sync, true) => "UnarySyncVoid",
                // the byte-stream shapes take their own Reshape helpers; both are server-streaming
                // calls of BytesValue, so they must be matched before the general server-streaming arm
                (GrpcMethodKind.ServerStreaming, GrpcResultShape.TaskStream, _) => "ServerByteStreamingTaskAsync",
                (GrpcMethodKind.ServerStreaming, GrpcResultShape.ValueTaskStream, _) => "ServerByteStreamingValueTaskAsync",
                (GrpcMethodKind.ServerStreaming, _, _) => "ServerStreamingAsync",
                (GrpcMethodKind.ClientStreaming, GrpcResultShape.Task, _) => "ClientStreamingTaskAsync",
                (GrpcMethodKind.ClientStreaming, GrpcResultShape.ValueTask, false) => "ClientStreamingValueTaskAsync",
                (GrpcMethodKind.ClientStreaming, GrpcResultShape.ValueTask, true) => "ClientStreamingValueTaskAsyncVoid",
                (GrpcMethodKind.DuplexStreaming, _, _) => "DuplexAsync",
                _ => "UnaryTaskAsync",
            };

        private static string Literal(string value)
        {
            var sb = new StringBuilder(value.Length + 2).Append('"');
            foreach (var c in value)
            {
                switch (c)
                {
                    case '\\': sb.Append("\\\\"); break;
                    case '"': sb.Append("\\\""); break;
                    default: sb.Append(c); break;
                }
            }
            return sb.Append('"').ToString();
        }
