        private static void EmitServerBindings(StringBuilder sb, GrpcInterfaceModel contract)
        {
            sb.Append("    ").AppendLine(GeneratedCodeAttribute);
            sb.AppendLine("    [global::System.Diagnostics.DebuggerNonUserCode]");
            sb.Append("    public static class ").AppendLine(contract.ServerBindingsTypeName);
            sb.AppendLine("    {");

            sb.Append("        public static int Bind<TService>(").Append(ServerMethodBinderTypeName).AppendLine("<TService> binder)");
            sb.Append("            where TService : class, ").AppendLine(contract.InterfaceFullName);
            sb.AppendLine("        {");
            sb.AppendLine("            var __cfg = binder.Configuration;");
            sb.AppendLine("            int count = 0;");

            foreach (var operation in contract.Operations)
            {
                var sameType = string.Equals(operation.RequestTypeFullName, operation.ResponseTypeFullName, StringComparison.Ordinal);
                var operationLiteral = Literal(operation.MethodName);

                // Marshallers are resolved per operation inside a try/catch so that one unmarshallable
                // payload can't take down the whole contract, and so the failure names the operation:
                // the host's startup log then points straight at the broken member.
                sb.AppendLine("            try");
                sb.AppendLine("            {");
                sb.Append("                var __m_req = __cfg.GetMarshaller<").Append(operation.RequestTypeFullName).AppendLine(">();");
                if (!sameType)
                {
                    sb.Append("                var __m_resp = __cfg.GetMarshaller<").Append(operation.ResponseTypeFullName).AppendLine(">();");
                }
                sb.Append("                var __op = new ").Append(MethodType(operation)).Append("(")
                    .Append(MethodTypeEnum(operation.Kind)).Append(", ")
                    .Append(Literal(contract.ServiceName)).Append(", ")
                    .Append(Literal(operation.OperationName)).Append(", __m_req, ")
                    .Append(sameType ? "__m_req" : "__m_resp").AppendLine(");");

                sb.Append("                binder.").Append(operation.Kind switch
                {
                    GrpcMethodKind.ServerStreaming => "AddServerStreamingMethod",
                    GrpcMethodKind.ClientStreaming => "AddClientStreamingMethod",
                    GrpcMethodKind.DuplexStreaming => "AddDuplexStreamingMethod",
                    _ => "AddUnaryMethod",
                })
                    .Append("<").Append(operation.RequestTypeFullName).Append(", ").Append(operation.ResponseTypeFullName).Append(">(__op, ")
                    // the declaring interface, since the metadata lookup is a GetMethod that doesn't
                    // search base interfaces
                    .Append("binder.GetMetadata(typeof(").Append(operation.DeclaringInterfaceFullName).Append("), ").Append(operationLiteral).Append("), ")
                    .Append(ServerHandlerName(operation)).AppendLine("<TService>);");
                sb.AppendLine("                count++;");
                sb.AppendLine("            }");
                sb.AppendLine("            catch (global::System.Exception __ex)");
                sb.AppendLine("            {");
                sb.Append("                throw new global::System.InvalidOperationException(\"Failed to bind '\" + ")
                    .Append(operationLiteral).Append(" + \"' on \" + typeof(").Append(contract.InterfaceFullName)
                    .AppendLine(").FullName + \": \" + __ex.Message, __ex);");
                sb.AppendLine("            }");
            }

            sb.AppendLine("            return count;");
            sb.AppendLine("        }");
            sb.AppendLine();

            foreach (var operation in contract.Operations)
            {
                EmitServerHandler(sb, contract, operation);
            }

            sb.AppendLine("    }");
        }

        private static string ServerHandlerName(GrpcOperationModel operation) => operation.MethodName + "_Server_" + operation.Kind;

        private static void EmitServerHandler(StringBuilder sb, GrpcInterfaceModel contract, GrpcOperationModel operation)
        {
            const string ServerCallContext = "global::Grpc.Core.ServerCallContext";
            var name = ServerHandlerName(operation);

            switch (operation.Kind)
            {
                case GrpcMethodKind.Unary:
                    sb.Append("        private static global::System.Threading.Tasks.Task<").Append(operation.ResponseTypeFullName)
                        .Append("> ").Append(name).Append("<TService>(TService service, ").Append(operation.RequestTypeFullName)
                        .Append(" request, ").Append(ServerCallContext).AppendLine(" ctx)");
                    sb.Append("            where TService : class, ").AppendLine(contract.InterfaceFullName);
                    sb.AppendLine("        {");
                    EmitServerContextLocal(sb, operation);
                    EmitServerReturn(sb, operation, ServiceCall(operation, "request"));
                    sb.AppendLine("        }");
                    break;

                case GrpcMethodKind.ServerStreaming:
                    sb.Append("        private static global::System.Threading.Tasks.Task ").Append(name)
                        .Append("<TService>(TService service, ").Append(operation.RequestTypeFullName)
                        .Append(" request, global::Grpc.Core.IServerStreamWriter<").Append(operation.ResponseTypeFullName)
                        .Append("> writer, ").Append(ServerCallContext).AppendLine(" ctx)");
                    sb.Append("            where TService : class, ").AppendLine(contract.InterfaceFullName);
                    sb.AppendLine("        {");
                    EmitServerContextLocal(sb, operation);
                    sb.Append("            return ").Append(ReshapeTypeName).Append(".WriteTo<").Append(operation.ResponseTypeFullName)
                        .Append(">(").Append(ServiceCall(operation, "request")).AppendLine(", writer, ctx.CancellationToken);");
                    sb.AppendLine("        }");
                    break;

                case GrpcMethodKind.ClientStreaming:
                    sb.Append("        private static global::System.Threading.Tasks.Task<").Append(operation.ResponseTypeFullName)
                        .Append("> ").Append(name).Append("<TService>(TService service, global::Grpc.Core.IAsyncStreamReader<")
                        .Append(operation.RequestTypeFullName).Append("> reader, ").Append(ServerCallContext).AppendLine(" ctx)");
                    sb.Append("            where TService : class, ").AppendLine(contract.InterfaceFullName);
                    sb.AppendLine("        {");
                    EmitServerContextLocal(sb, operation);
                    EmitRequestStreamLocal(sb, operation);
                    EmitServerReturn(sb, operation, ServiceCall(operation, "seq"));
                    sb.AppendLine("        }");
                    break;

                case GrpcMethodKind.DuplexStreaming:
                    sb.Append("        private static global::System.Threading.Tasks.Task ").Append(name)
                        .Append("<TService>(TService service, global::Grpc.Core.IAsyncStreamReader<").Append(operation.RequestTypeFullName)
                        .Append("> reader, global::Grpc.Core.IServerStreamWriter<").Append(operation.ResponseTypeFullName)
                        .Append("> writer, ").Append(ServerCallContext).AppendLine(" ctx)");
                    sb.Append("            where TService : class, ").AppendLine(contract.InterfaceFullName);
                    sb.AppendLine("        {");
                    EmitServerContextLocal(sb, operation);
                    EmitRequestStreamLocal(sb, operation);
                    sb.Append("            return ").Append(ReshapeTypeName).Append(".WriteTo<").Append(operation.ResponseTypeFullName)
                        .Append(">(").Append(ServiceCall(operation, "seq")).AppendLine(", writer, ctx.CancellationToken);");
                    sb.AppendLine("        }");
                    break;
            }
            sb.AppendLine();
        }

        private static void EmitServerContextLocal(StringBuilder sb, GrpcOperationModel operation)
        {
            switch (operation.Context)
            {
                case GrpcContextKind.CallContext:
                    sb.Append("            var __cc = new ").Append(CallContextTypeName).AppendLine("(service, ctx);");
                    break;
                case GrpcContextKind.CancellationToken:
                    sb.AppendLine("            var __ct = ctx.CancellationToken;");
                    break;
            }
        }

        private static void EmitRequestStreamLocal(StringBuilder sb, GrpcOperationModel operation)
        {
            sb.Append("            var seq = ").Append(ReshapeTypeName).Append(".AsAsyncEnumerable<")
                .Append(operation.RequestTypeFullName).AppendLine(">(reader, ctx.CancellationToken);");
        }

        /// <summary>
        /// Adapt whatever the service method returns to the <c>Task&lt;TResponse&gt;</c> the binder wants.
        /// </summary>
        private static void EmitServerReturn(StringBuilder sb, GrpcOperationModel operation, string call)
        {
            switch (operation.ResponseShape)
            {
                case GrpcResultShape.Task when operation.VoidResponse:
                    sb.Append("            return ").Append(ReshapeTypeName).Append(".EmptyTask(").Append(call).AppendLine(");");
                    break;
                case GrpcResultShape.Task:
                    sb.Append("            return ").Append(call).AppendLine(";");
                    break;
                case GrpcResultShape.ValueTask when operation.VoidResponse:
                    sb.Append("            return ").Append(ReshapeTypeName).Append(".EmptyValueTask(").Append(call).AppendLine(");");
                    break;
                case GrpcResultShape.ValueTask:
                    sb.Append("            return ").Append(call).AppendLine(".AsTask();");
                    break;
                case GrpcResultShape.Sync when operation.VoidResponse:
                    sb.Append("            ").Append(call).AppendLine(";");
                    sb.Append("            return ").Append(EmptyTypeName).AppendLine(".InstanceTask;");
                    break;
                case GrpcResultShape.Sync:
                    sb.Append("            return global::System.Threading.Tasks.Task.FromResult(").Append(call).AppendLine(");");
                    break;
                default:
                    sb.AppendLine("            throw new global::System.NotSupportedException(\"Unsupported response shape\");");
                    break;
            }
        }

        private static string ServiceCall(GrpcOperationModel operation, string requestExpression)
        {
            var args = new List<string>(2);
            if (!operation.VoidRequest) args.Add(requestExpression);
            switch (operation.Context)
            {
                case GrpcContextKind.CallContext: args.Add("__cc"); break;
                case GrpcContextKind.CancellationToken: args.Add("__ct"); break;
            }
            return "service." + operation.MethodName + "(" + string.Join(", ", args) + ")";
        }

