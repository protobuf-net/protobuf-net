extern alias gpb;

using BenchmarkDotNet.Attributes;
using ProtoBuf;
using System;
using System.IO;
using System.Linq;
using System.Text;
using Model = ProtoBuf.Nano.Bench.DescriptorModel; // 'Nano' would be shadowed by the ProtoBuf.Nano namespace
using Pbn = Google.Protobuf.Reflection;          // protobuf-net.Reflection's DTOs (legacy row)
using Gpb = gpb::Google.Protobuf.Reflection;     // the Google.Protobuf package (home-turf row)

namespace ProtoBuf.Nano.Bench;

/// <summary>
/// The north-star composite (docs/nano-core.md): descriptor.proto's own descriptor - the payload
/// describes itself - parsed three ways: the real legacy stack (RuntimeTypeModel over
/// protobuf-net.Reflection's DTOs), Google.Protobuf on home turf (its generated parser over its
/// generated DTOs), and the nano raw surface over the hand-written emitted-shape model in
/// DescriptorNano.cs. The payload is generated in setup by protobuf-net.Reflection parsing the
/// embedded descriptor.proto and serializing the result, so it cannot drift from the schema.
///
/// GlobalSetup is the correctness gate: a structural census (entity counts, every string's chars,
/// field-number and path sums, presence-guarded enum sums) must agree across all three object
/// models before any measurement.
/// </summary>
[MemoryDiagnoser]
public class DescriptorParseBenchmarks
{
    private byte[] _data = [];

    [GlobalSetup]
    public void Setup()
    {
        var set = new Pbn.FileDescriptorSet();
        if (!set.Add("google/protobuf/descriptor.proto", includeInOutput: true))
        {
            throw new InvalidOperationException("could not resolve embedded descriptor.proto");
        }
        set.Process();
        var errors = set.GetErrors();
        if (errors.Any(e => e.IsError))
        {
            throw new InvalidOperationException("parse errors: "
                + string.Join("; ", errors.Where(e => e.IsError).Select(e => e.Message)));
        }
        using (var ms = new MemoryStream())
        {
            Serializer.Serialize(ms, set);
            _data = ms.ToArray();
        }
        if (_data.Length < 1024) throw new InvalidOperationException($"implausibly small payload: {_data.Length} bytes");

        var legacy = CensusLegacy(ParseLegacyReal());
        var google = CensusGoogle(ParseGoogleProtobuf());
        var nano = CensusNano(ParseNanoRaw());
        if (legacy != google || google != nano)
        {
            throw new InvalidOperationException(
                $"census disagreement:\nlegacy {legacy}\ngoogle {google}\nnano   {nano}");
        }
        Console.WriteLine($"// payload {_data.Length} bytes; census {nano}");
    }

    // the [Benchmark] methods return object: BDN's autogenerated boilerplate names return types
    // WITHOUT this file's extern alias, so the ambiguous FileDescriptorSet types cannot appear on
    // the public benchmark surface (CS0433 in the generated project otherwise)

    [Benchmark(Baseline = true)]
    public object LegacyReal() => ParseLegacyReal();

    private Pbn.FileDescriptorSet ParseLegacyReal()
        => Serializer.Deserialize<Pbn.FileDescriptorSet>(new ReadOnlyMemory<byte>(_data));

    [Benchmark]
    public object GoogleProtobuf() => ParseGoogleProtobuf();

    private Gpb.FileDescriptorSet ParseGoogleProtobuf()
        => Gpb.FileDescriptorSet.Parser.ParseFrom(_data);

    [Benchmark]
    public object NanoRaw() => ParseNanoRaw();

    private Model.FileDescriptorSet ParseNanoRaw()
    {
        var state = new ReaderState(_data, 0, _data.Length);
        try
        {
            return Model.DescriptorNanoReader.ReadFileDescriptorSet(ref state, null);
        }
        finally
        {
            state.Dispose();
        }
    }

    // ---------------------------------------------------------------- census
    //
    // One accumulator, three walkers - structurally identical, but the DTO types differ per
    // stack so each stack walks its own. Counter meanings are fixed by the Census type; any
    // divergence in structure, names, numbers, paths or comments shifts at least one counter.

    private sealed class Census
    {
        public long Files, StrChars, Messages, Fields, FieldNumberSum, Enums, EnumValues,
            EnumValueNumberSum, Oneofs, Services, Methods, RangeSum, OptionsObjects, BoolTrues,
            ScalarSum, Locations, PathSpanSum, Uninterpreted;

        public override string ToString()
            => $"files={Files} str={StrChars} msg={Messages} fld={Fields} fldNo={FieldNumberSum} " +
               $"enum={Enums} eval={EnumValues} evalNo={EnumValueNumberSum} oneof={Oneofs} " +
               $"svc={Services} mth={Methods} rng={RangeSum} opt={OptionsObjects} bool={BoolTrues} " +
               $"scal={ScalarSum} loc={Locations} path={PathSpanSum} unin={Uninterpreted}";

        public string Value => ToString();
        public static void Chars(Census c, string s) => c.StrChars += s?.Length ?? 0;
    }

    private static string CensusNano(Model.FileDescriptorSet set)
    {
        var c = new Census();
        foreach (var f in set.Files)
        {
            c.Files++;
            Census.Chars(c, f.Name); Census.Chars(c, f.Package); Census.Chars(c, f.Syntax);
            foreach (var d in f.Dependencies) Census.Chars(c, d);
            c.ScalarSum += f.PublicDependencies.Sum(x => (long)x) + f.WeakDependencies.Sum(x => (long)x);
            foreach (var m in f.MessageTypes) Message(c, m);
            foreach (var e in f.EnumTypes) Enum(c, e);
            foreach (var x in f.Extensions) Field(c, x);
            foreach (var s in f.Services)
            {
                c.Services++;
                Census.Chars(c, s.Name);
                if (s.Options is not null) { c.OptionsObjects++; if (s.Options.Deprecated == true) c.BoolTrues++; c.Uninterpreted += s.Options.UninterpretedOptions.Count; }
                foreach (var m in s.Methods)
                {
                    c.Methods++;
                    Census.Chars(c, m.Name); Census.Chars(c, m.InputType); Census.Chars(c, m.OutputType);
                    if (m.ClientStreaming == true) c.BoolTrues++;
                    if (m.ServerStreaming == true) c.BoolTrues++;
                    if (m.Options is not null)
                    {
                        c.OptionsObjects++;
                        if (m.Options.Deprecated == true) c.BoolTrues++;
                        c.ScalarSum += (int)(m.Options.IdempotencyLevel ?? 0);
                        c.Uninterpreted += m.Options.UninterpretedOptions.Count;
                    }
                }
            }
            if (f.Options is { } o)
            {
                c.OptionsObjects++;
                Census.Chars(c, o.JavaPackage); Census.Chars(c, o.JavaOuterClassname);
                Census.Chars(c, o.GoPackage); Census.Chars(c, o.ObjcClassPrefix);
                Census.Chars(c, o.CsharpNamespace); Census.Chars(c, o.SwiftPrefix);
                Census.Chars(c, o.PhpClassPrefix); Census.Chars(c, o.PhpNamespace);
                Census.Chars(c, o.PhpMetadataNamespace); Census.Chars(c, o.RubyPackage);
                if (o.OptimizeFor is { } om) c.ScalarSum += (int)om;
                foreach (var b in new[] { o.JavaMultipleFiles, o.JavaGenerateEqualsAndHash,
                    o.JavaStringCheckUtf8, o.CcGenericServices, o.JavaGenericServices,
                    o.PyGenericServices, o.PhpGenericServices, o.Deprecated, o.CcEnableArenas })
                {
                    if (b == true) c.BoolTrues++;
                }
                c.Uninterpreted += o.UninterpretedOptions.Count;
            }
            if (f.SourceCodeInfo is { } sci)
            {
                foreach (var l in sci.Locations)
                {
                    c.Locations++;
                    c.PathSpanSum += l.Path.Sum(x => (long)x) + l.Span.Sum(x => (long)x);
                    Census.Chars(c, l.LeadingComments); Census.Chars(c, l.TrailingComments);
                    foreach (var s in l.LeadingDetachedComments) Census.Chars(c, s);
                }
            }
        }
        return c.Value;

        static void Message(Census c, Model.DescriptorProto m)
        {
            c.Messages++;
            Census.Chars(c, m.Name);
            foreach (var fd in m.Fields) Field(c, fd);
            foreach (var fd in m.Extensions) Field(c, fd);
            foreach (var n in m.NestedTypes) Message(c, n);
            foreach (var e in m.EnumTypes) Enum(c, e);
            foreach (var od in m.OneofDecls) { c.Oneofs++; Census.Chars(c, od.Name); if (od.Options is not null) c.OptionsObjects++; }
            foreach (var r in m.ExtensionRanges)
            {
                c.RangeSum += (r.Start ?? 0) + (r.End ?? 0);
                if (r.Options is not null) { c.OptionsObjects++; c.Uninterpreted += r.Options.UninterpretedOptions.Count; }
            }
            foreach (var r in m.ReservedRanges) c.RangeSum += (r.Start ?? 0) + (r.End ?? 0);
            foreach (var s in m.ReservedNames) Census.Chars(c, s);
            if (m.Options is { } o)
            {
                c.OptionsObjects++;
                foreach (var b in new[] { o.MessageSetWireFormat, o.NoStandardDescriptorAccessor, o.Deprecated, o.MapEntry })
                {
                    if (b == true) c.BoolTrues++;
                }
                c.Uninterpreted += o.UninterpretedOptions.Count;
            }
        }

        static void Field(Census c, Model.FieldDescriptorProto fd)
        {
            c.Fields++;
            c.FieldNumberSum += fd.Number ?? 0;
            Census.Chars(c, fd.Name); Census.Chars(c, fd.TypeName); Census.Chars(c, fd.Extendee);
            Census.Chars(c, fd.DefaultValue); Census.Chars(c, fd.JsonName);
            if (fd.Label is { } l) c.ScalarSum += (int)l;
            if (fd.Type is { } t) c.ScalarSum += (int)t;
            c.ScalarSum += fd.OneofIndex ?? 0;
            if (fd.Proto3Optional == true) c.BoolTrues++;
            if (fd.Options is { } o)
            {
                c.OptionsObjects++;
                c.ScalarSum += (int)(o.Ctype ?? 0) + (int)(o.Jstype ?? 0);
                foreach (var b in new[] { o.Packed, o.Lazy, o.Deprecated, o.Weak })
                {
                    if (b == true) c.BoolTrues++;
                }
                c.Uninterpreted += o.UninterpretedOptions.Count;
            }
        }

        static void Enum(Census c, Model.EnumDescriptorProto e)
        {
            c.Enums++;
            Census.Chars(c, e.Name);
            foreach (var v in e.Values)
            {
                c.EnumValues++;
                c.EnumValueNumberSum += v.Number ?? 0;
                Census.Chars(c, v.Name);
                if (v.Options is not null) { c.OptionsObjects++; if (v.Options.Deprecated == true) c.BoolTrues++; c.Uninterpreted += v.Options.UninterpretedOptions.Count; }
            }
            foreach (var r in e.ReservedRanges) c.RangeSum += (r.Start ?? 0) + (r.End ?? 0);
            foreach (var s in e.ReservedNames) Census.Chars(c, s);
            if (e.Options is { } o)
            {
                c.OptionsObjects++;
                if (o.AllowAlias == true) c.BoolTrues++;
                if (o.Deprecated == true) c.BoolTrues++;
                c.Uninterpreted += o.UninterpretedOptions.Count;
            }
        }
    }

