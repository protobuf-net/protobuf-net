    [Benchmark(OperationsPerInvoke = 2 * ElementsPerKind)]
    public (long, int, long, string, int, long) NanoRaw() => ParseNanoRaw();

    private (long, int, long, string, int, long) ParseNanoRaw()
    {
        var state = new ReaderState(_data, 0, _data.Length);
        try
        {
            var strings = _strings;
            var children = _children;
            strings.Clear();
            children.Clear();
            long idSum = 0, charSum = 0, childSum = 0;
            uint tag = state.ReadRawTag();
            while (tag != 0)
            {
                switch (tag)
                {
                    // wire-type tolerance by case labels for the varint field, per the convention
                    case (1 << 3) | 0:
                        idSum += unchecked((int)state.ReadRawVarint32());
                        break;
                    case (1 << 3) | 5:
                        idSum += unchecked((int)state.ReadRawFixed32());
                        break;
                    case (1 << 3) | 1:
                        idSum += checked((int)unchecked((long)state.ReadRawFixed64()));
                        break;
                    case (2 << 3) | 2:
                        // the run shape: the tag read IS the loop condition; a miss falls back to
                        // dispatch via continue with the tag already decoded - no Try, no re-decode
                        do
                        {
                            var s = state.ReadRawString();
                            charSum += s.Length;
                            strings.Add(s);
                        } while ((tag = state.ReadRawTag()) == ((2 << 3) | 2));
                        continue;
                    case (3 << 3) | 2:
                        do
                        {
                            var scope = state.PushLengthPrefix();
                            var child = NanoReadChild(ref state, null);
                            state.PopScope(scope);
                            childSum += child.Value;
                            children.Add(child);
                        } while ((tag = state.ReadRawTag()) == ((3 << 3) | 2));
                        continue;
                    case (3 << 3) | 3: // group-framed child: tolerated, non-run (falls to dispatch)
                    {
                        var scope = state.PushGroup((3 << 3) | 4);
                        var child = NanoReadChild(ref state, null);
                        state.PopScope(scope);
                        childSum += child.Value;
                        children.Add(child);
                        break;
                    }
                    default:
                        if (state.IsScopeEnd(tag)) goto done;
                        state.SkipTag(tag);
                        break;
                }
                tag = state.ReadRawTag();
            }
        done:
            return (idSum, strings.Count, charSum,
                strings.Count == 0 ? "" : strings[strings.Count - 1], children.Count, childSum);
        }
        finally
        {
            state.Dispose();
        }
    }

    // the emitted nano shape: value in, value returned, ??= construction inside - a repeated
    // element passes null, so construction happens here exactly as ReadMessage<T>(default) would
    private static Child NanoReadChild(ref ReaderState state, Child value)
    {
        value ??= new Child();
        uint tag;
        while ((tag = state.ReadRawTag()) != 0)
        {
            switch (tag)
            {
                case (1 << 3) | 0:
                    value.Value = unchecked((int)state.ReadRawVarint32());
                    break;
                case (1 << 3) | 5:
                    value.Value = unchecked((int)state.ReadRawFixed32());
                    break;
                case (1 << 3) | 1:
                    value.Value = checked((int)unchecked((long)state.ReadRawFixed64()));
                    break;
                default:
                    if (state.IsScopeEnd(tag)) return value;
                    state.SkipTag(tag);
                    break;
            }
        }
        return value;
    }
}
