using BenchmarkDotNet.Attributes;
using ProtoBuf;
using ProtoBuf.Nano;
using System;
using System.Collections.Generic;
using System.Text;
using ReaderState = ProtoBuf.ProtoReader.State;

namespace ProtoBuf.Nano.Bench;

/// <summary>
/// Repeated fields: 32K strings (field 2) + 32K children (field 3), arranged as runs of
/// <see cref="Run"/> elements separated by a varint (field 1) - Run=1 is fully interleaved
/// (run speculation always misses), Run=8 is run-shaped (speculation pays). The contrast is the
/// measurement: legacy's TryReadFieldHeader miss is a peek that re-decodes at the next header
/// read, while the raw tag-local loop condition hands a miss straight to dispatch with the tag
/// already decoded - no waste on either hit or miss.
///
/// Lists are allocated once and Cleared per parse (capacity retained), so the diagnoser shows the
/// per-element materialization (strings + Child instances - identical across parsers) rather than
/// list-growth noise. GlobalSetup is the correctness gate: all three parsers must agree on
/// (idSum, stringCount, charSum, lastString, childCount, childSum) against expected.
/// </summary>
[MemoryDiagnoser]
public class RepeatedParseBenchmarks
{
    public sealed class Child
    {
        public int Value;
    }

    /// <summary>Elements per run; 1 = fully interleaved, 8 = run-shaped. (Named RunLength rather
    /// than Run: BDN's autogenerated Runnable declares a Run method, and a param named Run fails
    /// the boilerplate build with CS1913.)</summary>
    [Params(1, 8)]
    public int RunLength = 1;

    private const int ElementsPerKind = 32768; // strings and children each; OperationsPerInvoke = both
    private byte[] _data = [];
    private List<string> _strings = [];
    private List<Child> _children = [];
    private (long, int, long, string, int, long) _expected;

    [GlobalSetup]
    public void Setup()
    {
        var rng = new Random(12345);
        var payload = new System.IO.MemoryStream();
        var sb = new StringBuilder();
        long idSum = 0, charSum = 0, childSum = 0;
        string last = "";

        static void WriteVarint(System.IO.MemoryStream s, uint value)
        {
            while (value >= 0x80)
            {
                s.WriteByte((byte)(value | 0x80));
                value >>= 7;
            }
            s.WriteByte((byte)value);
        }

        int records = ElementsPerKind / RunLength;
        for (int r = 0; r < records; r++)
        {
            uint id = (uint)rng.Next(0, 10000);
            idSum += unchecked((int)id);
            payload.WriteByte((1 << 3) | 0); // field 1, varint separator: breaks any run
            WriteVarint(payload, id);

            for (int i = 0; i < RunLength; i++) // the string run
            {
                int chars = rng.Next(0, 17);
                sb.Clear();
                for (int c = 0; c < chars; c++) sb.Append((char)rng.Next(0x20, 0x7F));
                var s = sb.ToString();
                charSum += s.Length;
                last = s;
                var utf8 = Encoding.UTF8.GetBytes(s);
                payload.WriteByte((2 << 3) | 2); // field 2, length-prefixed
                WriteVarint(payload, (uint)utf8.Length);
                payload.Write(utf8, 0, utf8.Length);
            }

            for (int i = 0; i < RunLength; i++) // the child run
            {
                uint v = (uint)rng.Next(0, 128); // 1-byte value => child body is always 2 bytes
                childSum += v;
                payload.WriteByte((3 << 3) | 2); // field 3, length-prefixed child
                payload.WriteByte(2);
                payload.WriteByte((1 << 3) | 0); // child field 1, varint
                payload.WriteByte((byte)v);
            }
        }
        _data = payload.ToArray();
        _strings = new List<string>(ElementsPerKind);
        _children = new List<Child>(ElementsPerKind);
        _expected = (idSum, ElementsPerKind, charSum, last, ElementsPerKind, childSum);

        var legacy = ParseLegacyReal();
        var shim = ParseNanoViaLegacyApi();
        var raw = ParseNanoRaw();
        if (legacy != shim || shim != raw || legacy != _expected)
        {
            throw new InvalidOperationException(
                $"disagreement: legacy {legacy}, shim {shim}, raw {raw}, expected {_expected}");
        }
    }

    [Benchmark(Baseline = true, OperationsPerInvoke = 2 * ElementsPerKind)]
    public (long, int, long, string, int, long) LegacyReal() => ParseLegacyReal();

    private (long, int, long, string, int, long) ParseLegacyReal()
    {
        var state = ProtoReader.State.Create(new ReadOnlyMemory<byte>(_data), model: null);
        try
        {
            var strings = _strings;
            var children = _children;
            strings.Clear();
            children.Clear();
            long idSum = 0, charSum = 0, childSum = 0;
            int field;
            while ((field = state.ReadFieldHeader()) > 0)
            {
                switch (field)
                {
                    case 1:
                        idSum += state.ReadInt32();
                        break;
                    case 2: // the legacy repeated shape: do-while on the look-ahead
                        do
                        {
                            var s = state.ReadString();
                            charSum += s.Length;
                            strings.Add(s);
                        } while (state.TryReadFieldHeader(2));
                        break;
                    case 3:
                        do
                        {
                            var child = new Child();
                            var token = state.StartSubItem();
                            int inner;
                            while ((inner = state.ReadFieldHeader()) > 0)
                            {
                                if (inner == 1) child.Value = state.ReadInt32();
                                else state.SkipField();
                            }
                            state.EndSubItem(token);
                            childSum += child.Value;
                            children.Add(child);
                        } while (state.TryReadFieldHeader(3));
                        break;
                    default:
                        state.SkipField();
                        break;
                }
            }
            return (idSum, strings.Count, charSum,
                strings.Count == 0 ? "" : strings[strings.Count - 1], children.Count, childSum);
        }
        finally
        {
            state.Dispose();
        }
    }

    // the nano internals behind the legacy API - consumer code IDENTICAL to LegacyReal
    [Benchmark(OperationsPerInvoke = 2 * ElementsPerKind)]
    public (long, int, long, string, int, long) NanoViaLegacyApi() => ParseNanoViaLegacyApi();

