using System;
using System.Security.Cryptography;
using System.Text;

namespace ProtoBuf.AotRefGen
{
    /// <summary>
    /// Ties a <c>*.reference.cs</c> to the fixture it was generated from.
    /// </summary>
    /// <remarks>
    /// <para>
    /// A reference is only evidence if it was generated from the input beside it, and the dangerous
    /// direction is an <em>absence</em>: a file that was never re-run and a ref-emit that genuinely
    /// emitted nothing look exactly alike. That has already produced one wrong conclusion, recorded
    /// under "Retracted" in <c>notes/aot-findings.md</c>.
    /// </para>
    /// <para>
    /// Generating a reference needs .NET Framework (persist-to-dll) and so cannot run on Linux, but
    /// <em>checking</em> one is a hash comparison and runs anywhere - which is why this is a stamp
    /// rather than a CI regeneration step.
    /// </para>
    /// <para>
    /// This file is compiled into both AotRefGen and BuildToolsUnitTests, deliberately: two copies of
    /// the normalisation rule that drifted apart would fail every fixture at once, for a reason that
    /// looks like a generator bug and is not.
    /// </para>
    /// </remarks>
    internal static class ReferenceProvenance
    {
        private const string Marker = "input sha256 ";

        /// <summary>
        /// Hashes fixture text with line endings normalised.
        /// </summary>
        /// <remarks>
        /// Normalisation is not optional: this repo round-trips LF and CRLF constantly (git reports it
        /// on nearly every commit), so a raw hash would report drift on a file nobody touched.
        /// </remarks>
        public static string Hash(string text)
        {
            var normalised = text.Replace("\r\n", "\n").Replace("\r", "\n");
            using (var sha = SHA256.Create())
            {
                var bytes = sha.ComputeHash(Encoding.UTF8.GetBytes(normalised));
                // Convert.ToHexString is .NET 5+, and this compiles for net472
                return BitConverter.ToString(bytes).Replace("-", "").ToLowerInvariant();
            }
        }

        /// <summary>The header stamped at the top of a generated reference.</summary>
        public static string Header(string inputFileName, string inputHash)
            => "// <auto-generated>" + Environment.NewLine
            + "// Decompiled from ref-emit by AotRefGen, from " + inputFileName + Environment.NewLine
            + "// " + Marker + inputHash + Environment.NewLine
            + "// Do not edit. After changing that fixture, regenerate on Windows:" + Environment.NewLine
            + "//   dotnet run --project src/AotRefGen" + Environment.NewLine
            + "// </auto-generated>" + Environment.NewLine + Environment.NewLine;

        /// <summary>
        /// The input hash a reference records, or null where it carries no stamp at all.
        /// </summary>
        public static string? ExtractHash(string referenceText)
        {
            var at = referenceText.IndexOf(Marker, StringComparison.Ordinal);
            if (at < 0) return null;

            at += Marker.Length;
            var end = at;
            while (end < referenceText.Length && IsHex(referenceText[end])) end++;
            return end == at ? null : referenceText.Substring(at, end - at);
        }

        private static bool IsHex(char c)
            => (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f');
    }
}
